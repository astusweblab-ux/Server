# -*- coding: utf-8 -*-
"""Сверяет снимки интерфейса со словарями: не осталось ли непереведённых строк.

Использование:
    python сверить_язык.py uk|en [папка со снимками]

Снимки делает `обойти_экраны.py` (папка `снимки`, переопределяется переменной СНИМКИ).
Проверки:
  * словарь знает эту строку и её перевод отличается от русского, а на экране всё ещё
    русский текст — значит строка не обёрнута в л(...);
  * украинский: буквы ЫыЪъЭэЁё (в украинском их не бывает) — точный признак русского текста;
  * английский: кириллица вне имён файлов, папок, служб и значений из словаря.

Цифры и размеры приводятся к «#» перед сравнением, поэтому строки со значениями
(«7 % · вільно 205.4 ГіБ») тоже проверяются.
"""
import io
import json
import os
import re
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ПАПКА = os.environ.get("СНИМКИ") or os.path.join(ЗДЕСЬ, "снимки")
ПЕРЕВОДЫ = os.path.join(ЗДЕСЬ, "переводы")
РУССКИЕ_БУКВЫ = re.compile("[ЫыЪъЭэЁё]")
КИРИЛЛИЦА = re.compile("[А-Яа-яЁёІіЇїЄєҐґ]")


def переводы():
    итог = {}
    for имя in sorted(os.listdir(ПЕРЕВОДЫ)):
        if имя.endswith(".json"):
            for ключ, значение in json.load(
                    io.open(os.path.join(ПЕРЕВОДЫ, имя), encoding="utf-8")).items():
                итог[ключ] = значение
    return итог


def строки(язык):
    if not os.path.isdir(ПАПКА):
        return []
    итог = []
    for имя in sorted(os.listdir(ПАПКА)):
        if имя.startswith(язык + "_") and имя.endswith("_тексты.txt"):
            путь = os.path.join(ПАПКА, имя)
            for с in io.open(путь, encoding="utf-8").read().splitlines():
                с = с.strip()
                if с and с not in итог:
                    итог.append(с)
    return итог


def норма(текст):
    """Ключ сравнения: цифры → «#», пробелы схлопнуты."""
    return re.sub(r"\s+", " ", re.sub(r"\d+", "#", текст)).strip().lower()


def имена(словарь, язык):
    """Ключи, которые и в переводе остаются как есть: имена файлов, служб, значения."""
    return set(ключ for ключ, значение in словарь.items()
               if значение.get(язык) == ключ)


def без_имён(строка):
    """Имена файлов, папок и служб пишутся одинаково на всех языках («экспорт», /var/log)."""
    return re.sub(r"«[^»]*»", " ", строка)


def техническое(строка, словарь, язык):
    """В английском кириллица допустима в именах файлов, папок и служб."""
    без_кавычек = без_имён(строка)
    имена_ключей = имена(словарь, язык)
    for слово in re.findall(r"[А-Яа-яЁёІіЇїЄєҐґ][\w./-]*", без_кавычек):
        if слово in имена_ключей:
            continue
        if re.search(r"[._/0-9]", слово):
            continue
        return False
    return True


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in ("uk", "en"):
        print("укажите язык: uk или en")
        return 2
    язык = sys.argv[1]
    словарь = переводы()
    русские = set(строки("ru"))
    свои = строки(язык)
    # Шаблоны, которые на этом языке обязаны выглядеть иначе, чем по-русски.
    ждут_перевода = {}
    for ключ, значение in словарь.items():
        перевод = значение.get(язык)
        if перевод and перевод != ключ:
            ждут_перевода[норма(ключ)] = перевод
    беды = []
    for строка in свои:
        if язык == "uk" and РУССКИЕ_БУКВЫ.search(без_имён(строка)) and строка not in словарь:
            беды.append(("русские буквы", строка))
            continue
        if норма(строка) in ждут_перевода and строка in русские:
            беды.append(("не переведено: %s" % ждут_перевода[норма(строка)], строка))
            continue
        if язык == "en" and КИРИЛЛИЦА.search(строка) and not техническое(строка, словарь, язык):
            беды.append(("кириллица в английском", строка))
    print("%s: строк %d, подозрительных %d" % (язык, len(свои), len(беды)))
    for причина, строка in беды:
        print("  [%s] %s" % (причина, строка))
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(main())

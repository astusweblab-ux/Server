# -*- coding: utf-8 -*-
"""Инструменты локализации: сканирование исходников, проверка полноты, сборка словарей."""
import io, json, os, re, sys, collections

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
АНДРОИД = os.path.dirname(ЗДЕСЬ)
КОРЕНЬ = os.path.join(АНДРОИД, "app", "src", "main", "java", "ru", "serverastus", "monitor")
ПЕРЕВОДЫ = os.path.join(ЗДЕСЬ, "переводы")
ИНВЕНТАРЬ = os.path.join(ЗДЕСЬ, "строки.json")
ВЫХОД = КОРЕНЬ

РЕ_Л = re.compile(r"(?<![A-Za-zА-Яа-яЁё_])[лЛ]\(\s*")


def конец_выражения(текст, индекс_фигурной):
    """Индекс за закрывающей «}» блока ${…}: вложенные строки и скобки учитываются."""
    глубина = 0
    и = индекс_фигурной
    n = len(текст)
    while и < n:
        с = текст[и]
        if с == '"':
            и += 1
            while и < n and текст[и] != '"':
                и += 2 if текст[и] == "\\" else 1
            и += 1
            continue
        if с == "{":
            глубина += 1
        elif с == "}":
            глубина -= 1
            if глубина == 0:
                return и + 1
        и += 1
    return n


def конец_литерала(текст, позиция):
    """Индекс за закрывающей кавычкой обычного литерала — с учётом ${…} внутри."""
    и = позиция + 1
    n = len(текст)
    while и < n:
        с = текст[и]
        if с == "\\":
            и += 2
            continue
        if с == "\n":
            return n if и + 1 > n else и + 1
        if с == "$" and текст[и + 1:и + 2] == "{":
            и = конец_выражения(текст, и + 1)
            continue
        if с == '"':
            return и + 1
        и += 1
    return n


def убрать_комментарии(текст):
    """Заменяет комментарии пробелами, сохраняя позиции и номера строк."""
    итог = []
    и = 0
    n = len(текст)
    while и < n:
        с = текст[и]
        if с == '"':
            if текст[и:и + 3] == '"""':
                конец = текст.find('"""', и + 3)
                конец = n if конец < 0 else конец + 3
            else:
                конец = конец_литерала(текст, и)
            итог.append(текст[и:конец])
            и = конец
            continue
        if текст[и: и + 2] == "//":
            j = текст.find("\n", и)
            j = n if j < 0 else j
            итог.append(" " * (j - и))
            и = j
            continue
        if текст[и: и + 2] == "/*":
            j = текст.find("*/", и)
            j = n if j < 0 else j + 2
            итог.append("".join(з if з == "\n" else " " for з in текст[и:j]))
            и = j
            continue
        итог.append(с)
        и += 1
    return "".join(итог)


def литералы(код):
    """Возвращает список (позиция, текст_литерала) для строк в двойных кавычках."""
    итог = []
    и = 0
    n = len(код)
    while и < n:
        if код[и] == '"':
            if код[и:и + 3] == '"""':
                конец = код.find('"""', и + 3)
                if конец < 0:
                    break
                сырое = код[и + 3:конец]
                значение = сырое.replace("${'$'}", "$")
                итог.append((и, значение, True))
                и = конец + 3
                continue
            конец = конец_литерала(код, и)
            буфер = []
            j = и + 1
            while j < конец - 1:
                if код[j] == "\\":
                    эск = код[j + 1]
                    буфер.append({"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "$": "$", "'": "'"}.get(эск, эск))
                    j += 2
                    continue
                буфер.append(код[j])
                j += 1
            итог.append((и, "".join(буфер).replace("${'$'}", "$"), False))
            и = конец
            continue
        и += 1
    return итог


def файлы(корень=КОРЕНЬ):
    итог = []
    for папка, _, имена in os.walk(корень):
        for имя in sorted(имена):
            if имя.endswith(".kt"):
                итог.append(os.path.join(папка, имя))
    return итог


def относительный(путь, корень):
    return os.path.relpath(путь, корень).replace("\\", "/")


def прочитать(путь):
    with io.open(путь, encoding="utf-8") as f:
        return f.read()


def шаблоны_л(путь):
    """Все шаблоны, переданные первым аргументом в л(...)."""
    код = убрать_комментарии(прочитать(путь))
    итог = []
    for совпадение in РЕ_Л.finditer(код):
        начало = совпадение.end()
        if код[начало] != '"':
            continue
        if код[начало:начало + 3] == '"""':
            конец = код.find('"""', начало + 3)
            if конец < 0:
                continue
            итог.append(код[начало + 3:конец].replace("${'$'}", "$"))
            continue
        j = начало + 1
        буфер = []
        предел = конец_литерала(код, начало) - 1
        while j < предел:
            if код[j] == "\\":
                эск = код[j + 1]
                буфер.append({"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "$": "$"}.get(эск, эск))
                j += 2
                continue
            буфер.append(код[j])
            j += 1
        итог.append("".join(буфер).replace("${'$'}", "$"))
    return итог


def сканировать():
    данные = {}
    for путь in файлы():
        код = убрать_комментарии(прочитать(путь))
        записи = []
        for позиция, значение, _ in литералы(код):
            if re.search(r"[А-Яа-яЁёІіЇїЄєҐґ]", значение):
                строка = код.count("\n", 0, позиция) + 1
                записи.append({"line": строка, "text": значение})
        данные[относительный(путь, КОРЕНЬ)] = записи
    return данные


def загрузить_переводы(сторона="новые"):
    итог = {}
    конфликты = []
    каталог = ПЕРЕВОДЫ
    for имя in sorted(os.listdir(каталог)):
        if not имя.endswith(".json"):
            continue
        путь = os.path.join(каталог, имя)
        try:
            данные = json.load(io.open(путь, encoding="utf-8"))
        except Exception as ошибка:
            print("!! %s: %s" % (имя, ошибка))
            continue
        print("%-16s %4d записей" % (имя, len(данные)))
        for ключ, значение in данные.items():
            uk = значение.get("uk")
            en = значение.get("en")
            if ключ in итог and (итог[ключ]["uk"] != uk or итог[ключ]["en"] != en):
                конфликты.append((ключ, итог[ключ], {"uk": uk, "en": en}, имя))
                continue
            итог[ключ] = {"uk": uk, "en": en}
    return итог, конфликты


def плейсхолдеры(текст):
    return sorted(set(re.findall(r"\{(\d+)\}", текст or "")))


def ложная_кириллица(текст):
    """Кириллица в английском тексте допустима, если это имя файла, папки
    или ключа настройки: «экспорт», метрики.csv, хранить_дней, сервер_история.db."""
    т = re.sub(r"«[^»]*»", "", текст or "")
    т = re.sub(r"[A-Za-z0-9_./-]*[А-Яа-яЁё][\w./-]*\.(csv|db|conf|log|json|txt)", "", т)
    т = re.sub(r"[А-Яа-яЁё_0-9]+_[А-Яа-яЁё_0-9]+", "", т)
    return not re.search(r"[А-Яа-яЁё]", т)


def проверить(итог, шаблоны_из_кода):
    ошибки = []
    for ключ, значение in итог.items():
        for язык in ("uk", "en"):
            текст = значение[язык]
            if not текст or not str(текст).strip():
                ошибки.append("пустой перевод (%s): %s" % (язык, ключ))
                continue
            if плейсхолдеры(ключ) != плейсхолдеры(текст):
                ошибки.append("не совпали заполнители (%s): %s <> %s" % (язык, ключ, текст))
        if not ложная_кириллица(значение["en"]):
            ошибки.append("кириллица в английском: %s -> %s" % (ключ, значение["en"]))
        if re.search(r"\{[3-9]\}|\(n\)", значение["uk"] or ""):
            pass
    нет = [ш for ш in шаблоны_из_кода if ш not in итог]
    return ошибки, нет


def кот(текст):
    замена = {"\\": "\\\\", '"': '\\"', "$": "\\$", "\n": "\\n", "\t": "\\t", "\r": "\\r"}
    return '"' + "".join(замена.get(с, с) for с in текст) + '"'


def куски(элементы, размер):
    for и in range(0, len(элементы), размер):
        yield элементы[и:и + размер]


def сгенерировать(итог, шаблоны_из_кода):
    каталог = os.path.join(ВЫХОД, "данные", "локаль")
    if not os.path.isdir(каталог):
        os.makedirs(каталог)
    for имя in os.listdir(каталог):
        if имя.endswith(".kt"):
            os.remove(os.path.join(каталог, имя))

    ключи = sorted(итог.keys())
    части = collections.defaultdict(list)
    for язык, суффикс in (("uk", "Украинский"), ("en", "Английский")):
        for номер, группа in enumerate(куски(ключи, 200), 1):
            имя = "Часть%s%d" % (суффикс, номер)
            строки = ["package ru.serverastus.monitor.данные.локаль", "", "// Сгенерировано: %d строк словаря (фрагмент %d)." % (len(группа), номер), "internal val %s: Map<String, String> = mapOf(" % имя]
            тело = []
            for ключ in группа:
                тело.append("    %s to %s," % (кот(ключ), кот(итог[ключ][язык])))
            строки.append("\n".join(тело))
            строки.append(")")
            with io.open(os.path.join(каталог, "Часть%s%d.kt" % (суффикс, номер)), "w", encoding="utf-8", newline="\n") as f:
                f.write("\n".join(строки) + "\n")
            части[язык].append("Часть%s%d" % (суффикс, номер))

    for язык, суффикс, файл in (("uk", "Украинский", "ЯзыкУкраинский.kt"), ("en", "Английский", "ЯзыкАнглийский.kt")):
        выражения = ["ru.serverastus.monitor.данные.локаль." + имя for имя in части[язык]]
        txt = ["package ru.serverastus.monitor.данные", "",
               "// Сгенерировано автоматически, вручную не правим — см. «Сборка словарей» в CLAUDE.md.",
               "val %s: Map<String, String> = %s" % (суффикс.upper(), " +\n    ".join(выражения))]
        with io.open(os.path.join(ВЫХОД, "данные", файл), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(txt) + "\n")

    # список всех шаблонов приложения для теста полноты
    строки_шаблонов = sorted(set(шаблоны_из_кода))
    имена = []
    for номер, группа in enumerate(куски(строки_шаблонов, 200), 1):
        имя = "Шаблоны%d" % номер
        строки = ["package ru.serverastus.monitor.данные.локаль", "",
                  "internal val %s: List<String> = listOf(" % имя]
        строки.append("\n".join("    %s," % кот(ш) for ш in группа))
        строки.append(")")
        with io.open(os.path.join(каталог, имя + ".kt"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(строки) + "\n")
        имена.append(имя)
    txt = ["package ru.serverastus.monitor.данные", "",
           "// Сгенерировано автоматически: все шаблоны л(...), встреченные в исходниках.",
           "val СТРОКИ_ПРИЛОЖЕНИЯ: List<String> = %s" % " +\n    ".join(
               "ru.serverastus.monitor.данные.локаль." + имя for имя in имена)]
    with io.open(os.path.join(ВЫХОД, "данные", "СтрокиПриложения.kt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(txt) + "\n")
    print("Словари: uk=%d en=%d, шаблонов=%d, файлов=%d" % (len(итог), len(итог), len(строки_шаблонов), len(части["uk"])))


def main():
    режим = sys.argv[1] if len(sys.argv) > 1 else "проверка"
    if режим == "инвентарь":
        данные = сканировать()
        путь = ИНВЕНТАРЬ
        with io.open(путь, "w", encoding="utf-8", newline="\n") as f:
            json.dump(данные, f, ensure_ascii=False, indent=1)
        print("файлов: %d, литералов: %d" % (len(данные), sum(len(v) for v in данные.values())))
        return
    if режим == "собрать":
        итог, конфликты = загрузить_переводы()
        шаблоны = []
        for путь in файлы():
            шаблоны.extend(шаблоны_л(путь))
        ошибки, нет = проверить(итог, шаблоны)
        if конфликты:
            print("КОНФЛИКТЫ (%d):" % len(конфликты))
            for ключ, было, стало, имя in конфликты[:20]:
                print("  %s | %s vs %s (%s)" % (ключ, было, стало, имя))
        print("словарь: %d записей, шаблонов в коде: %d, без перевода: %d" % (len(итог), len(set(шаблоны)), len(нет)))
        for ш in нет[:40]:
            print("  НЕТ: %s" % ш)
        print("ошибки: %d" % len(ошибки))
        for о in ошибки[:60]:
            print("  " + о)
        if "--записать" in sys.argv:
            сгенерировать(итог, шаблоны)
        return
    if режим == "нет":
        итог, конфликты = загрузить_переводы()
        шаблоны = []
        for путь in файлы():
            шаблоны.extend(шаблоны_л(путь))
        ошибки, нет = проверить(итог, шаблоны)
        путь = os.path.join(ПЕРЕВОДЫ, "нужно_перевода.txt")
        список = sorted(set(нет))
        with io.open(путь, "w", encoding="utf-8", newline="\n") as f:
            for ш in список:
                f.write(ш.replace("\n", "\\n").replace("\t", "\\t") + "\n")
        print("нужно перевести: %d" % len(список))
        return
    if режим == "обёрнутые":
        шаблоны = collections.Counter()
        for путь in файлы():
            for ш in шаблоны_л(путь):
                шаблоны[ш] += 1
        for ш, счёт in шаблоны.most_common():
            if счёт > 1:
                pass
        print("всего обёрнутых строк: %d (уникальных %d)" % (sum(шаблоны.values()), len(шаблоны)))
        return
    if режим == "литералы_без_л":
        шаблоны = set()
        for путь in файлы():
            шаблоны.update(шаблоны_л(путь))
        итог = []
        for путь in файлы():
            код = убрать_комментарии(прочитать(путь))
            for позиция, значение, _ in литералы(код):
                if not re.search(r"[А-Яа-яЁёІіЇїЄєҐґ]", значение):
                    continue
                if значение in шаблоны and РЕ_Л.search(код[max(0, позиция - 400):позиция]) is None:
                    continue
                начало_строки = код.rfind("\n", 0, позиция) + 1
                префикс = код[начало_строки:позиция]
                if РЕ_Л.search(префикс + " ") and префикс.rstrip().endswith(("л(", "Л(")):
                    continue
                строка = код.count("\n", 0, позиция) + 1
                предложение = код[код.rfind("\n", 0, позиция) + 1:код.find("\n", позиция)]
                итог.append((относительный(путь, КОРЕНЬ), строка, значение, предложение.strip()[:160]))
        print("литералов без обёртки: %d" % len(итог))
        for путь, строка, значение, предложение in итог:
            print("%s:%d  %s  ||  %s" % (путь, строка, значение[:120], предложение))
        return
    print("режимы: инвентарь | собрать [--записать] | обёрнутые | литералы_без_л")


if __name__ == "__main__":
    main()

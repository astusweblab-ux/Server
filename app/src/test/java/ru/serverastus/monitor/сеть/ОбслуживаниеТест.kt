        val изменённые = части().toMutableList().also { it[7] = "272\n" }
        val данные = собратьОбслуживание(изменённые, 1L)

        assertEquals(272, данные.удалитьПакетов)

        val совет = оценитьОбслуживание(данные).рекомендации
            .first { it.заголовок.contains("автоматическое удаление") }

        assertEquals("APT считает 272 пакета кандидатами на автоматическое удаление", совет.заголовок)
        assertTrue("Совет не должен быть важной проблемой", !совет.важная)
        assertEquals("sudo apt autoremove --dry-run", совет.команда)
        assertTrue(совет.пояснение.contains("проверить список"))

        val отчёт = отчётОбслуживания(данные, оценитьОбслуживание(данные))
        assertTrue(отчёт.contains("  Кандидатов на автоматическое удаление: 272"))
    }


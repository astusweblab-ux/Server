    private fun текст(имя: String): String {
        val поток = javaClass.getResourceAsStream("/снимки/$имя.txt")
        checkNotNull(поток) { "Не найден снимок ответа сервера: $имя" }
        return поток.use { it.readBytes().toString(Charsets.UTF_8) }
    }

    private fun части(): List<String> = разделить(текст("обслуживание"))

    private fun данные(время: Long = 1_789_586_335L) = собратьОбслуживание(части(), время)


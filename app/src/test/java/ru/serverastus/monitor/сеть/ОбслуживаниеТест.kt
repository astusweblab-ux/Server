    @Test
    fun `каталог логов без журнала сравнивается и с абсолютом, и с долей диска`() {
        fun важность(логи: Long, всего: Long) = важностьОбычныхЛогов(
            Обслуживание(размерЖурнала = 0L, размерЛогов = логи, дискВсего = всего),
        )

        val мебибайт = 1024L * 1024
        val гибибайт = 1024L * мебибайт

        assertEquals("меньше 512 МБ — не замечание", 0, важность(300 * мебибайт, 16 * гибибайт))
        assertEquals("гигабайт на диске в два терабайта — это 0.05 %", 0, важность(гибибайт, 2000 * гибибайт))
        assertEquals("тот же гигабайт на диске в 16 ГБ — уже 6 %", 4, важность(гибибайт, 16 * гибибайт))
        assertEquals(8, важность(4 * гибибайт, 16 * гибибайт))
    }


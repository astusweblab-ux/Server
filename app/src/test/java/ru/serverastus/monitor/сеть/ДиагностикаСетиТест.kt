    private fun снимок(имя: String): String {
        val поток = javaClass.getResourceAsStream("/снимки/$имя.txt")
        checkNotNull(поток) { "Не найден снимок ответа сервера: $имя" }
        return поток.use { it.readBytes().toString(Charsets.UTF_8) }
    }

    private fun части(): List<String> = разделить(снимок("сеть"))

    private fun данные(время: Long = 1_789_586_335L) = собратьДиагностикуСети(части(), время)

    /** Ловит ожидаемую ошибку связи: у JUnit4 нет удобного `assertThrows` для Kotlin. */
    private fun ошибкаСвязи(блок: () -> Unit): ОшибкаСвязи {
        try {
            блок()
        } catch (ошибка: ОшибкаСвязи) {
            return ошибка
        }
        throw AssertionError("Ожидалась ошибка связи")
    }


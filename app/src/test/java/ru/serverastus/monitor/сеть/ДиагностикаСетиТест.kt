    @Test
    fun `оценка реального сервера совпадает с эталонной`() {
        val сеть = данные()
        val оценка = оценитьСеть(сеть)

        assertEquals(83, оценка.балл)
        assertEquals(УРОВЕНЬ_СЕТИ_НОРМАЛЬНО, оценка.уровень)
        assertEquals(0, оценка.рекомендации.count { it.важная })
        assertEquals(9, оценка.рекомендации.size)

        // Накопительная доля отбросов на карте 3.88 %, но опрос всего один: потерь
        // «сейчас» не измерить, поэтому балл за прошлое не снимается — только совет.
        val интерфейс = оценка.рекомендации.first { it.заголовок.contains("enp0s25") }
        assertTrue(!интерфейс.важная)
        assertTrue(интерфейс.заголовок.contains("33999"))
        assertTrue(интерфейс.заголовок.contains("за всё время работы"))
        assertTrue(интерфейс.пояснение.contains("Потерь за один снимок не измерить"))

        val заголовки = оценка.рекомендации.joinToString(" | ") { it.заголовок }
        assertTrue(заголовки.contains("Отброшено SYN"))
        assertTrue(заголовки.contains("Управление перегрузкой TCP: cubic"))
        assertTrue(заголовки.contains("Максимальный буфер приёма"))
        assertTrue(заголовки.contains("медленный старт"))
        assertTrue(заголовки.contains("Очередь SYN"))
        assertTrue(заголовки.contains("TCP-проверка молчащих соединений"))
        assertTrue(заголовки.contains("Закрытие соединения"))
        assertTrue(заголовки.contains("UDP на закрытые порты"))

        // BBR не загружен — совет должен ссылаться на модуль ядра.
        val перегрузка = оценка.рекомендации.first { it.заголовок.contains("Управление перегрузкой") }
        assertTrue(перегрузка.пояснение.contains("BBR не загружен"))
        assertTrue(перегрузка.команда.contains("modprobe tcp_bbr"))
        assertTrue(перегрузка.команда.contains("net.core.default_qdisc=fq"))
    }

    @Test
    fun `потери на интерфейсе без потерь в очереди ядра не винят netdev_max_backlog`() {
        // Живой сервер: net.core.netdev_max_backlog уже 4096, а softnet_stat не
        // показывает ни одной потери — значит очередь ни при чём, и предлагать
        // sysctl с тем же значением 4096 бессмысленно (это и была реальная ошибка).
        // Здесь карта теряет 7.5 % пакетов за опрос, но это кадры без обработчика.
        val сеть = следующийОпрос(отброшеноНаКарте = 30L, принятоНаКарте = 400L, очередьКарты = 4096L)
        val оценка = оценитьСеть(сеть)
        val интерфейс = оценка.рекомендации.first { it.заголовок.contains("enp0s25") }

        assertTrue("потери без перегрузки очереди — не важная проблема", !интерфейс.важная)
        assertTrue(!интерфейс.команда.contains("netdev_max_backlog"))
        assertTrue(интерфейс.команда.contains("tcpdump"))
    }

    @Test
    fun `потери на интерфейсе с перегруженной очередью ядра остаются важными`() {
        val сеть = следующийОпрос(
            отброшеноНаКарте = 30L,
            принятоНаКарте = 400L,
            потерьОчередиЯдра = 500L,

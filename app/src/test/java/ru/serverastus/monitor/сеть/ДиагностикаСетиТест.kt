    /**
     * Второй опрос того же сервера: карте добавляются принятые пакеты и отбросы,
     * поэтому оценка видит потери «сейчас», а не накопительный счётчик.
     */
    private fun следующийОпрос(
        отброшеноНаКарте: Long,
        принятоНаКарте: Long = 400L,
        потерьОчередиЯдра: Long? = 0L,
        очередьКарты: Long? = null,
    ): ДиагностикаСети {
        val прежняя = данные()
        val текущая = прежняя.copy(
            время = прежняя.время + 30L,
            интерфейсы = прежняя.интерфейсы.map { интерфейс ->
                if (интерфейс.имя != "enp0s25") интерфейс
                else интерфейс.copy(
                    принятоПакетов = интерфейс.принятоПакетов + принятоНаКарте,
                    отброшеноПриёме = интерфейс.отброшеноПриёме + отброшеноНаКарте,
                )
            },
            потерьОчередиЯдра = потерьОчередиЯдра,
            параметры = if (очередьКарты == null) прежняя.параметры
            else прежняя.параметры + ("net.core.netdev_max_backlog" to очередьКарты.toString()),
        )
        return добавитьТемп(текущая, прежняя)
    }

    @Test
    fun `отбросы за опрос считаются только при наличии второго опроса`() {
        val первый = данные()
        val карта = первый.интерфейсы[1]

        // Один снимок: судить о потерях нечем.
        assertNull(карта.отбросыЗаОпрос)
        assertTrue(!карта.потериСейчас)

        // Предыдущий опрос есть, но интерфейса в нём не было — тоже нечем.
        val безКарты = добавитьТемп(первый, первый.copy(время = первый.время - 30L, интерфейсы = emptyList()))
        assertNull(безКарты.интерфейсы[1].отбросыЗаОпрос)

        val второй = следующийОпрос(отброшеноНаКарте = 30L, принятоНаКарте = 400L)
        val заОпрос = второй.интерфейсы[1].отбросыЗаОпрос!!
        assertEquals(30L, заОпрос.отброшено)
        assertEquals(400L, заОпрос.принято)
        assertEquals(7.5, заОпрос.доля, 1e-9)
        assertTrue(второй.интерфейсы[1].потериСейчас)

        // Петля в обоих снимках: приростов нет, значит и потерь нет.
        assertEquals(0L, второй.интерфейсы[0].отбросыЗаОпрос!!.отброшено)
        assertTrue(!второй.интерфейсы[0].потериСейчас)
    }

    @Test
    fun `потери за опрос важнее накопительного счётчика`() {
        // 30 отбросов на 400 принятых пакетов за опрос — это 7.5 %: настоящие потери.
        // net.core.netdev_max_backlog у фикстуры 1000, поэтому совет важный и с командой.
        val оценка = оценитьСеть(следующийОпрос(отброшеноНаКарте = 30L, принятоНаКарте = 400L))
        val интерфейс = оценка.рекомендации.first { it.заголовок.contains("enp0s25") }

        assertTrue(интерфейс.важная)
        assertTrue(интерфейс.заголовок.contains("30 за опрос"))
        assertEquals("sysctl -w net.core.netdev_max_backlog=4096", интерфейс.команда)
    }

    @Test
    fun `отбросы за прошлое балл не снимают`() {
        // Второй опрос без единого отброса: накопительные 3.88 % остались, но терять
        // сейчас нечего — балл не снимается, остаётся совет на ноль баллов.
        val сеть = следующийОпрос(отброшеноНаКарте = 0L)
        val оценка = оценитьСеть(сеть)
        val интерфейс = оценка.рекомендации.first { it.заголовок.contains("enp0s25") }

        assertTrue(!интерфейс.важная)
        assertTrue(интерфейс.заголовок.contains("за всё время работы"))
        assertTrue(интерфейс.пояснение.contains("Потерь за последний опрос нет"))
        assertEquals(83, оценка.балл)
        assertEquals(0, оценка.рекомендации.count { it.важная })

        assertTrue(отчётСети(сеть, оценка).contains("за опрос отброшено 0 из 400 пакетов — 0.00 %"))
    }

    /** Второй опрос того же сервера: у карты уже были ошибки линии, к ним добавляется прирост. */
    private fun опросСОшибками(накопленные: Long, прирост: Long): ДиагностикаСети {
        fun снимокОшибок(база: ДиагностикаСети, значение: Long) = база.copy(
            интерфейсы = база.интерфейсы.map { интерфейс ->
                if (интерфейс.имя != "enp0s25") интерфейс else интерфейс.copy(ошибкиПриёма = значение)
            },
        )

        val прежняя = снимокОшибок(данные(), накопленные)
        val текущая = снимокОшибок(прежняя, накопленные + прирост).copy(время = прежняя.время + 30L)
        return добавитьТемп(текущая, прежняя)
    }


/**
 * Проверки нескольких серверов: перенос старого односерверного файла, хранение
 * профилей, изоляция целей и служб, удаление сервера и работа с секретами.
 * Keystore на JVM недоступен, поэтому шифрование подменяется обратимым —
 * хранилище секретов проверяется как обычный компонент.
 */
class НесколькоСерверовТест {

    @get:Rule
    val папка = TemporaryFolder()

    private val обратимое = object : Шифровальщик {
        override fun зашифровать(текст: String): String = ПРЕФИКС + текст.reversed()

        override fun расшифровать(значение: String): String? =
            if (значение.startsWith(ПРЕФИКС)) значение.removePrefix(ПРЕФИКС).reversed() else null

        private val ПРЕФИКС = "тест:"
    }

    @Before
    fun фиксируемРусскийЯзык() {
        Локаль.подменитьЯзык("ru")
    }

    @After
    fun возвращаемСистемныйЯзык() {
        Локаль.подменитьЯзык(null)
    }

    // --- помощники ---------------------------------------------------------

    private fun хранилище(): ХранилищеСекретов =
        ХранилищеСекретов(File(папка.root, "секреты.json"), обратимое)

    /** Создаёт настройки поверх каталога, при необходимости — с готовым config.json. */
    private fun настройки(текстФайла: String? = null): Настройки {
        if (текстФайла != null) File(папка.root, "config.json").writeText(текстФайла, Charsets.UTF_8)
        return Настройки(папка.root, хранилище())
    }

    private fun текстФайла(): String = File(папка.root, "config.json").readText(Charsets.UTF_8)

    private fun jsonФайла(): JSONObject = JSONObject(текстФайла())

    /** Профиль нового сервера в том виде, в каком его собирает мастер. */
    private fun профиль(
        хост: String,
        пароль: String = "",
        сайты: List<String> = emptyList(),
        службы: List<String> = emptyList(),
    ): JSONObject = JSONObject().apply {
        put("хост", хост)
        put("порт", 2222)
        put("пользователь", "aibot")
        put("пароль", пароль)
        put("мастер_пройден", true)
        put("службы", JSONArray(службы))
        put(
            "сайты",
            JSONArray().apply {
                сайты.forEach { put(JSONObject().put("имя", it).put("url", it)) }
            },
        )
    }

    private fun списокСлужб(узел: JSONObject): List<String> {
        val массив = узел.optJSONArray("службы") ?: return emptyList()
        return (0 until массив.length()).map { массив.optString(it) }
    }

    /** Файл прежней версии: один сервер в разделе `сервер_linux`, пароль открытым текстом. */
    private fun старыйФайл(): String = """
        {
          "сервер_linux": {
            "включен": true,
            "хост": "192.168.0.2",
            "порт": 2222,
            "пользователь": "aibot",
            "пароль": "тайна",
            "файл_ключа": "",
            "таймаут_секунд": 20,
            "диск_путь": "/",
            "интервал_секунд": 5,
            "службы": ["ssh", "cron"]
          },
          "сайты": [{"имя": "ASTUS_PROJECT", "url": "http://192.168.0.2"}],
          "порты": [{"имя": "SSH", "хост": "192.168.0.2", "порт": 2222}],
          "сайты_интервал_секунд": 10,
          "порты_интервал_секунд": 15,
          "хранить_дней": 14,
          "мастер_пройден": true,
          "запускать_при_загрузке": true,
          "уведомления": {"локальные": true}
        }
    """.trimIndent()

    // --- перенос старого файла ---------------------------------------------

    @Test
    fun `старый файл с одним сервером превращается в первый профиль`() {
        val настройки = настройки(старыйФайл())

        assertEquals(1, настройки.серверы.size)
        assertEquals("srv1", настройки.активныйId)
        assertEquals("192.168.0.2", настройки.текст(настройки.сервер, "хост"))
        assertEquals(2222, настройки.целое(настройки.сервер, "порт", 22))
        assertEquals("aibot", настройки.текст(настройки.сервер, "пользователь"))
        assertEquals("тайна", настройки.парольСервера())
        assertEquals(1, настройки.сайты().size)
        assertEquals("http://192.168.0.2", настройки.текст(настройки.сайты()[0], "url"))
        assertEquals(1, настройки.порты().size)
        assertEquals(2222, настройки.целое(настройки.порты()[0], "порт", 22))
        assertEquals(listOf("ssh.service", "cron.service"), настройки.службы())
        assertTrue(настройки.мастерПройден)
        // Прежние файлы данных остаются за первым профилем — история не теряется.
        assertEquals("сервер_история.db", настройки.файлИстории())
        assertEquals("журнал.log", настройки.файлЖурнала())
        // Интервалы целей и срок хранения переехали из корня в профиль.
        assertEquals(10.0, настройки.числоСервера("сайты_интервал_секунд", 1.0), 0.001)
        assertEquals(14.0, настройки.числоСервера("хранить_дней", 1.0), 0.001)
    }

    @Test
    fun `у сервера из старого файла имя профиля пустое, а подпись — адрес`() {
        val настройки = настройки(старыйФайл())

        // Шапка покажет имя удалённого узла (как до поддержки нескольких
        // серверов), поэтому имя профиля остаётся пустым, а не подменяется адресом.
        assertEquals("", настройки.имяПрофиля())
        assertEquals("192.168.0.2", настройки.подпись())
    }

    @Test
    fun `заданное имя профиля важнее адреса и не теряется при сохранении`() {
        val настройки = настройки(старыйФайл())
        val ид = настройки.добавитьСервер(профиль("10.0.0.5"), "Офис")

        assertEquals("Офис", настройки.имяПрофиля(ид))
        assertEquals("Офис", настройки.подпись(ид))
        assertEquals("Офис", настройки(текстФайла()).подпись(ид))
        // Без имени профиль не подменяет его адресом — иначе в шапке вместо
        // имени узла оказался бы IP.
        val безИмени = настройки.добавитьСервер(профиль("10.0.0.6"))
        assertEquals("", настройки.имяПрофиля(безИмени))
        assertEquals("10.0.0.6", настройки.подпись(безИмени))
    }


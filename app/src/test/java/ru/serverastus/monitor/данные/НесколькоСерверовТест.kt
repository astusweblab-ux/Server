    @Test
    fun `сброс настроек очищает и профили, и секреты`() {
        val настройки = настройки(старыйФайл())
        настройки.сбросить()

        assertEquals(0, настройки.серверы.size)
        assertEquals("", настройки.парольСервера())
        assertEquals(emptyList<String>(), хранилище().имена())
    }

    // --- состояние связи ----------------------------------------------------

    @Test
    fun `состояние сервера хранится отдельно от соседей`() {
        val настройки = настройки(старыйФайл())
        val первый = настройки.активныйId
        val второй = настройки.добавитьСервер(профиль("10.0.0.5"), "Второй")

        настройки.отметитьПодключение(второй, успех = false, ошибка = "нет связи")

        assertEquals("недоступен", настройки.состояние(второй))
        assertEquals("нет связи", настройки.последняяОшибка(второй))
        assertTrue(настройки.последнееПодключение(второй) > 0)
        // Первого сервера это не касается.
        assertEquals("", настройки.состояние(первый))
        assertEquals(0L, настройки.последнееПодключение(первый))
        // Состояние сохраняется между запусками.
        assertEquals("недоступен", Настройки(папка.root, хранилище()).состояние(второй))
    }

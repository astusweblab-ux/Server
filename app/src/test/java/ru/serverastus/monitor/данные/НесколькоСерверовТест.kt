    @Test
    fun `второй сервер получает свои файлы данных и становится активным`() {
        val настройки = настройки(старыйФайл())
        val первый = настройки.активныйId

        val второй = настройки.добавитьСервер(
            профиль("10.0.0.5", пароль = "другой", сайты = listOf("https://второй.ру"), службы = listOf("nginx")),
            "Второй сервер",
        )

        assertEquals("srv2", второй)
        assertEquals("srv2", настройки.активныйId)
        assertEquals(2, настройки.серверы.size)
        assertEquals("Второй сервер", настройки.подпись(второй))
        assertEquals("сервер_история_srv2.db", настройки.файлИстории(второй))
        assertEquals("журнал_srv2.log", настройки.файлЖурнала(второй))
        assertNotEquals(настройки.файлИстории(первый), настройки.файлИстории(второй))
        assertEquals("другой", настройки.парольСервера(второй))
        assertEquals("тайна", настройки.парольСервера(первый))
    }

    @Test
    fun `сайты и службы серверов не смешиваются`() {
        val настройки = настройки(старыйФайл())
        val первый = настройки.активныйId
        val второй = настройки.добавитьСервер(
            профиль("10.0.0.5", сайты = listOf("https://второй.ру"), службы = listOf("nginx")),
            "Второй",
        )

        // Активен второй: экраны видят только его цели.
        assertEquals(listOf("https://второй.ру"), настройки.сайты().map { настройки.текст(it, "url") })
        assertEquals(listOf("nginx.service"), настройки.службы())
        // У первого всё своё и ничего не пропало.
        assertEquals(listOf("http://192.168.0.2"), настройки.сайты(первый).map { настройки.текст(it, "url") })
        assertEquals(listOf("ssh.service", "cron.service"), настройки.службы(первый))
        assertEquals("192.168.0.2", настройки.текст(настройки.найти(первый)!!, "хост"))
        assertEquals("10.0.0.5", настройки.текст(настройки.найти(второй)!!, "хост"))
    }

    @Test
    fun `переключение возвращает данные выбранного сервера`() {
        val настройки = настройки(старыйФайл())
        val первый = настройки.активныйId
        val второй = настройки.добавитьСервер(профиль("10.0.0.5", сайты = listOf("https://второй.ру")), "Второй")

        assertTrue(настройки.выбратьСервер(первый))
        assertEquals(первый, настройки.активныйId)
        assertEquals(listOf("http://192.168.0.2"), настройки.сайты().map { настройки.текст(it, "url") })

        assertTrue(настройки.выбратьСервер(второй))
        assertEquals(listOf("https://второй.ру"), настройки.сайты().map { настройки.текст(it, "url") })

        // Незнакомый идентификатор активный сервер не меняет.
        assertFalse(настройки.выбратьСервер("srv99"))
        assertEquals(второй, настройки.активныйId)
    }


    @Test
    fun `правка одного сервера не меняет соседний`() {
        val настройки = настройки(старыйФайл())
        val первый = настройки.активныйId
        val второй = настройки.добавитьСервер(профиль("10.0.0.5", сайты = listOf("https://второй.ру")), "Второй")

        настройки.применить(
            JSONObject()
                .put("имя", "Второй переименован")
                .put(
                    "сервер_linux",
                    JSONObject().put("хост", "10.0.0.7").put("порт", 2222).put("пользователь", "aibot"),
                )
                .put("сайты", JSONArray().apply {
                    put(JSONObject().put("имя", "А").put("url", "https://а.ру"))
                    put(JSONObject().put("имя", "Б").put("url", "https://б.ру"))
                }),
            второй,
        )

        assertEquals("10.0.0.7", настройки.текст(настройки.найти(второй)!!, "хост"))
        assertEquals(2, настройки.сайты(второй).size)
        assertEquals("Второй переименован", настройки.подпись(второй))
        // Первый сервер остался нетронутым, включая адрес, цели и службы.
        assertEquals("192.168.0.2", настройки.текст(настройки.найти(первый)!!, "хост"))
        assertEquals(1, настройки.сайты(первый).size)
        assertEquals(listOf("ssh.service", "cron.service"), настройки.службы(первый))
        assertEquals("srv1", настройки.текст(настройки.найти(первый)!!, "id"))
    }


    }

    @Test
    fun `строка техжурнала читается на текущем языке`() {
        Локаль.подменитьЯзык("ru")
        val поРусски = "[17.09.2026 03:43:23] " + Локаль.л("Окно приложения открыто")
        assertEquals(поРусски, Локаль.перевестиСтрокуЖурнала(поРусски))

        Локаль.подменитьЯзык("uk")
        assertEquals(
            "[17.09.2026 03:43:23] " + УКРАИНСКИЙ["Окно приложения открыто"],
            Локаль.перевестиСтрокуЖурнала(поРусски),
        )

        Локаль.подменитьЯзык("en")
        assertEquals(
            "[17.09.2026 03:43:23] " + АНГЛИЙСКИЙ["Окно приложения открыто"],
            Локаль.перевестиСтрокуЖурнала(поРусски),
        )

        // Запись, сделанная на английском, читается по-русски.
        val поАнглийски = "[17.09.2026 03:43:23] " + Локаль.л("Окно приложения открыто")
        Локаль.подменитьЯзык("ru")
        assertEquals(поРусски, Локаль.перевестиСтрокуЖурнала(поАнглийски))
    }

    @Test
    fun `склеенная строка техжурнала переводится по частям`() {
        val шаблон = УКРАИНСКИЙ.keys.first {
            it.contains("{1}") && it.contains("{2}") && it.contains("{3}")
        }
        Локаль.подменитьЯзык("ru")
        val строка = "[17.09.2026 03:43:23] astuslab: " + Локаль.л(шаблон, "ЦП", 95.0, 90.0)
        Локаль.подменитьЯзык("en")
        val переведённая = Локаль.перевестиСтрокуЖурнала(строка)
        val отметка = "[17.09.2026 03:43:23] astuslab: "
        assertTrue("отметка времени потерялась: $переведённая", переведённая.startsWith(отметка))
        assertEquals(Локаль.л(шаблон, Локаль.л("ЦП"), 95.0, 90.0), переведённая.removePrefix(отметка))
    }

    @Test
    fun `строка техжурнала без перевода остаётся как есть`() {
        Локаль.подменитьЯзык("de")
        val строка = "[17.09.2026 03:43:23] java.io.IOException: broken pipe"
        assertEquals(строка, Локаль.перевестиСтрокуЖурнала(строка))
        assertEquals("", Локаль.перевестиСтрокуЖурнала(""))
    }

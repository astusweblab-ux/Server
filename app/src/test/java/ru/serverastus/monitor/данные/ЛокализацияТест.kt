/**
 * Локализация: словари украинского и английского языков должны полностью покрывать
 * русские шаблоны из кода, а готовые строки (журнал, отчёты, экспорт) — переводиться
 * обратно, чтобы после смены языка интерфейса не оставалось чужого текста.
 */
class ЛокализацияТест {

    @Before
    fun фиксируемЯзык() {
        Локаль.подменитьЯзык("ru")
    }

    @After
    fun возвращаемСистемныйЯзык() {
        Локаль.подменитьЯзык(null)
    }

    private val русскиеБуквы = Regex("[А-Яа-яЁёІіЇїЄєҐґ]")

    /**
     * Имена файлов, папок и ключи настроек показываются как есть даже в английском тексте
     * («экспорт», сервер_история.db, /etc/sysctl.d/99-сеть.conf, хранить_дней), поэтому
     * кириллицу внутри них проверка не считает непереведённым текстом.
     */
    private fun безИмён(текст: String): String =
        текст.replace(Regex("«[^»]*»"), "«»")
            .replace(Regex("\\S+\\.(csv|db|conf|log|json|txt)"), "")
            .replace(Regex("[a-zа-яё_]+_[a-zа-яё_]+"), "")

    private fun заполнители(текст: String): List<String> =
        Regex("\\{(\\d+)\\}").findAll(текст).map { it.groupValues[1] }.sorted().toList()

    @Test
    fun `оба словаря непустые и совпадают по ключам`() {
        assertTrue("украинский словарь пуст", УКРАИНСКИЙ.size > 100)
        assertEquals(УКРАИНСКИЙ.size, АНГЛИЙСКИЙ.size)
        assertEquals(УКРАИНСКИЙ.keys, АНГЛИЙСКИЙ.keys)
    }

    @Test
    fun `в словарях нет пустых переводов и непереведённых строк`() {
        val толькоРусскиеБуквы = Regex("[ЫыЪъЭэЁё]")
        var слов = 0
        var совпало = 0
        for ((ключ, перевод) in УКРАИНСКИЙ) {
            assertTrue("пустой перевод: «$ключ»", перевод.isNotBlank())
            assertFalse(
                "русская буква в украинском переводе «$ключ»: $перевод",
                толькоРусскиеБуквы.containsMatchIn(безИмён(перевод)),
            )
            if (русскиеБуквы.containsMatchIn(ключ)) {
                слов++
                if (ключ == перевод) совпало++
            }
        }
        assertTrue("украинский словарь почти не переведён: совпало $совпало из $слов", совпало * 3 < слов)
        for ((ключ, перевод) in АНГЛИЙСКИЙ) {
            assertTrue("пустой перевод: «$ключ»", перевод.isNotBlank())
            if (русскиеБуквы.containsMatchIn(безИмён(ключ))) {
                assertFalse("перевод совпал с шаблоном: «$ключ»", ключ == перевод)
            }
        }
    }

    @Test
    fun `заполнители перевода совпадают с шаблоном`() {
        for ((ключ, перевод) in УКРАИНСКИЙ) {
            assertEquals("@{1} в украинском: «$ключ»", заполнители(ключ), заполнители(перевод))
        }
        for ((ключ, перевод) in АНГЛИЙСКИЙ) {
            assertEquals("@{1} в английском: «$ключ»", заполнители(ключ), заполнители(перевод))
        }
    }

    @Test
    fun `в английском словаре нет кириллицы`() {
        for ((ключ, перевод) in АНГЛИЙСКИЙ) {
            assertFalse(
                "кириллица в английском переводе «$ключ»: $перевод",
                русскиеБуквы.containsMatchIn(безИмён(перевод)),
            )
        }
    }

    @Test
    fun `каждый русский шаблон из кода переведён`() {
        val безПеревода = mutableListOf<String>()
        for (шаблон in СТРОКИ_ПРИЛОЖЕНИЯ) {
            if (!русскиеБуквы.containsMatchIn(шаблон)) continue
            if (!УКРАИНСКИЙ.containsKey(шаблон) || !АНГЛИЙСКИЙ.containsKey(шаблон)) безПеревода.add(шаблон)
        }
        assertTrue("без перевода остались шаблоны: $безПеревода", безПеревода.isEmpty())
    }

    /**
     * Часть строк код передаёт в л(...) не литералом, а переменной: единицы размера из
     * `форматБайт`, состояния служб из `СОСТОЯНИЯ_СЛУЖБ`, уровни оценок сети и обслуживания.
     * Сканер исходников такие ключи не видит, поэтому они проверяются списком — иначе единицы
     * измерения («1.2 ГиБ») остаются русскими в английском интерфейсе.
     *
     * Уровни журнала («сбой», «предупреждение», «успех») сюда не входят: они хранятся в базе
     * как служебные значения и показываются через `уровеньСобытия` — это проверяет отдельный тест.
     */
    @Test
    fun `косвенные ключи переведены`() {
        val ключи = listOf("Б", "КиБ", "МиБ", "ГиБ", "ТиБ", "ПиБ") +
            СОСТОЯНИЯ_СЛУЖБ.values +
            listOf(
                УРОВЕНЬ_СЕТИ_ОТЛИЧНО, УРОВЕНЬ_СЕТИ_НОРМАЛЬНО, УРОВЕНЬ_СЕТИ_ВНИМАНИЕ, УРОВЕНЬ_СЕТИ_ПЛОХО,
                УРОВЕНЬ_ОБСЛУЖИВАНИЯ_ОТЛИЧНО, УРОВЕНЬ_ОБСЛУЖИВАНИЯ_НОРМАЛЬНО,
                УРОВЕНЬ_ОБСЛУЖИВАНИЯ_ВНИМАНИЕ, УРОВЕНЬ_ОБСЛУЖИВАНИЯ_ПЛОХО,
            )
        for (ключ in ключи) {
            assertTrue("нет украинского перевода: «$ключ»", УКРАИНСКИЙ.containsKey(ключ))
            assertTrue("нет английского перевода: «$ключ»", АНГЛИЙСКИЙ.containsKey(ключ))
        }
    }

    @Test
    fun `единицы размера показываются на текущем языке`() {
        val гигабайт = 1073741824L
        Локаль.подменитьЯзык("ru")
        assertEquals("1.0 ГиБ", форматБайт(гигабайт))
        Локаль.подменитьЯзык("uk")
        assertEquals("1.0 ГіБ", форматБайт(гигабайт))
        Локаль.подменитьЯзык("en")
        assertEquals("1.0 GiB", форматБайт(гигабайт))
        assertEquals("1.5 KiB", форматБайт(1536))
        assertEquals("512 B", форматБайт(512))
    }

    /**
     * Уровень оценки («отлично», «нормально», «внимание», «плохо») ядро диагностики возвращает
     * готовым значением, а не шаблоном, поэтому переводить его нужно в месте показа — в ярлычке
     * экрана и в текстовом отчёте. Иначе в английском интерфейсе рядом с «78 of 100» стоит
     * «нормально», а украинская оценка приходит с русским уровнем.
     */
    @Test
    fun `уровень оценки переводится в интерфейсе и в отчётах`() {
        val сети = ОценкаСети(балл = 78, уровень = УРОВЕНЬ_СЕТИ_НОРМАЛЬНО)
        val обслуживание = ОценкаОбслуживания(балл = 81, уровень = УРОВЕНЬ_ОБСЛУЖИВАНИЯ_НОРМАЛЬНО)
        Локаль.подменитьЯзык("en")
        assertEquals("normal", Локаль.л(сети.уровень))
        assertEquals("normal", Локаль.л(обслуживание.уровень))
        assertTrue(
            "английский отчёт сети без уровня: ${отчётСети(ДиагностикаСети(), сети)}",
            отчётСети(ДиагностикаСети(), сети).contains("Score: 78 of 100 — normal"),
        )
        assertTrue(
            "английский отчёт обслуживания без уровня: ${отчётОбслуживания(Обслуживание(), обслуживание)}",
            отчётОбслуживания(Обслуживание(), обслуживание).contains("Score: 81 of 100 — normal"),
        )
        Локаль.подменитьЯзык("uk")
        assertTrue(
            "украинский отчёт сети без уровня",
            отчётСети(ДиагностикаСети(), сети).contains("Оцінка: 78 з 100 — нормально"),
        )
        Локаль.подменитьЯзык("ru")
        assertTrue(
            "русский отчёт сети изменился",
            отчётСети(ДиагностикаСети(), сети).contains("Оценка: 78 из 100 — нормально"),
        )
    }

    /**
     * Подписи к параметрам ядра берутся через л(...) при каждом обращении: обычный `val` выполнил
     * бы перевод один раз при первой загрузке класса, и после смены языка системы список остался
     * бы на прежнем языке (именно так падал тест отчёта сети при смене языка в другом тесте).
     */
    @Test
    fun `подписи параметров ядра не застывают на одном языке`() {
        fun подпись(): String =
            ПОКАЗЫВАЕМЫЕ_ПАРАМЕТРЫ.first { it.first == "net.ipv4.tcp_congestion_control" }.second
        Локаль.подменитьЯзык("ru")
        assertEquals("Управление перегрузкой TCP", подпись())
        Локаль.подменитьЯзык("uk")
        assertEquals("Керування перевантаженням TCP", подпись())
        Локаль.подменитьЯзык("en")
        assertEquals("TCP congestion control", подпись())
    }

    @Test
    fun `текст собирается на выбранном языке`() {
        Локаль.подменитьЯзык("ru")
        assertEquals("Сервер", Локаль.л("Сервер"))
        Локаль.подменитьЯзык("uk")
        assertEquals(УКРАИНСКИЙ["Сервер"], Локаль.л("Сервер"))
        Локаль.подменитьЯзык("en")
        assertEquals(АНГЛИЙСКИЙ["Сервер"], Локаль.л("Сервер"))
        // Любой прочий язык системы — английский.
        Локаль.подменитьЯзык("de")
        assertEquals(АНГЛИЙСКИЙ["Сервер"], Локаль.л("Сервер"))
        Локаль.подменитьЯзык("pl")
        assertEquals(АНГЛИЙСКИЙ["Сервер"], Локаль.л("Сервер"))
        assertEquals("en", Локаль.язык())
    }

    @Test
    fun `подстановки занимают места аргументов`() {
        val шаблон = УКРАИНСКИЙ.keys.first { it.contains("{1}") && it.contains("{2}") }
        Локаль.подменитьЯзык("uk")
        val итог = Локаль.л(шаблон, "хост", 7)
        assertTrue("аргументы не подставились: $итог", итог.contains("хост") && итог.contains("7"))
        assertFalse("остались заполнители: $итог", итог.contains("{1}") || итог.contains("{2}"))
    }

    @Test
    fun `готовый русский текст читается на украинском и английском`() {
        val шаблон = УКРАИНСКИЙ.keys.first { it.contains("{1}") && it.contains("{2}") }
        Локаль.подменитьЯзык("ru")
        val поРусски = Локаль.л(шаблон, "example.com", 7)
        Локаль.подменитьЯзык("uk")
        assertEquals(Локаль.л(шаблон, "example.com", 7), Локаль.перевестиГотовый(поРусски))
        Локаль.подменитьЯзык("en")
        assertEquals(Локаль.л(шаблон, "example.com", 7), Локаль.перевестиГотовый(поРусски))
    }

    @Test
    fun `готовый украинский текст читается по-русски`() {
        val шаблон = УКРАИНСКИЙ.keys.first { it.contains("{1}") && it.contains("{2}") }
        Локаль.подменитьЯзык("uk")
        val поУкраински = Локаль.л(шаблон, "сервер", 3)
        Локаль.подменитьЯзык("ru")
        assertEquals(Локаль.л(шаблон, "сервер", 3), Локаль.перевестиГотовый(поУкраински))
    }

    @Test
    fun `готовый английский текст читается по-украински`() {
        val ключ = УКРАИНСКИЙ.keys.first { !it.contains("{") && русскиеБуквы.containsMatchIn(it) }
        Локаль.подменитьЯзык("en")
        val поАнглийски = Локаль.л(ключ)
        Локаль.подменитьЯзык("uk")
        assertEquals(Локаль.л(ключ), Локаль.перевестиГотовый(поАнглийски))
    }

    @Test
    fun `вложенный текст переводится целиком`() {
        val внешний = УКРАИНСКИЙ.keys.first { it.contains("{1}") }
        val внутренний = УКРАИНСКИЙ.keys.first { !it.contains("{") && русскиеБуквы.containsMatchIn(it) }
        Локаль.подменитьЯзык("ru")
        val поРусски = Локаль.л(внешний, Локаль.л(внутренний))
        Локаль.подменитьЯзык("en")
        assertEquals(Локаль.л(внешний, Локаль.л(внутренний)), Локаль.перевестиГотовый(поРусски))
    }

    @Test
    fun `неизвестный текст остаётся как есть`() {
        Локаль.подменитьЯзык("en")
        val чужой = "Совершенно произвольная строка без шаблона"
        assertEquals(чужой, Локаль.перевестиГотовый(чужой))
        assertEquals("", Локаль.перевестиГотовый(""))
    }

    @Test
    fun `событие журнала показывается на текущем языке`() {
        Локаль.подменитьЯзык("ru")
        val событие = СобытиеЖурнала(
            время = 0,
            уровень = "сбой",
            цель = "Сервер",

        assertEquals(АНГЛИЙСКИЙ["Сбой"], уровеньСобытия("сбой"))
        assertEquals(АНГЛИЙСКИЙ["Предупреждение"], уровеньСобытия("предупреждение"))
        assertEquals(АНГЛИЙСКИЙ["Успех"], уровеньСобытия("успех"))

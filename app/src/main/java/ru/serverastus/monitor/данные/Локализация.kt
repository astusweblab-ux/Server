package ru.serverastus.monitor.данные

import java.util.Locale

/**
 * Локализация интерфейса: русский, украинский и английский.
 *
 * Исходный текст в коде всегда русский и одновременно служит ключом перевода,
 * поэтому переводить нужно только украинский и английский (см. `ЯзыкУкраинский.kt`
 * и `ЯзыкАнглийский.kt`). Строки с подстановками пишутся с заполнителями {1}, {2} …
 * — так перевод может переставить слова местами:
 *
 *     л("Сертификат {1} истекает через {2} дн.", имя, дней)
 *
 * Язык выбирается автоматически по языку системы: русский — русский,
 * украинский — украинский, любой другой — английский.
 */
object Локаль {

    private val СЛОВАРИ: Map<String, Map<String, String>> = mapOf(
        "uk" to УКРАИНСКИЙ,
        "en" to АНГЛИЙСКИЙ,
    )

    private var подмена: String? = null

    private val замокГотовых = Any()
    private val кэшГотовых = HashMap<String, String>()
    private val точныеГотовые = HashMap<String, String>()
    private val шаблоныГотовые = mutableListOf<ГотовыйШаблон>()
    private var собрано = false

    /** Код языка интерфейса: «ru», «uk» или «en». */
    fun язык(): String {
        val код = (подмена ?: Locale.getDefault().language).lowercase(Locale.ROOT)
        return when {
            код == "ru" -> "ru"
            код == "uk" -> "uk"
            else -> "en"
        }
    }

    /** Переводит шаблон на язык системы и подставляет аргументы вместо {1}, {2} … */
    fun л(шаблон: String, vararg аргументы: Any?): String {
        val перевод = СЛОВАРИ[язык()]?.get(шаблон) ?: шаблон
        if (аргументы.isEmpty()) return перевод
        return подставить(перевод, аргументы)
    }

    /** Для тестов: фиксирует язык вместо системного (`null` — снова системный). */
    fun подменитьЯзык(код: String?) {
        подмена = код
    }

    /**
     * Показывает уже собранный текст на текущем языке интерфейса.
     *
     * Нужен для того, что хранится готовой строкой: журнал событий, статистика, экспорт.
     * Текст сопоставляется со всеми известными формами шаблона — русской, украинской и
     * английской, — поэтому запись, сделанная до смены языка, всё равно читается на
     * текущем. Если совпадения нет, текст возвращается без изменений.
     */
    fun перевестиГотовый(текст: String): String {
        if (текст.isEmpty()) return текст
        val ключКэша = язык() + '\u0000' + текст
        synchronized(замокГотовых) { кэшГотовых[ключКэша]?.let { return it } }
        val итог = перевестиГотовыйВнутри(текст, 0)
        synchronized(замокГотовых) {
            if (кэшГотовых.size > 1024) кэшГотовых.clear()
            кэшГотовых[ключКэша] = итог
        }
        return итог
    }

    /**
     * Строка технического журнала на текущем языке: отметка времени «[дд.мм.гггг чч:мм:сс] »
     * не трогается, остальное переводится.
     *
     * Часть строк — склейка готовых текстов «цель: сообщение» (см. `Оповещения`), поэтому
     * если строка целиком не совпала с известным текстом, переводим её половины по отдельности.
     */
    fun перевестиСтрокуЖурнала(строка: String): String {
        if (строка.isEmpty()) return строка
        val начало = началоТекста(строка)
        return строка.substring(0, начало) + перевестиЧасти(строка.substring(начало))
    }

    /** Индекс первого символа текста строки — сразу за «[дд.мм.гггг чч:мм:сс] ». */
    private fun началоТекста(строка: String): Int {
        if (!строка.startsWith("[")) return 0
        val конец = строка.indexOf("] ")
        return if (конец < 0) 0 else конец + 2
    }

    private fun перевестиЧасти(текст: String): String {
        val целиком = перевестиГотовый(текст)
        if (целиком != текст) return целиком
        val двоеточие = текст.indexOf(": ")
        if (двоеточие <= 0) return текст
        val цель = перевестиГотовый(текст.substring(0, двоеточие))
        val сообщение = перевестиГотовый(текст.substring(двоеточие + 2))
        return "$цель: $сообщение"
    }

    private fun перевестиГотовыйВнутри(текст: String, глубина: Int): String {
        if (текст.isEmpty()) return текст
        собратьКандидатов()
        точныеГотовые[текст]?.let { ключ -> return л(ключ) }
        if (глубина >= 3) return текст
        for (шаблон in шаблоныГотовые) {
            // Дешёвая отсечка: длинный неизменный кусок шаблона обязан быть в тексте.
            if (!текст.contains(шаблон.чанк)) continue
            val совпадение = шаблон.образец.matchEntire(текст) ?: continue
            val аргументы = совпадение.groupValues
                .drop(1)
                .map { перевестиГотовыйВнутри(it, глубина + 1) }
            return л(шаблон.ключ, *аргументы.toTypedArray())
        }
        return текст
    }

    /** Строит обратные словари один раз — сразу по всем языкам. */
    private fun собратьКандидатов() {
        if (собрано) return
        synchronized(замокГотовых) {
            if (собрано) return
            точныеГотовые.clear()
            шаблоныГотовые.clear()
            val ключи = LinkedHashSet<String>()
            for ((_, словарь) in СЛОВАРИ) ключи.addAll(словарь.keys)
            val кандидаты = LinkedHashMap<String, String>()
            for (ключ in ключи) кандидаты[ключ] = ключ
            for ((_, словарь) in СЛОВАРИ) {
                for ((ключ, перевод) in словарь) {
                    if (!кандидаты.containsKey(перевод)) кандидаты[перевод] = ключ
                }
            }
            for ((форма, ключ) in кандидаты) {
                if (форма.indexOf('{') < 0) {
                    точныеГотовые[форма] = ключ
                } else {
                    разобратьШаблон(форма, ключ)?.let { шаблоныГотовые.add(it) }
                }
            }
            // Шаблоны с более длинным неизменным куском сначала: они точнее коротких.
            шаблоныГотовые.sortByDescending { it.чанк.length }
            собрано = true
        }
    }

    /** Превращает форму шаблона с {1}, {2} … в регулярное выражение. */
    private fun разобратьШаблон(форма: String, ключ: String): ГотовыйШаблон? {
        val образец = StringBuilder("^")
        val чанк = StringBuilder()
        var лучший = ""
        var индекс = 0
        var мест = 0
        while (индекс < форма.length) {
            val знак = форма[индекс]
            if (знак == '{') {
                val конец = форма.indexOf('}', индекс + 1)
                val номер = if (конец > индекс + 1) {
                    форма.substring(индекс + 1, конец).toIntOrNull()
                } else {
                    null
                }
                if (номер != null && номер in 1..9) {
                    if (чанк.length > лучший.length) лучший = чанк.toString()
                    чанк.setLength(0)
                    образец.append("(.*?)")
                    мест++
                    индекс = конец + 1
                    continue
                }
            }
            образец.append(экранировать(знак))
            чанк.append(знак)
            индекс++
        }
        if (чанк.length > лучший.length) лучший = чанк.toString()
        if (мест == 0) return null
        return try {
            ГотовыйШаблон(Regex(образец.append('$').toString()), ключ, лучший)
        } catch (ошибка: Exception) {
            null
        }
    }

    private fun экранировать(знак: Char): String =
        if (знак in "\\^$.|?*+()[]{}") "\\$знак" else знак.toString()


    private fun подставить(шаблон: String, аргументы: Array<out Any?>): String {
        val итог = StringBuilder(шаблон.length + 16)
        var индекс = 0
        while (индекс < шаблон.length) {
            val знак = шаблон[индекс]
            if (знак == '{') {
                val конец = шаблон.indexOf('}', индекс + 1)
                val номер = if (конец > индекс + 1) {
                    шаблон.substring(индекс + 1, конец).toIntOrNull()
                } else {
                    null
                }
                if (номер != null && номер in 1..аргументы.size) {
                    итог.append(аргументы[номер - 1] ?: "")
                    индекс = конец + 1
                    continue
                }
            }
            итог.append(знак)
            индекс++
        }
        return итог.toString()
    }
}

/** Короткая обёртка: `л("Сервер")` вместо `Локаль.л("Сервер")`. */
fun л(шаблон: String, vararg аргументы: Any?): String = Локаль.л(шаблон, *аргументы)

/** Разобранный шаблон готового текста: регулярка, русский ключ и неизменный кусок. */
private class ГотовыйШаблон(
    val образец: Regex,
    val ключ: String,
    val чанк: String,
)

/**
 * Текст события журнала на текущем языке интерфейса.
 *
 * Записи хранятся на языке момента записи, поэтому текст переводится обратно: сначала
 * ищется точное совпадение с известной строкой, затем — совпадение с шаблоном с
 * подстановками. Даже старые записи журнала читаются на текущем языке.
 */
fun СобытиеЖурнала.текст(): String = Локаль.перевестиГотовый(сообщение)

/** Цель события («Сервер», «Приложение», имя сайта или службы) на текущем языке. */
fun СобытиеЖурнала.цельТекст(): String = Локаль.перевестиГотовый(цель)

/** Подпись уровня события: «Сбой», «Предупреждение», «Успех», «Восстановление». */
fun уровеньСобытия(уровень: String): String = л(
    when (уровень) {
        "сбой" -> "Сбой"
        "предупреждение" -> "Предупреждение"
        "успех" -> "Успех"
        "восстановление" -> "Восстановление"
        else -> "Сведения"
    },
)

/** Проверяет, что для шаблона есть перевод на текущий язык (для тестов полноты). */
fun естьПеревод(шаблон: String): Boolean = Локаль.л(шаблон) != шаблон || Локаль.язык() == "ru"

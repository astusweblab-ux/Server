package ru.serverastus.monitor.данные

/**
 * Имя службы systemd в едином виде: «ssh» и «ssh.service» — это одна служба.
 *
 * В старых настройках записи могли остаться без суффикса (пользователь вводил
 * «ssh», как в `systemctl`), а найденные на сервере службы всегда приходят с
 * суффиксом. Без общей нормализации уже добавленная служба выглядела бы как
 * новая и предлагалась к добавлению повторно, а список копил бы дубли.
 *
 * Имя, в котором точка уже есть (`ssh.service`, `postgresql@14-main.service`,
 * а также не-сервисные юниты вроде `nginx.socket`), не меняется — иначе из
 * `nginx.socket` получился бы несуществующий `nginx.socket.service`.
 */
internal fun нормализоватьСлужбу(введённое: String): String {
    val имя = введённое.trim().lowercase()
    if (имя.isEmpty()) return ""
    return if (имя.contains('.')) имя else л("{1}.service", имя)
}

/**
 * Есть ли такая служба в списке — сравнение по нормализованному имени, поэтому
 * сохранённое «ssh» и найденное на сервере «ssh.service» считаются одной службой.
 */
internal fun естьСлужба(список: List<String>, имя: String): Boolean {
    val приведённое = нормализоватьСлужбу(имя)
    if (приведённое.isEmpty()) return false
    return список.any { нормализоватьСлужбу(it) == приведённое }
}

/** Добавляет службу, если такой ещё нет; возвращает false, если это повтор. */
internal fun добавитьСлужбу(список: MutableList<String>, имя: String): Boolean {
    if (естьСлужба(список, имя)) return false
    val приведённое = нормализоватьСлужбу(имя)
    if (приведённое.isEmpty()) return false
    список.add(приведённое)
    return true
}

/** Список служб без пустых и повторяющихся имён (сравнение по нормализованному виду). */
internal fun привестиСписокСлужб(имена: List<String>): List<String> {
    val итог = mutableListOf<String>()
    for (имя in имена) добавитьСлужбу(итог, имя)
    return итог
}

package ru.serverastus.monitor.данные

import android.content.Context
import org.json.JSONArray
import org.json.JSONObject
import java.io.File

private const val ФАЙЛ_СЕКРЕТОВ = "секреты.json"

/** Поля профиля, которые может менять форма настроек (id и файлы данных — нет). */
private val ПОЛЯ_СЕРВЕРА = listOf(
    "включен", "хост", "порт", "пользователь", "файл_ключа", "таймаут_секунд", "диск_путь",
    "пороги_предупреждений", "интервал_секунд", "интервал_подробностей_секунд",
    "интервал_безопасности_секунд", "интервал_сети_секунд", "интервал_обслуживания_секунд",
)

/** Поля профиля с целями мониторинга и сроком хранения истории. */
private val ПОЛЯ_ЦЕЛЕЙ = listOf(
    "сайты", "порты", "сайты_интервал_секунд", "порты_интервал_секунд", "хранить_дней", "мастер_пройден",
)

/** Ключи, общие для всего приложения: они лежат в корне файла, а не в профиле. */
private val ПОЛЯ_ОБЩИЕ = listOf("запускать_при_загрузке", "журнал_в_консоль", "уведомления")

/**
 * Настройки приложения: тот же файл `config.json`, что и у настольной версии
 * (ключи на русском языке). Файл лежит во внешнем каталоге приложения —
 * его видно по USB и можно просто скопировать с компьютера. Пароли в файл не
 * попадают: они лежат в [ХранилищеСекретов], а в профиле остаётся ссылка
 * `секрет_id`.
 *
 * Серверов может быть несколько: список `серверы` хранит профили целиком
 * (адрес, доступ, сайты, порты, службы, интервалы), `активный_сервер` — какой
 * из них сейчас показывают экраны. Общие для приложения ключи (уведомления,
 * запуск при загрузке, срок хранения истории задаётся в профиле) остались в
 * корне файла. Класс не требует контекста, поэтому его работу можно проверить
 * обычными JVM-тестами.
 */
class Настройки(val каталог: File, val секреты: ХранилищеСекретов) {

    constructor(контекст: Context) : this(
        контекст.getExternalFilesDir(null) ?: контекст.filesDir,
        ХранилищеСекретов(File(контекст.filesDir, ФАЙЛ_СЕКРЕТОВ), ШифровальщикКейстора()),
    )

    val файл: File get() = File(каталог, "config.json")

    var данные: JSONObject = JSONObject()
        private set

    /** Последнее записанное состояние связи — чтобы не переписывать файл каждый опрос. */
    private var записанноеСостояние = ""

    init {
        загрузить()
    }

    /** Читает файл, накладывая его содержимое на настройки по умолчанию. */
    fun загрузить() {
        val прочитанное = try {
            if (файл.isFile) JSONObject(файл.readText(Charsets.UTF_8)) else JSONObject()
        } catch (ошибка: Exception) {
            JSONObject()
        }
        данные = слить(умолчания(), прочитанное)
        // Файл прошлых версий знал только один сервер — переносим его в список.
        if (!прочитанное.has("серверы")) перенестиОдинСервер(прочитанное)
    }

    /**
     * Старый формат (один сервер в разделе `сервер_linux`) превращается в первый
     * профиль списка: адрес, пароль, сайты, порты, службы и интервалы сохраняются,
     * прежний файл остаётся рядом как `config.json.до-нескольких-серверов`, а
     * прежние файлы истории и техжурнала продолжают использоваться. Имя профиля
     * не задаём — в шапке видно имя, которое вернул сам сервер.
     */
    private fun перенестиОдинСервер(прочитанное: JSONObject) {
        val ид = "srv1"
        val узел = профильИзСтарогоФормата(прочитанное, ид, "сервер_история.db", "журнал.log") ?: return
        val копия = File(каталог, "config.json.до-нескольких-серверов")
        if (!копия.isFile && файл.isFile) {
            try {
                копия.writeText(файл.readText(Charsets.UTF_8), Charsets.UTF_8)
            } catch (_: Exception) {
                // копия — только страховка, её отсутствие не мешает переносу
            }
        }
        серверыМассив().put(узел)
        данные.put("активный_сервер", ид)
        // Прежние корневые ключи переехали в профиль — в файле их быть не должно.
        for (ключ in listOf("сервер_linux", "мастер_пройден") + ПОЛЯ_ЦЕЛЕЙ) данные.remove(ключ)
        сохранить()
    }

    /**
     * Собирает профиль из настроек одного сервера: так читается старый файл
     * целиком и так же принимается набор, импортированный из мастера. Пароль
     * уходит в хранилище секретов, в узле остаётся только ссылка на него.
     */
    private fun профильИзСтарогоФормата(
        прочитанное: JSONObject,
        ид: String,
        файлИстории: String,
        файлЖурнала: String,
    ): JSONObject? {
        val старый = прочитанное.optJSONObject("сервер_linux") ?: прочитанное
        if (текст(старый, "хост").isEmpty() && текст(старый, "пользователь").isEmpty()) return null
        val узел = умолчанияСервера()
        узел.put("id", ид)
        узел.put("файл_истории", файлИстории)
        узел.put("файл_журнала", файлЖурнала)
        for (ключ in ПОЛЯ_СЕРВЕРА) if (старый.has(ключ)) узел.put(ключ, старый.opt(ключ))
        if (старый.has("службы")) узел.put("службы", JSONArray(привестиСписокСлужб(службыИз(старый))))
        for (ключ in ПОЛЯ_ЦЕЛЕЙ) {
            val откуда = if (прочитанное.has(ключ)) прочитанное else старый
            if (откуда.has(ключ)) узел.put(ключ, откуда.opt(ключ))
        }
        val пароль = текст(старый, "пароль")
        if (пароль.isNotEmpty()) {
            секреты.сохранить(ид, пароль)
            узел.put("секрет_id", ид)
        }
        узел.remove("пароль")
        return узел
    }

    /** Записывает настройки в файл (создаёт каталог при необходимости). */
    fun сохранить() {
        каталог.mkdirs()
        привестиВПамяти()
        файл.writeText(данные.toString(2), Charsets.UTF_8)
    }

    /**
     * Готовит настройки к записи: в каждом профиле службы приводятся к единому
     * виду («ssh» → «ssh.service», повторы убираются), а пароль, если он каким-то
     * образом оказался в JSON, переезжает в хранилище секретов.
     */
    private fun привестиВПамяти() {
        for (узел in узлы(серверыМассив())) {
            if (узел.optJSONArray("службы") != null) {
                узел.put("службы", JSONArray(привестиСписокСлужб(службыИз(узел))))
            }
            val ид = текст(узел, "id")
            val пароль = текст(узел, "пароль")
            if (ид.isNotEmpty() && пароль.isNotEmpty()) {
                секреты.сохранить(ид, пароль)
                узел.put("секрет_id", ид)
                узел.remove("пароль")
            }
        }
    }

    /** Имена служб так, как они лежат в узле сервера (без нормализации). */
    private fun службыИз(узел: JSONObject): List<String> {
        val массив = узел.optJSONArray("службы") ?: return emptyList()
        return (0 until массив.length()).map { массив.optString(it) }
    }

    /** Массив профилей внутри настроек (создаётся, если его ещё нет). */
    private fun серверыМассив(): JSONArray {
        val готовый = данные.optJSONArray("серверы")
        if (готовый != null) return готовый
        val массив = JSONArray()
        данные.put("серверы", массив)
        return массив
    }

    private fun узлы(массив: JSONArray): List<JSONObject> =
        (0 until массив.length()).mapNotNull { массив.optJSONObject(it) }

    private fun спискиИз(узел: JSONObject, имя: String): List<JSONObject> {
        val массив = узел.optJSONArray(имя) ?: return emptyList()
        return (0 until массив.length()).mapNotNull { массив.optJSONObject(it) }
    }

    fun записать(правка: (JSONObject) -> Unit) {
        правка(данные)
        сохранить()
    }

    /**
     * Импорт настроек из JSON. Файл нового образца (со списком `серверы`) заменяет
     * настройки целиком, а чужой файл старого образца добавляется ещё одним сервером:
     * так импорт одного сервера не затирает уже настроенные.
     */
    fun импортировать(текст: String): Boolean = try {
        val прочитанное = JSONObject(текст)
        if (прочитанное.has("серверы")) {
            данные = слить(умолчания(), прочитанное)
        } else {
            val ид = следующийId()
            val узел = профильИзСтарогоФормата(прочитанное, ид, "", "")
                ?: throw IllegalArgumentException("в файле нет данных сервера")
            узел.put("файл_истории", "сервер_история_$ид.db")
            узел.put("файл_журнала", "журнал_$ид.log")
            узел.put("имя", текст(узел, "имя").ifBlank { текст(узел, "хост") })
            серверыМассив().put(узел)
            данные.put("активный_сервер", ид)
        }
        сохранить()
        true
    } catch (ошибка: Exception) {
        false
    }

    fun сбросить() {
        данные = умолчания()
        секреты.очистить()
        сохранить()
    }

    /** Записывает набор настроек в профиль активного сервера. */
    fun применить(значение: JSONObject) = применить(значение, активныйId)

    /**
     * Записывает набор настроек — так сохраняют мастер и форма настроек. Если
     * идентификатор не задан, меняется профиль активного сервера; пустой или
     * незнакомый идентификатор означает новый сервер, и тогда создаётся отдельный
     * профиль, а настройки прежних серверов остаются нетронутыми.
     */
    fun применить(значение: JSONObject, идСервера: String?) {
        val узел = if (идСервера == null) найти(активныйId) else найти(идСервера)
        if (узел == null) {
            добавитьСервер(значение, текст(значение, "имя"))
            return
        }
        заполнитьПрофиль(узел, значение)
        // Общие для приложения ключи (уведомления, автозапуск) лежат в корне файла.
        for (ключ in ПОЛЯ_ОБЩИЕ) if (значение.has(ключ)) данные.put(ключ, значение.opt(ключ))
        сохранить()
    }

    /** Проверяет набор настроек, не меняя текущий файл (для формы настроек). */
    fun проверить(значение: JSONObject): List<String> {
        val узел = умолчанияСервера()
        заполнитьПрофиль(узел, значение)
        return замечания(узел)
    }

    // --- несколько серверов ------------------------------------------------

    /** Список профилей: у каждого свои доступ, цели, интервалы и файлы данных. */
    val серверы: List<JSONObject> get() = узлы(серверыМассив()).filter { текст(it, "id").isNotEmpty() }

    /** Идентификатор выбранного сервера — его данные показывают все экраны. */
    val активныйId: String
        get() {
            val сохранённый = текст(данные, "активный_сервер")
            if (сохранённый.isNotEmpty() && найти(сохранённый) != null) return сохранённый
            return серверы.firstOrNull()?.let { текст(it, "id") } ?: ""
        }

    /** Профиль по идентификатору или null, если такого сервера нет. */
    fun найти(ид: String?): JSONObject? {
        if (ид.isNullOrBlank()) return null
        return серверы.firstOrNull { текст(it, "id") == ид }
    }

    /** Профиль активного сервера; пока серверов нет — пустые умолчания. */
    fun узелСервера(ид: String? = null): JSONObject = найти(ид ?: активныйId) ?: умолчанияСервера()

    /** Подпись сервера для списков: имя профиля, а без него — адрес. */
    fun подпись(ид: String? = null): String {
        val узел = узелСервера(ид)
        return имяПрофиля(ид).ifBlank { текст(узел, "хост") }
    }

    /**
     * Имя, заданное пользователем. Пустое у сервера из старого файла: в шапке вместо
     * него показывается имя удалённого узла — как это было до поддержки нескольких
     * серверов, а в списках остаётся адрес.
     */
    fun имяПрофиля(ид: String? = null): String = текст(узелСервера(ид), "имя")

    /** Состояние последнего опроса сервера: «онлайн», «недоступен» или пусто. */
    fun состояние(ид: String? = null): String = текст(узелСервера(ид), "последнее_состояние")

    /** Время последнего опроса сервера (секунды эпохи) и текст ошибки связи. */
    fun последнееПодключение(ид: String? = null): Long =
        целое(узелСервера(ид), "последнее_подключение", 0).toLong()

    fun последняяОшибка(ид: String? = null): String = текст(узелСервера(ид), "последняя_ошибка")

    /** Пароль сервера: сначала из хранилища секретов, потом из профиля (старый файл). */
    fun парольСервера(ид: String? = null): String {
        val узел = узелСервера(ид)
        val ключ = текст(узел, "секрет_id").ifBlank { текст(узел, "id") }
        return секреты.получить(ключ) ?: текст(узел, "пароль")
    }

    /** Создаёт профиль нового сервера и возвращает его идентификатор. */
    fun добавитьСервер(значение: JSONObject, имя: String = "", сделатьАктивным: Boolean = true): String {
        val ид = следующийId()
        val узел = умолчанияСервера()
        узел.put("id", ид)
        // Свои файлы данных у каждого сервера: иначе история и журнал смешаются.
        узел.put("файл_истории", "сервер_история_$ид.db")
        узел.put("файл_журнала", "журнал_$ид.log")
        заполнитьПрофиль(узел, значение)
        // Имя остаётся таким, как его ввели: если его нет, в шапке покажется имя
        // удалённого узла, а в списках — адрес.
        узел.put("имя", имя.ifBlank { текст(узел, "имя") })
        серверыМассив().put(узел)
        данные.put("активный_сервер", if (сделатьАктивным) ид else активныйId)
        сохранить()
        return ид
    }

    /** Правки существующего профиля: переименование, смена доступа, цели. */
    fun обновитьСервер(ид: String, правки: JSONObject) {
        val узел = найти(ид) ?: return
        заполнитьПрофиль(узел, правки)
        val имя = текст(правки, "имя")
        if (имя.isNotEmpty()) узел.put("имя", имя)
        сохранить()
    }

    /**
     * Удаляет профиль. Файлы истории и техжурнала остаются на диске: если сервер
     * добавят снова, его данные не потеряются. Просьбу подтвердить удаление и
     * предупреждение о последнем сервере показывает экран «Серверы».
     */
    fun удалитьСервер(ид: String): Boolean {
        val массив = серверыМассив()
        val индекс = (0 until массив.length()).firstOrNull { текст(массив.optJSONObject(it) ?: JSONObject(), "id") == ид }
            ?: return false
        массив.remove(индекс)
        секреты.удалить(ид)
        данные.put("активный_сервер", активныйId)
        сохранить()
        return true
    }

    /** Делает сервер активным: экраны и движок переходят на его данные. */
    fun выбратьСервер(ид: String): Boolean {
        if (найти(ид) == null) return false
        if (активныйId == ид) return true
        данные.put("активный_сервер", ид)
        сохранить()
        return true
    }

    /**
     * Запоминает результат опроса: время и состояние связи для списка серверов.
     * В файл пишется только смена состояния — иначе `config.json` переписывался
     * бы на каждом опросе, раз в несколько секунд.
     */
    fun отметитьПодключение(ид: String, успех: Boolean, ошибка: String = "") {
        val узел = найти(ид) ?: return
        val состояние = if (успех) "онлайн" else "недоступен"
        узел.put("последнее_подключение", System.currentTimeMillis() / 1000)
        узел.put("последнее_состояние", состояние)
        узел.put("последняя_ошибка", if (успех) "" else ошибка)
        if (записанноеСостояние != "$ид:$состояние") {
            записанноеСостояние = "$ид:$состояние"
            сохранить()
        }
    }

    /**
     * Наполняет профиль значениями из готового набора настроек. Идентификатор,
     * файлы данных и состояние подключения не трогаются: их задаёт само
     * приложение, иначе два сервера могли бы писать в одну историю.
     */
    private fun заполнитьПрофиль(узел: JSONObject, значение: JSONObject) {
        val источник = значение.optJSONObject("сервер_linux") ?: значение
        for (ключ in ПОЛЯ_СЕРВЕРА) if (источник.has(ключ)) узел.put(ключ, источник.opt(ключ))
        if (источник.has("службы")) узел.put("службы", JSONArray(привестиСписокСлужб(службыИз(источник))))
        for (ключ in ПОЛЯ_ЦЕЛЕЙ) {
            val откуда = if (значение.has(ключ)) значение else источник
            if (откуда.has(ключ)) узел.put(ключ, откуда.opt(ключ))
        }
        val имя = текст(значение, "имя").ifBlank { текст(источник, "имя") }
        if (имя.isNotEmpty()) узел.put("имя", имя)
        val ид = текст(узел, "id")
        val пароль = текст(источник, "пароль")
        if (пароль.isNotEmpty()) {
            // Пустое поле пароля при заполненном файле ключа означает «работаем по ключу».
            if (ид.isEmpty()) {
                узел.put("пароль", пароль)
            } else {
                секреты.сохранить(ид, пароль)
                узел.put("секрет_id", ид)
            }
        } else if (текст(узел, "файл_ключа").isNotEmpty()) {
            if (ид.isNotEmpty()) секреты.удалить(ид)
            узел.put("секрет_id", "")
        }
        if (ид.isNotEmpty()) узел.remove("пароль")
    }

    /**
     * Свободный идентификатор вида `srv2`. Номера не переиспользуются: иначе
     * новый сервер получил бы файлы истории удалённого и показал чужие данные.
     */
    private fun следующийId(): String {
        var номер = целое(данные, "следующий_номер", 1).coerceAtLeast(1)
        val занятые = серверы.map { текст(it, "id") }.toSet()
        while ("srv$номер" in занятые) номер++
        данные.put("следующий_номер", номер + 1)
        return "srv$номер"
    }

    // --- доступ к разделам -------------------------------------------------

    fun узел(имя: String): JSONObject = данные.optJSONObject(имя) ?: JSONObject().also { данные.put(имя, it) }

    /** Профиль выбранного сервера: с ним работают движок и все экраны. */
    val сервер: JSONObject get() = узелСервера()

    /** Строковое значение узла: пусто, если ключа нет или вместо него null. */
    fun текст(узел: JSONObject, ключ: String): String =
        узел.optString(ключ, "").trim().takeIf { it != "null" } ?: ""

    /** Данных для подключения достаточно — можно показывать рабочие экраны. */
    fun настроен(ид: String? = null): Boolean {
        val узел = узелСервера(ид)
        return текст(узел, "хост").isNotEmpty() && текст(узел, "пользователь").isNotEmpty() &&
            (парольСервера(ид).isNotEmpty() || текст(узел, "файл_ключа").isNotEmpty())
    }

    /**
     * Мастер настройки пройден. У каждого сервера свой признак, а пока список
     * пуст (мастер пропустили) — общий для приложения: иначе мастер открывался
     * бы при каждом запуске.
     */
    val мастерПройден: Boolean
        get() = if (серверы.isEmpty()) да(данные, "мастер_пройден", false) else мастерПройден(активныйId)

    fun мастерПройден(ид: String?): Boolean = да(узелСервера(ид), "мастер_пройден", false)

    fun отметитьМастер(ид: String? = null) {
        val узел = найти(ид ?: активныйId)
        if (узел == null) данные.put("мастер_пройден", true) else узел.put("мастер_пройден", true)
        сохранить()
    }

    fun пороги(ид: String? = null): ТриПорога {
        val п = узелСервера(ид).optJSONObject("пороги_предупреждений") ?: JSONObject()
        return ТриПорога(
            цп = п.optDouble("цп_процент", 90.0),
            озу = п.optDouble("озу_процент", 90.0),
            диск = п.optDouble("диск_процент", 90.0),
        )
    }

    /** Службы systemd: имена приводятся к виду «имя.service», повторы убираются. */
    fun службы(ид: String? = null): List<String> = привестиСписокСлужб(службыИз(узелСервера(ид)))

    fun сайты(ид: String? = null): List<JSONObject> = спискиИз(узелСервера(ид), "сайты")

    fun порты(ид: String? = null): List<JSONObject> = спискиИз(узелСервера(ид), "порты")

    /**
     * Имя файла истории сервера. У перенесённого профиля это прежний
     * `сервер_история.db`, у каждого нового — свой файл: истории разных серверов
     * не смешиваются.
     */
    fun файлИстории(ид: String? = null): String {
        val узел = узелСервера(ид)
        val заданное = текст(узел, "файл_истории")
        if (заданное.isNotEmpty()) return заданное
        val свой = текст(узел, "id")
        return if (свой.isEmpty()) "сервер_история.db" else "сервер_история_$свой.db"
    }

    /** Имя файла техжурнала сервера — по тому же правилу, что и история. */
    fun файлЖурнала(ид: String? = null): String {
        val узел = узелСервера(ид)
        val заданное = текст(узел, "файл_журнала")
        if (заданное.isNotEmpty()) return заданное
        val свой = текст(узел, "id")
        return if (свой.isEmpty()) "журнал.log" else "журнал_$свой.log"
    }

    /**
     * Числовое значение из профиля сервера. Интервалы целей и срок хранения
     * истории старый файл держал в корне, поэтому корень читается как запасной
     * вариант — так настройки с прежних версий работают без правки руками.
     */
    fun числоСервера(ключ: String, поумолчанию: Double, ид: String? = null): Double {
        val узел = найти(ид ?: активныйId)
        if (узел != null && узел.has(ключ)) return число(узел, ключ, поумолчанию)
        if (данные.has(ключ)) return число(данные, ключ, поумолчанию)
        return число(умолчанияСервера(), ключ, поумолчанию)
    }

    fun уведомления(): JSONObject = узел("уведомления")

    fun целое(узел: JSONObject, ключ: String, поумолчанию: Int): Int {
        val значение = узел.opt(ключ)
        return when (значение) {
            is Number -> значение.toInt()
            is String -> значение.toIntOrNull() ?: поумолчанию
            else -> поумолчанию
        }
    }

    fun число(узел: JSONObject, ключ: String, поумолчанию: Double): Double {
        val значение = узел.opt(ключ)
        return when (значение) {
            is Number -> значение.toDouble()
            is String -> значение.replace(',', '.').toDoubleOrNull() ?: поумолчанию
            else -> поумолчанию
        }
    }

    fun да(узел: JSONObject, ключ: String, поумолчанию: Boolean): Boolean {
        val значение = узел.opt(ключ)
        return when (значение) {
            is Boolean -> значение
            is Number -> значение.toInt() != 0
            is String -> значение.equals("true", true) || значение == "1" || значение.equals("да", true)
            else -> поумолчанию
        }
    }

    /** Список ожидаемых кодов ответа сайта — принимает и число, и массив. */
    fun коды(сайт: JSONObject): List<Int> {
        val значение = сайт.opt("ожидать_коды")
        val коды = when (значение) {
            is JSONArray -> (0 until значение.length()).mapNotNull { значение.optInt(it) }
            is Number -> listOf(значение.toInt())
            is String -> значение.split(',', ' ', '/').mapNotNull { it.trim().toIntOrNull() }
            else -> emptyList()
        }
        return коды.ifEmpty { listOf(200) }
    }

    /** Проверка настроек выбранного сервера перед сохранением: список замечаний. */
    fun замечания(): List<String> = замечания(узелСервера())

    /** То же для отдельного профиля — так проверяет себя форма настроек. */
    private fun замечания(узел: JSONObject): List<String> {
        val итог = mutableListOf<String>()
        if (текст(узел, "хост").isEmpty()) итог.add(л("Не указан адрес сервера (хост)"))
        if (текст(узел, "пользователь").isEmpty()) итог.add(л("Не указан пользователь сервера"))
        val порт = целое(узел, "порт", 22)
        if (порт !in 1..65535) итог.add(л("Порт SSH должен быть от 1 до 65535"))
        val свой = текст(узел, "id")
        val пароль = секреты.получить(текст(узел, "секрет_id").ifBlank { свой }) ?: текст(узел, "пароль")
        if (пароль.isEmpty() && текст(узел, "файл_ключа").isEmpty()) {
            итог.add(л("Не указан ни пароль, ни файл ключа — подключиться не получится"))
        }
        спискиИз(узел, "сайты").forEachIndexed { индекс, сайт ->
            if (текст(сайт, "url").isEmpty()) итог.add(л("У сайта №{1} не указан адрес", индекс + 1))
        }
        спискиИз(узел, "порты").forEachIndexed { индекс, порт_ ->
            if (текст(порт_, "хост").isEmpty()) итог.add(л("У порта №{1} не указан хост", индекс + 1))
        }
        return итог
    }


    val автообновленияВключены: Boolean? = null,
    val ротацияЛоговВключена: Boolean? = null,
    val дублиВFstab: List<String> = emptyList(),
    val накопители: List<НакопительАудита> = emptyList(),
    val smartДоступен: Boolean = false,
    val дискиЗдоровье: List<ЗдоровьеДиска> = emptyList(),
) {
    /** Доля занятой подкачки в процентах; null, если подкачки нет. */
    val свопПроцент: Double?
        get() {
            val всего = свопВсего ?: return null
            val занято = свопЗанято ?: return null
            if (всего <= 0L) return null
            return занято.toDouble() * 100.0 / всего
        }

    /** Накопители, которые есть в системе, но нигде не смонтированы. */
    val простаивающиеНакопители: List<НакопительАудита>
        get() = накопители.filter { !it.смонтирован && it.размер > 0L }
}


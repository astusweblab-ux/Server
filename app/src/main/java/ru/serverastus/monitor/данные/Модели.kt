/** Сетевой интерфейс сервера из `/proc/net/dev`: счётчики и ошибки канала. */
data class ИнтерфейсСети(
    val имя: String,
    val принятоБайт: Long = 0L,
    val принятоПакетов: Long = 0L,
    val отправленоБайт: Long = 0L,
    val отправленоПакетов: Long = 0L,
    val ошибкиПриёма: Long = 0L,
    val отброшеноПриёме: Long = 0L,
    val ошибкиОтправки: Long = 0L,
    val отброшеноОтправке: Long = 0L,
    val принятоПакетовЗаОпрос: Long? = null,
    val отброшеноЗаОпрос: Long? = null,
    val ошибкиПриёмаЗаОпрос: Long? = null,
    val ошибкиОтправкиЗаОпрос: Long? = null,
    val состояниеЛинка: String? = null,
    val естьНоситель: Boolean? = null,
    val скоростьМбит: Long? = null,
    val дуплекс: String? = null,
) {
    /** Доля отброшенных при приёме пакетов за всё время работы сервера, в процентах. */
    val доляОтброшенных: Double? get() = if (принятоПакетов > 0) отброшеноПриёме * 100.0 / принятоПакетов else null

    /**
     * Отбросы за последний опрос или null, когда предыдущего опроса нет: судить
     * о потерях по одному снимку нечем, а накопительный счётчик для этого не
     * годится.
     */
    val отбросыЗаОпрос: ОтбросыЗаОпрос?
        get() {
            val отброшено = отброшеноЗаОпрос ?: return null
            val принято = принятоПакетовЗаОпрос ?: 0L
            val доля = when {
                принято > 0L -> отброшено * 100.0 / принято
                отброшено == 0L -> 0.0
                else -> 100.0
            }
            return ОтбросыЗаОпрос(отброшено, принято, доля)
        }

    /** Теряет ли интерфейс пакеты прямо сейчас — по приросту за последний опрос. */
    val потериСейчас: Boolean
        get() {
            val заОпрос = отбросыЗаОпрос ?: return false
            return заОпрос.отброшено >= МИН_ОТБРОШЕННЫХ_ЗА_ОПРОС && заОпрос.доля > ПОРОГ_ОТБРОШЕННЫХ_НОРМА
        }

    /**
     * Ошибки линии за последний опрос. Именно прирост, а не накопительный
     * счётчик: у e1000e он обычно пуст, но у карт, где ошибки были давно,
     * накопленное значение висит годами и о текущем состоянии не говорит.
     */
    val ошибкиКаналаЗаОпрос: Long
        get() = (ошибкиПриёмаЗаОпрос ?: 0L) + (ошибкиОтправкиЗаОпрос ?: 0L)

    /** Ошибки линии растут прямо сейчас. */
    val ошибкиСейчас: Boolean get() = ошибкиКаналаЗаОпрос > 0L

    /**
     * Держит ли интерфейс линк: null — данных нет (снимок без sysfs или
     * виртуальный интерфейс вроде lo, который ядро показывает как `unknown`).
     */
    val линияПоднята: Boolean?
        get() = when (состояниеЛинка) {
            null -> естьНоситель
            "up" -> true
            "unknown" -> null
            else -> false
        }

    /** Живой физический интерфейс: по нему шёл трафик — только про такие и стоит предупреждать. */
    val рабочий: Boolean get() = принятоПакетов > 0L || отправленоПакетов > 0L
}


/** Скорость изменения счётчиков между двумя опросами диагностики. */
data class ТемпСети(
    val секунд: Double = 0.0,
    val соединенийВСекунду: Double = 0.0,
    val ретрансмиссийВМинуту: Double = 0.0,
    val udpПакетовВСекунду: Double = 0.0,
    val сбросовВМинуту: Double = 0.0,
    val доляРетрансмиссий: Double? = null,
    val ретрансмиссийЗаОпрос: Long = 0L,
    val сегментовЗаОпрос: Long = 0L,
) {
    /**
     * Всплеск потерь прямо сейчас: доля повторных передач выше нормы и
     * повторных передач за опрос достаточно, чтобы доля была не случайной.
     * На почти пустом канале 5–10 повторных передач дают несколько процентов
     * сами по себе, поэтому по одному проценту судить нельзя.
     */
    val всплескРетрансмиссий: Boolean
        get() = ретрансмиссийЗаОпрос >= МИН_РЕТРАНСМИССИЙ_НА_ОПРОС &&
            (доляРетрансмиссий ?: 0.0) > ПОРОГ_РЕТРАНСМИССИЙ_ВСПЛЕСК
}

/**
 * Диагностика TCP и UDP: счётчики протоколов из `/proc/net/snmp` и
 * `/proc/net/netstat`, состояния сокетов (`/proc/net/sockstat`, `ss -s`),
 * conntrack, ошибки интерфейсов и текущие параметры ядра.
 * Счётчики накопительные — с момента запуска сервера, поэтому рядом с ними
 * показывается скорость изменения за последний опрос ([темп]).
 */
data class ДиагностикаСети(
    val время: Long = 0L,
    // TCP — /proc/net/snmp (строка Tcp:)
    val сегментовПринято: Long = 0L,
    val сегментовОтправлено: Long = 0L,
    val ретрансмиссий: Long = 0L,
    val ошибокПриёмаСегментов: Long = 0L,
    val сбросовОтправлено: Long = 0L,
    val активныхОткрытий: Long = 0L,
    val пассивныхОткрытий: Long = 0L,
    val неудачныхОткрытий: Long = 0L,
    val сбросовСоединений: Long = 0L,
    val установленоСейчас: Long = 0L,
    val ошибокКонтрольныхСумм: Long = 0L,
    // UDP — /proc/net/snmp (строка Udp:)
    val udpДатаграмм: Long = 0L,
    val udpОтправлено: Long = 0L,
    val udpНетПорта: Long = 0L,
    val udpОшибок: Long = 0L,
    val udpОшибокБуфераПриёма: Long = 0L,
    val udpОшибокБуфераОтправки: Long = 0L,
    // /proc/net/netstat (строка TcpExt:)
    val переполненияОчереди: Long = 0L,
    val отброшеноSYN: Long = 0L,
    val synКуки: Long = 0L,
    val ошибкиПамятиTcp: Long = 0L,
    val давлениеПамяти: Long = 0L,
    val таймаутовTcp: Long = 0L,
    val потерянныхРетрансмиссий: Long = 0L,
    val отброшеноБэклогом: Long = 0L,
    // сокеты
    val сокетовВсего: Long = 0L,
    val сокетовTcp: Long = 0L,
    val сокетовTcpОсиротевших: Long = 0L,
    val сокетовTimeWait: Long = 0L,
    val сокетовUdp: Long = 0L,
    val памятьTcpСтраниц: Long = 0L,
    val сводка: СводкаSs? = null,
    val слушающихПортов: Int? = null,
    // conntrack и параметры ядра
    val conntrack: Long? = null,
    val conntrackМаксимум: Long? = null,
    val параметры: Map<String, String> = emptyMap(),
    val интерфейсы: List<ИнтерфейсСети> = emptyList(),
    // /proc/net/softnet_stat — потери программной очереди приёма (backlog) по
    // всем CPU; null, если сервер не прислал эту часть снимка.
    val потерьОчередиЯдра: Long? = null,
    val темп: ТемпСети? = null,
) {
    /** Доля повторных передач TCP в процентах за всё время работы сервера. */
    val доляРетрансмиссий: Double?
        get() = if (сегментовОтправлено > 0) ретрансмиссий * 100.0 / сегментовОтправлено else null

    /** Все ошибки UDP: потерянные датаграммы и переполнение буферов. */
    val ошибокUdpВсего: Long get() = udpОшибок + udpОшибокБуфераПриёма + udpОшибокБуфераОтправки

    /** Интерфейсы без петли — по ним судят о проблемах канала. */
    val внешниеИнтерфейсы: List<ИнтерфейсСети> get() = интерфейсы.filter { it.имя != "lo" }

    val отброшеноПриёме: Long get() = внешниеИнтерфейсы.sumOf { it.отброшеноПриёме }

    val ошибкиКанала: Long get() = внешниеИнтерфейсы.sumOf { it.ошибкиПриёма + it.ошибкиОтправки }

    val принятоПакетов: Long get() = внешниеИнтерфейсы.sumOf { it.принятоПакетов }

    /** Заполненность таблицы conntrack в процентах. */
    val загруженностьConntrack: Double?
        get() {
            val предел = conntrackМаксимум ?: return null
            val занято = conntrack ?: return null
            return if (предел > 0) занято * 100.0 / предел else null
        }

    /** Размер диапазона локальных портов — сколько соединений можно открыть. */
    val диапазонПортов: Long?
        get() = параметры["net.ipv4.ip_local_port_range"]
            ?.split(Regex("\\s+"))
            ?.mapNotNull { it.trim().toLongOrNull() }
            ?.takeIf { it.size == 2 }
            ?.let { (it[1] - it[0] + 1).coerceAtLeast(0) }

    /** Значение параметра ядра; null, если сервер его не показал. */
    fun параметр(имя: String): String? = параметры[имя]?.takeIf { it.isNotBlank() }

    fun параметрЧисло(имя: String): Long? = параметр(имя)?.trim()?.toLongOrNull()
}


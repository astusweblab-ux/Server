package ru.serverastus.monitor.данные

/**
 * Сравнительный вид адреса сайта: регистр домена и хвостовой «/» не значимы,
 * поэтому «https://Example.com/» и «https://example.com» — один и тот же сайт.
 */
internal fun ключАдреса(адрес: String): String = адрес.trim().lowercase().trimEnd('/')

/** Есть ли в списке элемент с таким же ключом (тем же сравнением, что и при добавлении). */
internal fun <T> естьЭлемент(список: List<T>, ключ: String, получить: (T) -> String): Boolean {
    if (ключ.isEmpty()) return false
    return список.any { получить(it) == ключ }
}

/**
 * Добавляет элемент, если элемента с таким же ключом в списке ещё нет.
 * Возвращает false (и не меняет список), если это повтор или ключ пустой —
 * так мастер и настройки не копят дубли в одном списке проверок.
 */
internal fun <T> добавитьБезДубля(список: MutableList<T>, элемент: T, ключ: (T) -> String): Boolean {
    val нужный = ключ(элемент)
    if (естьЭлемент(список, нужный) { ключ(it) }) return false
    if (нужный.isEmpty()) return false
    список.add(элемент)
    return true
}

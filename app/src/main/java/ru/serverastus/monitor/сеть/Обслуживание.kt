/**
 * Оценка обслуживания сервера. Смысл тот же, что у оценки сети: показать одним
 * числом, всё ли в порядке с профилактикой — обновления, службы, журналы, время,
 * диски. Штрафы подобраны так, чтобы «работающий, но забытый» сервер получал
 * заметно меньше 100, а ухоженный — не ниже 90.
 */
fun оценитьОбслуживание(данные: Обслуживание?): ОценкаОбслуживания {
    if (данные == null) return ОценкаОбслуживания()

    val важные = mutableListOf<РекомендацияОбслуживания>()
    val советы = mutableListOf<РекомендацияОбслуживания>()
    var балл = 100

    fun добавить(
        очки: Int,
        заголовок: String,
        пояснение: String,
        команда: String = "",
        важная: Boolean = очки >= 8,
    ) {
        балл -= очки
        val рекомендация = РекомендацияОбслуживания(заголовок, пояснение, команда, важная)
        if (важная) важные.add(рекомендация) else советы.add(рекомендация)
    }

    // 1. Сбойные службы — прямой сигнал, что что-то отвалилось. Первые три
    // стоят по 8 очков, дальше штраф не растёт: обычно это одна причина.
    if (данные.сбойныеЮниты.isNotEmpty()) {
        val перечень = данные.сбойныеЮниты.take(3).joinToString(", ")
        добавить(
            minOf(24, 8 * данные.сбойныеЮниты.size),
            л("Сбойных служб: {1}", данные.сбойныеЮниты.size),
            л(
                "systemd считает эти юниты упавшими: {1}. Посмотрите причину и перезапустите — часто это служба, которую выключили, но пакет остался установлен.",
                перечень,
            ),
            "systemctl --failed",
        )
    }

    // 2. Ожидание перезагрузки: либо просит система, либо установлено ядро
    // новее работающего (после обновления ядра перезагрузка обязательна).
    if (данные.перезагрузкаТребуется || данные.перезагрузкаЯдра) {
        val причина = when {
            данные.перезагрузкаЯдра && данные.ядроУстановлено.isNotEmpty() ->
                л("Работает ядро {1}, а установлено {2}.", данные.ядро, данные.ядроУстановлено)
            данные.перезагрузкаЯдра -> л("Установлено ядро новее работающего ({1}).", данные.ядро)
            else -> л("Система оставила флаг /var/run/reboot-required.")
        }
        добавить(
            12,
            л("Сервер ждёт перезагрузки"),
            л("{1} Часть обновлений безопасности вступает в силу только после перезагрузки.", причина),
            "sudo reboot",
        )
    }

    // 3. Обновления безопасности — самое важное из обновлений.
    val безопасности = данные.обновленийБезопасности ?: 0
    val кУстановке = данные.обновленийСейчас ?: 0
    val прочих = maxOf(0, кУстановке - безопасности)
    if (безопасности > 0) {
        добавить(
            10,
            л("Обновления безопасности: {1}", безопасности),
            л("Это исправления уязвимостей. Их ставят в первую очередь, отдельно от остальных обновлений."),
            "sudo apt update && sudo apt upgrade",
        )
    }
    if (прочих > 0) {
        // Обычные обновления без исправлений уязвимостей — плановое дело, а не
        // проблема: штраф начинается только там, где обновления копятся месяцами.
        val очки = when {
            прочих >= 50 -> 10
            прочих >= 20 -> 4
            else -> 0
        }
        val пояснение = if (очки == 0)
            л("Исправлений уязвимостей среди них нет — это плановое обслуживание. Поставьте их при удобном случае, отдельного срочного окна не требуется.")
        else
            л("Накопились обновления пакетов. Чем дольше тянуть, тем больше шансов на конфликт версий.")
        добавить(
            очки,
            л("Прочих обновлений: {1}", прочих),
            пояснение,
            "sudo apt update && sudo apt upgrade",
            важная = очки >= 8,
        )
    }

    // 4. Место на разделе с данными.
    данные.дискЗанято?.let { занято ->
        when {
            занято >= 90.0 -> добавить(
                20,
                л("Диск заполнен на {1} %", один(занято)),
                л(
                    "Свободно {1} из {2}. При заполнении выше 90 % часть служб перестаёт писать данные и падает.",
                    форматБайт(данные.дискСвободно),
                    форматБайт(данные.дискВсего),
                ),
                "du -xh --max-depth=1 / | sort -h | tail -n 15",
            )
            занято >= 80.0 -> добавить(
                10,
                л("Диск заполнен на {1} %", один(занято)),
                л(
                    "Свободно {1}. Пора почистить старые журналы, резервные копии и кэш пакетов.",
                    форматБайт(данные.дискСвободно),
                ),
                "sudo journalctl --vacuum-size=200M",
            )
            занято >= 70.0 -> добавить(
                4,
                л("Диск заполнен на {1} %", один(занято)),
                л("Запас ещё есть, но растёт он обычно незаметно. Полезно посмотреть, что занимает место."),
                "du -xh --max-depth=1 / | sort -h | tail -n 15",
                важная = false,
            )
        }
    }

    // 5. Журнал systemd и каталог /var/log. Каталог считается без журнала:
    // сумма `du -sb /var/log` включает его целиком, и без вычета один и тот же
    // объём выглядел бы дважды — и в строке журнала, и в строке каталога.
    данные.размерЖурнала?.let { размер ->
        when {
            размер >= ПОРОГ_ЖУРНАЛА_ТРЕВОГА_БАЙТ -> добавить(
                8,
                л("Журнал systemd занимает {1}", форматБайт(размер)),
                л("Это только журнал ядра и служб. Его стоит ограничить — иначе он съест диск раньше, чем вы это заметите."),
                "sudo journalctl --vacuum-size=300M",
            )
            размер >= ПОРОГ_ЖУРНАЛА_БАЙТ -> добавить(
                4,
                л("Журнал systemd занимает {1}", форматБайт(размер)),
                л("Размер уже заметный. Предел в 300 МБ хранит историю за пару недель и держит диск свободным."),
                "sudo journalctl --vacuum-size=300M",
                важная = false,
            )
        }
    }
    when (важностьОбычныхЛогов(данные)) {
        8 -> добавить(
            8,
            л("/var/log без журнала занимает {1}", форматБайт(обычныеЛоги(данные))),
            крупныеЛогиПояснение(данные.крупныеЛоги) +
                л("Скорее всего один из сервисов пишет слишком подробно."),
            "sudo du -sh /var/log/* | sort -h | tail -n 10",
        )
        4 -> добавить(
            4,
            л("/var/log без журнала занимает {1}", форматБайт(обычныеЛоги(данные))),
            л("Каталог журналов вырос. Проверьте ротацию и подробность логирования у отдельных служб."),
            "sudo du -sh /var/log/* | sort -h | tail -n 10",
            важная = false,
        )
    }

    // 6. Точное время — от него зависят метки в логах, сертификаты и fail2ban.
    if (данные.ntpСинхронизирован == false) {
        добавить(
            6,
            л("Время не синхронизировано"),
            л("Часы сервера расходятся с точным временем: поедут метки в журналах, а проверка сертификатов и блокировки fail2ban начнут ошибаться."),
            "sudo systemctl enable --now systemd-timesyncd",
        )
    }

    // 7. Подкачка: постоянная занятость свопа означает нехватку памяти.
    данные.свопПроцент?.let { процент ->
        when {
            процент >= 80.0 -> добавить(
                8,
                л("Подкачка занята на {1} %", один(процент)),
                л("Активно используется файл подкачки — значит памяти не хватает и сервер заметно тормозит на диск. Посмотрите, кто её занимает."),
                "ps aux --sort=-%mem | head -n 10",
            )
            процент >= 50.0 -> добавить(
                4,
                л("Подкачка занята на {1} %", один(процент)),
                л("Часть данных вытеснена на диск. Не критично, но стоит присмотреться к потреблению памяти."),
                "ps aux --sort=-%mem | head -n 10",
                важная = false,
            )
        }
    }

    // 8. Мусор от пакетов и автоматизация обновлений.
    данные.удалитьПакетов?.let { пакеты ->
        if (пакеты > ПОРОГ_АВТООЧИСТКИ_ПАКЕТОВ) {
            // Очки не снимаются: список кандидатов на autoremove — не проблема
            // сервера, а информация apt, которую ещё нужно проверить руками.
            добавить(
                0,
                л("APT считает {1} кандидатами на автоматическое удаление", пакетовПрописью(пакеты.toLong())),
                л("Это оценка apt, а не приговор: столько пакетов помечены как автоматически установленные и остались без хозяина — обычно устаревшие библиотеки (Node.js, X11, perl). Среди них бывает ядро для отката или библиотека живого проекта, поэтому перед удалением рекомендуется проверить список."),
                "sudo apt autoremove --dry-run",
                важная = false,
            )
        }
    }
    if (данные.автообновленияВключены == false) {
        добавить(
            4,
            л("Автообновления безопасности выключены"),
            л("unattended-upgrades устанавливает исправления уязвимостей сам, без вашего участия. Для сервера, к которому нет ежедневного доступа, это самая дешёвая страховка."),
            "sudo apt install unattended-upgrades && sudo dpkg-reconfigure -plow unattended-upgrades",
            важная = false,
        )
    }
    if (данные.ротацияЛоговВключена == false) {
        добавить(
            4,
            л("Ротация журналов выключена"),
            л("logrotate.timer неактивен: файлы в /var/log будут расти, пока не закончится место."),
            "sudo systemctl enable --now logrotate.timer",
            важная = false,
        )
    }

    // 9. Здоровье дисков: без smartmontools узнать его невозможно, а это
    // единственный способ увидеть, что диск собирается умереть.
    if (!данные.smartДоступен) {
        добавить(
            3,
            л("Нет контроля здоровья дисков"),
            л("Не установлен smartmontools, поэтому состояние накопителей неизвестно. Пакет маленький, но показывает износ и переназначенные сектора."),
            "sudo apt install smartmontools",
            важная = false,
        )
    }
    // Диск без ответа SMART (пустой статус) — это не диагноз, а отсутствие
    // данных: тревогу поднимает только явный отказ.
    val больные = данные.дискиЗдоровье.filter { it.статус.isNotBlank() && !it.вПорядке }
    if (больные.isNotEmpty()) {
        val перечень = больные.joinToString(", ") { л("{1} ({2})", it.устройство, it.статус.ifBlank { л("нет ответа") }) }
        добавить(
            30,
            л("Проблемы со здоровьем диска"),
            л(
                "SMART сообщает о неисправности: {1}. Такой диск может отказать в любой момент — сделайте копию данных и готовьте замену.",
                перечень,
            ),
            "sudo smartctl -a /dev/sda",
        )
    }
    val температуры = данные.дискиЗдоровье.mapNotNull { it.температура }
    if (температуры.isNotEmpty() && температуры.max() >= 60.0) {
        добавить(
            3,
            л("Диск нагрет до {1} °C", один(температуры.max())),
            л("Выше 60 °C накопитель живёт заметно меньше. Проверьте продув корпуса и температуру в помещении."),
            "sudo smartctl -A /dev/sda | grep Temperature",
            важная = false,
        )
    }

    // 10. Повторяющиеся точки монтирования в fstab: лишняя строка путает
    // порядок монтирования и мешает ручной правке файла.
    if (данные.дублиВFstab.isNotEmpty()) {
        добавить(
            2,
            л("Повторяющиеся точки монтирования в fstab"),
            л(
                "В /etc/fstab несколько строк на одну точку ({1}). Оставьте одну запись — так меньше шансов запутаться при переезде или замене диска.",
                данные.дублиВFstab.joinToString(", "),
            ),
            "cat /etc/fstab",
            важная = false,
        )
    }

    // 11. Долгая загрузка — обычно виноват лишний автозапуск служб.
    данные.загрузкаСекунд?.let { секунды ->
        if (секунды > ПОРОГ_ЗАГРУЗКИ_СЕКУНД) {
            добавить(
                2,
                л("Загрузка занимает {1} с", один(секунды)),
                л("Долгий старт обычно означает службы, которые ждут недоступную сеть или диск. Долгую загрузку видно в детальном отчёте systemd."),
                "systemd-analyze blame",
                важная = false,
            )
        }
    }

    // 12. Накопитель, который есть в системе, но нигде не используется —
    // не ошибка, а полезная находка: место можно занять.
    val простаивающие = данные.простаивающиеНакопители
    if (простаивающие.isNotEmpty()) {
        val перечень = простаивающие.joinToString(", ") { л("{1} ({2})", it.устройство, форматБайт(it.размер)) }
        добавить(
            0,
            л("Не используется накопитель: {1}", простаивающие.joinToString(", ") { it.устройство }),
            л(
                "Накопители {1} в системе есть, но ни один раздел на них не смонтирован. На свободном диске удобно держать резервные копии.",
                перечень,
            ),
            "lsblk -o NAME,SIZE,FSTYPE,MOUNTPOINT",
            важная = false,
        )
    }

    val итог = балл.coerceIn(0, 100)
    val уровень = when {
        итог >= 90 -> УРОВЕНЬ_ОБСЛУЖИВАНИЯ_ОТЛИЧНО
        итог >= 75 -> УРОВЕНЬ_ОБСЛУЖИВАНИЯ_НОРМАЛЬНО
        итог >= 60 -> УРОВЕНЬ_ОБСЛУЖИВАНИЯ_ВНИМАНИЕ
        else -> УРОВЕНЬ_ОБСЛУЖИВАНИЯ_ПЛОХО
    }
    return ОценкаОбслуживания(итог, уровень, важные + советы)
}

/**
 * Размер /var/log без журнала systemd: `du -sb /var/log` считает журнал внутри
 * каталога, поэтому без вычета он попадал бы в обе строки — и в «Журнал systemd»,
 * и в «Каталог /var/log».
 */
fun обычныеЛоги(данные: Обслуживание): Long? {
    val логи = данные.размерЛогов ?: return null
    return maxOf(0L, логи - (данные.размерЖурнала ?: 0L))
}

/** Доля раздела, занятая журналами без systemd, в процентах. */
fun доляОбычныхЛогов(данные: Обслуживание): Double? {
    val логи = обычныеЛоги(данные) ?: return null
    val всего = данные.дискВсего ?: return null
    if (всего <= 0L) return null
    return логи.toDouble() * 100.0 / всего
}

/**
 * Насколько каталог /var/log без журнала systemd заслуживает внимания: 0 — всё в
 * порядке, 4 — совет, 8 — важная находка. Учитываются и объём, и доля раздела:
 * пара сотен мегабайт на диске в сотни гигабайт — это норма, а не замечание.
 */
fun важностьОбычныхЛогов(данные: Обслуживание): Int {
    val логи = обычныеЛоги(данные) ?: return 0
    val доля = доляОбычныхЛогов(данные)
    return when {
        логи >= ПОРОГ_ЛОГОВ_ТРЕВОГА_БАЙТ && (доля == null || доля >= ДОЛЯ_ЛОГОВ_ТРЕВОГА) -> 8
        логи >= ПОРОГ_ЛОГОВ_ВНИМАНИЕ_БАЙТ && (доля == null || доля >= ДОЛЯ_ЛОГОВ_СОВЕТ) -> 4
        else -> 0
    }
}

/** Пояснение к большой папке журналов: перечисляет крупнейшие файлы. */
private fun крупныеЛогиПояснение(логи: List<КрупныйЛог>): String {
    if (логи.isEmpty()) return ""
    val перечень = логи.take(3).joinToString(", ") { л("{1} ({2})", it.путь, форматБайт(it.байт)) }
    return л("Крупнее всего: {1}. ", перечень)
}

private fun один(значение: Double): String =
    if (значение == значение.toLong().toDouble()) значение.toLong().toString()
    else String.format(Locale.ROOT, "%.1f", значение)

/**
 * Текстовый отчёт по обслуживанию — то, что уходит в буфер обмена кнопкой
 * «Скопировать отчёт» и что удобно переслать администратору сервера.
 */
fun отчётОбслуживания(данные: Обслуживание, оценка: ОценкаОбслуживания): String {
    val строки = mutableListOf<String>()
    fun строка(текст: String = "") = строки.add(текст)

    строка(л("Обслуживание сервера · {1}", полнаяДата(данные.время)))
    строка(л("Оценка: {1} из 100 — {2}", оценка.балл, л(оценка.уровень)))
    строка()

    строка(л("Система"))
    строка(л("  Ядро: {1}", данные.ядро.ifBlank { л("нет данных") }))
    if (данные.ядроУстановлено.isNotEmpty() && данные.ядроУстановлено != данные.ядро) {
        строка(л("  Установлено ядро: {1}", данные.ядроУстановлено))
    }
    строка(л("  Аптайм: {1}", форматАптайм(данные.аптайм)))
    данные.загрузкаСекунд?.let { строка(л("  Загрузка: {1} с", один(it))) }
    if (данные.перезагрузкаТребуется) строка(л("  Требуется перезагрузка: да"))
    строка()

    строка(л("Обновления пакетов"))
    строка(л("  Доступно обновлений: {1}", данные.обновленийВсего ?: 0))
    строка(л("  Из них безопасности: {1}", данные.обновленийБезопасности ?: 0))
    данные.обновленийСейчас?.let { строка(л("  apt установит сейчас: {1}", it)) }
    строка(л(
        "  Установлено пакетов: {1}, автозапуск юнитов: {2}",
        данные.пакетовУстановлено ?: 0,
        данные.автозапускЮнитов ?: 0,
    ))
    строка(л("  Кандидатов на автоматическое удаление: {1}", данные.удалитьПакетов ?: 0))
    строка(л("  Автообновления безопасности: {1}", естьНет(данные.автообновленияВключены)))
    строка(л("  Ротация журналов: {1}", естьНет(данные.ротацияЛоговВключена)))
    строка()

    строка(л("Журналы и место"))
    строка(л("  Журнал systemd: {1}", форматБайт(данные.размерЖурнала)))
    строка(л("  Каталог /var/log: {1}", форматБайт(данные.размерЛогов)))
    for (лог in данные.крупныеЛоги.take(6)) {
        строка(л("    {1}  {2}", форматБайт(лог.байт), лог.путь))
    }
    val занято = данные.дискЗанято?.let { один(it) } ?: "?"
    строка(л(
        "  Раздел занят на {1} % (свободно {2} из {3})",
        занято,
        форматБайт(данные.дискСвободно),
        форматБайт(данные.дискВсего),
    ))
    строка()

    строка(л("Службы и время"))
    строка(л("  Сбойных юнитов: {1}", данные.сбойныеЮниты.size) +
        if (данные.сбойныеЮниты.isEmpty()) "" else л(" — {1}", данные.сбойныеЮниты.joinToString(", ")))
    строка(л("  Синхронизация времени: {1}", естьНет(данные.ntpСинхронизирован)))
    if (данные.службаВремени.isNotEmpty()) строка(л("  Служба времени: {1}", данные.службаВремени))
    if (данные.часовойПояс.isNotEmpty()) строка(л("  Часовой пояс: {1}", данные.часовойПояс))
    данные.свопПроцент?.let { строка(л("  Подкачка занята на {1} %", один(it))) }
    строка()

    строка(л("Накопители"))
    for (диск in данные.накопители) {
        val статус = if (диск.смонтирован) л("смонтирован") else л("не используется")
        строка(л("  {1} — {2}, {3}{4}", диск.устройство, форматБайт(диск.размер), статус,
            if (диск.модель.isBlank()) "" else л(", {1}", диск.модель)))
    }
    if (данные.дискиЗдоровье.isEmpty()) {
        строка(л("  SMART: {1}", if (данные.smartДоступен) л("данных нет") else л("нет smartmontools")))
    } else {
        for (диск in данные.дискиЗдоровье) {
            val части = mutableListOf<String>()
            диск.статус.takeIf { it.isNotBlank() }?.let { части.add(it) }
            диск.переназначеноСекторов?.takeIf { it > 0L }?.let { части.add(л("переназначено секторов: {1}", it)) }
            диск.температура?.let { части.add(л("{1} °C", один(it))) }
            диск.часовРаботы?.let { части.add(л("наработка {1} ч", форматСчётчик(it))) }
            строка(л("  {1}: {2}", диск.устройство, части.joinToString(", ").ifBlank { л("нет данных") }))
        }
    }
    if (данные.дублиВFstab.isNotEmpty()) {
        строка(л("  Повторы в /etc/fstab: {1}", данные.дублиВFstab.joinToString(", ")))
    }
    строка()

    строка(л("Рекомендации ({1})", оценка.рекомендации.size))
    if (оценка.рекомендации.isEmpty()) {
        строка(л("  Замечаний нет — сервер обслуживается аккуратно."))
    } else {
        for (рекомендация in оценка.рекомендации) {
            строка(л("• {1}", рекомендация.заголовок))
            строка(л("  {1}", рекомендация.пояснение))
            if (рекомендация.команда.isNotBlank()) строка(л("  Команда: {1}", рекомендация.команда))
        }
    }
    return строки.joinToString("\n")
}

private fun естьНет(значение: Boolean?): String = when (значение) {
    true -> л("включено")
    false -> л("выключено")
    else -> л("нет данных")
}

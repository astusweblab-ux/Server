/** Разбирает пары строк `заголовки`/`значения` — формат `/proc/net/snmp` и `/proc/net/netstat`. */
fun разобратьПарыСтрок(текст: String?): Map<String, Map<String, Long>> {
    val заголовки = mutableMapOf<String, List<String>>()
    val итог = mutableMapOf<String, MutableMap<String, Long>>()
    for (строка in (текст ?: "").split("\n")) {
        val чист = строка.trim()
        val двоеточие = чист.indexOf(':')
        if (двоеточие <= 0) continue
        val префикс = чист.substring(0, двоеточие).trim()
        val поля = чист.substring(двоеточие + 1).trim().split(РАЗДЕЛИТЕЛЬ_ПОЛЕЙ).filter { it.isNotEmpty() }
        if (поля.isEmpty()) continue
        if (поля.first().toLongOrNull() == null) {
            заголовки[префикс] = поля
            continue
        }
        val имена = заголовки[префикс] ?: continue
        val значения = итог.getOrPut(префикс) { mutableMapOf() }
        поля.forEachIndexed { индекс, поле ->
            val имя = имена.getOrNull(индекс) ?: return@forEachIndexed
            поле.toLongOrNull()?.let { значения[имя] = it }
        }
    }
    return итог
}

/** Разбирает `/proc/net/sockstat` и `/proc/net/sockstat6`: `TCP: inuse 20 orphan 0 tw 18`. */
fun разобратьСокеты(текст: String?): Map<String, Map<String, Long>> {
    val итог = mutableMapOf<String, MutableMap<String, Long>>()
    for (строка in (текст ?: "").split("\n")) {
        val чист = строка.trim()
        val двоеточие = чист.indexOf(':')
        if (двоеточие <= 0) continue
        val префикс = чист.substring(0, двоеточие).trim()
        val поля = чист.substring(двоеточие + 1).trim().split(РАЗДЕЛИТЕЛЬ_ПОЛЕЙ).filter { it.isNotEmpty() }
        val значения = итог.getOrPut(префикс) { mutableMapOf() }
        var индекс = 0
        while (индекс + 1 < поля.size) {
            val значение = поля[индекс + 1].toLongOrNull()
            if (значение == null) {
                индекс += 1
                continue
            }
            значения[поля[индекс]] = значение
            индекс += 2
        }
    }
    return итог
}

/** Разбирает сводку из `ss -s`. */
fun разобратьСс(текст: String?): СводкаSs? {
    var нашлось = false
    val сводка = СводкаSs()
    var итог = сводка
    for (строка in (текст ?: "").split("\n")) {
        val чист = строка.trim()
        if (чист.startsWith("Total:")) {
            нашлось = true
            итог = итог.copy(всего = чист.substringAfter(':').trim().toLongOrNull() ?: 0L)
        } else if (чист.startsWith("TCP:")) {
            нашлось = true
            fun поле(шаблон: String): Long? = Regex(шаблон).find(чист)?.groupValues?.get(1)?.toLongOrNull()
            итог = итог.copy(
                tcp = поле("^TCP:\\s+(\\d+)") ?: итог.tcp,
                установлено = поле("estab\\s+(\\d+)") ?: итог.установлено,
                закрыто = поле("closed\\s+(\\d+)") ?: итог.закрыто,
                осиротело = поле("orphaned\\s+(\\d+)") ?: итог.осиротело,
                timeWait = поле("timewait\\s+(\\d+)") ?: итог.timeWait,
            )
        }
    }
    return if (нашлось) итог else null
}

/** Разбирает `/proc/net/dev` — счётчики и ошибки сетевых интерфейсов. */
fun разобратьИнтерфейсы(текст: String?): List<ИнтерфейсСети> {
    val итог = mutableListOf<ИнтерфейсСети>()
    for (строка in (текст ?: "").split("\n")) {
        val двоеточие = строка.indexOf(':')
        if (двоеточие <= 0) continue
        val имя = строка.substring(0, двоеточие).trim()
        if (имя.isEmpty() || имя == "Inter-|") continue
        val числа = строка.substring(двоеточие + 1).trim()
            .split(РАЗДЕЛИТЕЛЬ_ПОЛЕЙ)
            .mapNotNull { it.toLongOrNull() }
        if (числа.size < 16) continue
        итог.add(
            ИнтерфейсСети(
                имя = имя,
                принятоБайт = числа[0],
                принятоПакетов = числа[1],
                ошибкиПриёма = числа[2],
                отброшеноПриёме = числа[3],
                отправленоБайт = числа[8],
                отправленоПакетов = числа[9],
                ошибкиОтправки = числа[10],
                отброшеноОтправке = числа[11],
            )
        )
    }
    return итог
}

/**
 * Разбирает снимок каталога `/sys/class/net`: состояние линка, наличие носителя,
 * скорость и режим дуплекса. Прочерк вместо значения ядро отдаёт, когда файла
 * нет или читать его нельзя (скорости у интерфейса без линка не бывает) —
 * такой прочерк считается отсутствующим значением.
 */
fun разобратьЛинки(текст: String?): Map<String, СведенияОЛинке> {
    val итог = linkedMapOf<String, СведенияОЛинке>()
    for (строка in (текст ?: "").split("\n")) {
        val поля = строка.trim().split(РАЗДЕЛИТЕЛЬ_ПОЛЕЙ)
        if (поля.size < 5) continue
        val имя = поля[0]
        if (имя.isEmpty() || имя.contains('/')) continue
        fun значение(поле: String): String? = поле.takeIf { it.isNotEmpty() && it != "-" }?.lowercase()
        итог[имя] = СведенияОЛинке(
            состояние = значение(поля[1]),
            носитель = when (поля[2]) {
                "1" -> true
                "0" -> false
                else -> null
            },
            скоростьМбит = поля[3].toLongOrNull()?.takeIf { it > 0L },
            дуплекс = значение(поля[4]),
        )
    }
    return итог
}

/**
 * Разбирает `/proc/net/softnet_stat`: сумма (по всем CPU) пакетов, отброшенных
 * из-за переполнения программной очереди приёма — второе поле каждой строки,
 * шестнадцатеричное. Единственный точный способ понять, виновата ли в потерях
 * на интерфейсе очередь `netdev_max_backlog`, а не что-то ещё (файрвол,
 * мультикаст без подписчика).
 */
fun разобратьПотериЯдра(текст: String?): Long? {
    var итог = 0L
    var найдено = false
    for (строка in (текст ?: "").split("\n")) {
        val поля = строка.trim().split(РАЗДЕЛИТЕЛЬ_ПОЛЕЙ).filter { it.isNotEmpty() }
        if (поля.size < 2) continue
        val значение = поля[1].toLongOrNull(16) ?: continue
        итог += значение
        найдено = true
    }
    return if (найдено) итог else null
}

/** Разбирает вывод `sysctl -e`: строки «ключ = значение», ошибки игнорируются. */
fun разобратьПараметры(текст: String?): Map<String, String> {
    val итог = linkedMapOf<String, String>()
    for (строка in (текст ?: "").split("\n")) {
        val чист = строка.trim()
        val равно = чист.indexOf('=')
        if (равно <= 0) continue
        val ключ = чист.substring(0, равно).trim()
        if (!ключ.startsWith("net.")) continue
        итог[ключ] = чист.substring(равно + 1).trim().replace(РАЗДЕЛИТЕЛЬ_ПОЛЕЙ, " ")
    }
    return итог
}

/** Собирает диагностику сети из частей ответа на `СНИМОК_СЕТЬ`. */
fun собратьДиагностикуСети(частиВход: List<String>, сейчас: Long): ДиагностикаСети {
    var части = частиВход
    if (части.isNotEmpty() && части[0].startsWith("export")) части = части.drop(1)
    if (части.size < 7) {
        throw ОшибкаСвязи(л("Сервер вернул неполный ответ на запрос диагностики сети"), обрезано = true)
    }

    val snmp = разобратьПарыСтрок(части[0])
    val tcp = snmp["Tcp"].orEmpty()
    val udp = snmp["Udp"].orEmpty()
    if (tcp["OutSegs"] == null && tcp["InSegs"] == null) {
        throw ОшибкаСвязи(л("Сервер вернул неполный ответ на запрос диагностики сети"), обрезано = true)
    }

    val расширенные = разобратьПарыСтрок(части[1])
    val tcpExt = расширенные["TcpExt"].orEmpty()

    val сокеты = разобратьСокеты(части[2])
    val tcpСокеты = сокеты["TCP"].orEmpty()
    val udpСокеты = сокеты["UDP"].orEmpty()
    val udpСокеты6 = сокеты["UDP6"].orEmpty()

    val conntrack = части[6].split("\n").map { it.trim() }.filter { it.isNotEmpty() }
    val параметры = if (части.size > 7) разобратьПараметры(части[7]).toMutableMap() else mutableMapOf()

    // Состояние линка приходит отдельной частью снимка: в `/proc/net/dev` его
    // нет, а именно оно отличает живую линию от оборванной.
    val линки = if (части.size > 9) разобратьЛинки(части[9]) else emptyMap()

    val занятоConntrack = conntrack.getOrNull(0)?.toLongOrNull()
    val пределConntrack = conntrack.getOrNull(1)?.toLongOrNull()
    if (занятоConntrack != null) параметры["net.netfilter.nf_conntrack_count"] = занятоConntrack.toString()
    if (пределConntrack != null) параметры["net.netfilter.nf_conntrack_max"] = пределConntrack.toString()

    return ДиагностикаСети(
        время = сейчас,
        сегментовПринято = tcp["InSegs"] ?: 0L,
        сегментовОтправлено = tcp["OutSegs"] ?: 0L,
        ретрансмиссий = tcp["RetransSegs"] ?: 0L,
        ошибокПриёмаСегментов = tcp["InErrs"] ?: 0L,
        сбросовОтправлено = tcp["OutRsts"] ?: 0L,
        активныхОткрытий = tcp["ActiveOpens"] ?: 0L,
        пассивныхОткрытий = tcp["PassiveOpens"] ?: 0L,
        неудачныхОткрытий = tcp["AttemptFails"] ?: 0L,
        сбросовСоединений = tcp["EstabResets"] ?: 0L,
        установленоСейчас = tcp["CurrEstab"] ?: 0L,
        ошибокКонтрольныхСумм = tcp["InCsumErrors"] ?: 0L,
        udpДатаграмм = udp["InDatagrams"] ?: 0L,
        udpОтправлено = udp["OutDatagrams"] ?: 0L,
        udpНетПорта = udp["NoPorts"] ?: 0L,
        udpОшибок = udp["InErrors"] ?: 0L,
        udpОшибокБуфераПриёма = udp["RcvbufErrors"] ?: 0L,
        udpОшибокБуфераОтправки = udp["SndbufErrors"] ?: 0L,
        переполненияОчереди = tcpExt["ListenOverflows"] ?: 0L,
        отброшеноSYN = tcpExt["ListenDrops"] ?: 0L,
        synКуки = tcpExt["SyncookiesSent"] ?: 0L,
        ошибкиПамятиTcp = tcpExt["TCPAbortOnMemory"] ?: 0L,
        давлениеПамяти = tcpExt["TCPMemoryPressures"] ?: 0L,
        таймаутовTcp = tcpExt["TCPTimeouts"] ?: 0L,
        потерянныхРетрансмиссий = tcpExt["TCPLostRetransmit"] ?: 0L,
        отброшеноБэклогом = tcpExt["TCPBacklogDrop"] ?: 0L,
        сокетовВсего = сокеты["sockets"]?.get("used") ?: 0L,
        сокетовTcp = tcpСокеты["inuse"] ?: 0L,
        сокетовTcpОсиротевших = tcpСокеты["orphan"] ?: 0L,
        сокетовTimeWait = tcpСокеты["tw"] ?: 0L,
        сокетовUdp = (udpСокеты["inuse"] ?: 0L) + (udpСокеты6["inuse"] ?: 0L),
        памятьTcpСтраниц = tcpСокеты["mem"] ?: 0L,
        сводка = разобратьСс(части[3]),
        слушающихПортов = части[4].split("\n").lastOrNull { it.isNotBlank() }?.trim()?.toIntOrNull(),
        conntrack = занятоConntrack,
        conntrackМаксимум = пределConntrack,
        параметры = параметры,
        интерфейсы = разобратьИнтерфейсы(части[5]).map { интерфейс ->
            val линк = линки[интерфейс.имя] ?: return@map интерфейс
            интерфейс.copy(
                состояниеЛинка = линк.состояние,
                естьНоситель = линк.носитель,
                скоростьМбит = линк.скоростьМбит,
                дуплекс = линк.дуплекс,
            )
        },
        потерьОчередиЯдра = if (части.size > 8) разобратьПотериЯдра(части[8]) else null,
    )
}

/**
 * Считает скорость изменения счётчиков между двумя опросами. Пока второго
 * опроса нет (или прошло меньше секунды), снимок возвращается без темпов.
 */
fun добавитьТемп(текущая: ДиагностикаСети, прежняя: ДиагностикаСети?): ДиагностикаСети {
    if (прежняя == null) return текущая
    val секунд = (текущая.время - прежняя.время).toDouble()
    if (секунд < 1.0) return текущая

    fun дельта(новое: Long, старое: Long): Long = (новое - старое).coerceAtLeast(0L)

    val открытий = дельта(
        текущая.активныхОткрытий + текущая.пассивныхОткрытий,
        прежняя.активныхОткрытий + прежняя.пассивныхОткрытий,
    )
    val ретрансмиссий = дельта(текущая.ретрансмиссий, прежняя.ретрансмиссий)
    val сегментов = дельта(текущая.сегментовОтправлено, прежняя.сегментовОтправлено)
    val udp = дельта(
        текущая.udpДатаграмм + текущая.udpОтправлено,
        прежняя.udpДатаграмм + прежняя.udpОтправлено,
    )
    val сбросов = дельта(текущая.сбросовОтправлено, прежняя.сбросовОтправлено)

    // По интерфейсам считаем прирост между опросами: накопительный счётчик
    // отброшенных растёт и от служебных кадров, для которых у ядра нет
    // обработчика (LLDP, IEEE1905.1, 802.3 XID от роутера), поэтому о потерях
    // именно сейчас можно судить только по дельте.
    val прежниеИнтерфейсы = прежняя.интерфейсы.associateBy { it.имя }
    val интерфейсы = текущая.интерфейсы.map { интерфейс ->
        val было = прежниеИнтерфейсы[интерфейс.имя] ?: return@map интерфейс
        интерфейс.copy(
            принятоПакетовЗаОпрос = дельта(интерфейс.принятоПакетов, было.принятоПакетов),
            отброшеноЗаОпрос = дельта(интерфейс.отброшеноПриёме, было.отброшеноПриёме),
            ошибкиПриёмаЗаОпрос = дельта(интерфейс.ошибкиПриёма, было.ошибкиПриёма),
            ошибкиОтправкиЗаОпрос = дельта(интерфейс.ошибкиОтправки, было.ошибкиОтправки),
        )
    }

    return текущая.copy(
        интерфейсы = интерфейсы,
        темп = ТемпСети(
            секунд = секунд,
            соединенийВСекунду = открытий / секунд,
            ретрансмиссийВМинуту = ретрансмиссий * 60.0 / секунд,
            udpПакетовВСекунду = udp / секунд,
            сбросовВМинуту = сбросов * 60.0 / секунд,
            доляРетрансмиссий = if (сегментов >= 50) ретрансмиссий * 100.0 / сегментов else null,
            ретрансмиссийЗаОпрос = ретрансмиссий,
            сегментовЗаОпрос = сегментов,
        )
    )
}

/** Оценка состояния TCP и UDP: балл 0–100, уровень и советы по настройке ядра. */
fun оценитьСеть(данные: ДиагностикаСети?): ОценкаСети {
    if (данные == null) return ОценкаСети()

    val важные = mutableListOf<РекомендацияСети>()
    val советы = mutableListOf<РекомендацияСети>()
    var балл = 100

    fun добавить(
        очки: Int,
        заголовок: String,
        пояснение: String,
        команда: String = "",
        важная: Boolean = очки >= 10,
    ) {
        балл -= очки
        val рекомендация = РекомендацияСети(заголовок, пояснение, команда, важная)
        if (важная) важные.add(рекомендация) else советы.add(рекомендация)
    }

    // 1. Повторные передачи — главный признак потерь в канале. Основной
    // показатель — накопительная доля за всё время работы сервера: она
    // устойчива. Мгновенная доля (за последний опрос) учитывается, только
    // если повторных передач за опрос было достаточно много, иначе на почти
    // пустом канале всплеск из нескольких сегментов даёт ложную тревогу.
    val доляНакопленная = данные.доляРетрансмиссий
    val всплеск = данные.темп?.всплескРетрансмиссий == true
    val доляРетрансмиссий = if (всплеск) {
        maxOf(данные.темп?.доляРетрансмиссий ?: 0.0, доляНакопленная ?: 0.0)
    } else {
        доляНакопленная
    }
    if (доляРетрансмиссий != null && доляРетрансмиссий > ПОРОГ_РЕТРАНСМИССИЙ_ВСПЛЕСК) {
        добавить(
            30,
            л("Повторные передачи TCP: {1} %", два(доляРетрансмиссий)),
            л("Ядро повторно отправляет сегменты — значит пакеты теряются по пути. Проверьте загрузку канала, ошибки интерфейса ниже и качество линии у провайдера."),
            "sysctl -w net.ipv4.tcp_mtu_probing=1",
        )
    } else if (доляРетрансмиссий != null && доляРетрансмиссий > ПОРОГ_РЕТРАНСМИССИЙ_НОРМА) {
        добавить(
            12,
            л("Повышенная доля повторных передач: {1} %", два(доляРетрансмиссий)),
            л(
                "До {1} % считается нормой. Значение выше говорит о начинающихся потерях в канале или о перегрузке сетевой карты.",
                два(ПОРОГ_РЕТРАНСМИССИЙ_НОРМА),
            ),
            "",
            важная = false,
        )
    }
    if (данные.потерянныхРетрансмиссий > 0 && (доляРетрансмиссий ?: 0.0) > ПОРОГ_РЕТРАНСМИССИЙ_НОРМА) {
        добавить(
            10,
            л("Потеряно повторных передач: {1}", данные.потерянныхРетрансмиссий),
            л("Сегменты так и не дошли до получателя после всех попыток — соединения рвутся. Вместе с высокой долей повторных передач это указывает на перегруженный канал."),
            "sysctl -w net.ipv4.tcp_mtu_probing=1",
        )
    }

    // 2. Очередь входящих соединений: сервер не успевает принимать подключения.
    when {
        данные.переполненияОчереди > 0 || данные.отброшеноSYN >= 100 || данные.отброшеноБэклогом > 0 ->
            добавить(
                20,
                л("Переполнение очереди входящих соединений"),
                л(
                    "Не принято соединений: {1}, отброшено SYN: {2}. Клиенты видят таймаут при подключении. Увеличьте очередь и проверьте, успевает ли приложение отвечать.",
                    данные.переполненияОчереди,
                    данные.отброшеноSYN + данные.отброшеноБэклогом,
                ),
                "sysctl -w net.core.somaxconn=4096 net.ipv4.tcp_max_syn_backlog=4096",
            )
        данные.отброшеноSYN > 0 ->
            добавить(
                3,
                л("Отброшено SYN: {1} (за время работы сервера)", данные.отброшеноSYN),
                л("Единичные отбросы из очереди прослушивания — обычно всплеск подключений от сканеров. Если счётчик быстро растёт, увеличьте очередь."),
                "sysctl -w net.core.somaxconn=4096",
                важная = false,
            )
    }

    // 3. SYN-cookies включаются, когда очередь «полуоткрытых» соединений переполнена.
    if (данные.synКуки > 0) {
        добавить(
            15,
            л("Включалась защита SYN-cookies: {1} раз", данные.synКуки),
            л("Ядро включило SYN-cookies из-за переполнения очереди SYN — чаще всего это перебор портов (в том числе со стороны fail2ban) или флуд. Соединения при этом теряют часть параметров."),
            "sysctl -w net.ipv4.tcp_synack_retries=2 net.ipv4.tcp_max_syn_backlog=4096",
        )
    }

    // 4. Нехватка памяти под TCP-буферы.
    if (данные.ошибкиПамятиTcp > 0 || данные.давлениеПамяти > 0) {
        val пределПамяти = данные.параметр("net.ipv4.tcp_mem")?.split(РАЗДЕЛИТЕЛЬ_ПОЛЕЙ)?.lastOrNull()
        val новоеЗначение = пределПамяти?.toLongOrNull()?.let { (it * 1.5).toLong() }
        добавить(
            15,
            л("Ядру не хватало памяти под TCP"),
            л(
                "Закрытий по нехватке памяти: {1}, срабатываний ограничителя: {2}. Соединения обрываются досрочно.",
                данные.ошибкиПамятиTcp,
                данные.давлениеПамяти,
            ),
            if (новоеЗначение != null) л("sysctl -w net.ipv4.tcp_mem=\"{1} {2} {3}\"", пределПамяти, пределПамяти, новоеЗначение) else "",
        )
    }

    // 5. Ошибки UDP — потерянные датаграммы и переполнение буферов.
    if (данные.ошибокUdpВсего > 0) {
        добавить(
            12,
            л("Ошибки приёма UDP: {1}", данные.ошибокUdpВсего),
            л(
                "Датаграммы теряются или не помещаются в буфер: ошибок {1}, переполнений буфера приёма {2}, буфера отправки {3}. Для DNS, WireGuard и игровых сервисов это прямые потери запросов.",
                данные.udpОшибок,
                данные.udpОшибокБуфераПриёма,
                данные.udpОшибокБуфераОтправки,
            ),
            "sysctl -w net.core.rmem_max=16777216 net.core.rmem_default=262144",
        )
    }

    // 6. Таблица соединений (conntrack) — при переполнении рвутся все новые соединения.
    val занятостьConntrack = данные.загруженностьConntrack
    if (занятостьConntrack != null && занятостьConntrack >= 90.0) {
        добавить(
            20,
            л("Таблица соединений заполнена на {1}", форматПроцента(занятостьConntrack)),
            л(
                "Записей {1} из {2}. При заполнении ядро перестанет принимать новые соединения — сайт будет недоступен.",
                данные.conntrack,
                данные.conntrackМаксимум,
            ),
            л("sysctl -w net.netfilter.nf_conntrack_max={1}", (данные.conntrackМаксимум ?: 0L) * 2),
        )
    } else if (занятостьConntrack != null && занятостьConntrack >= 70.0) {
        добавить(
            8,
            л("Таблица соединений заполнена на {1}", форматПроцента(занятостьConntrack)),
            л(
                "Записей {1} из {2}. Запас есть, но при всплеске посетителей он закончится — стоит поднять предел заранее.",
                данные.conntrack,
                данные.conntrackМаксимум,
            ),
            л("sysctl -w net.netfilter.nf_conntrack_max={1}", (данные.conntrackМаксимум ?: 0L) * 2),
            важная = false,
        )
    }

    // 7. Накопление соединений в состоянии TIME_WAIT — кончаются свободные порты.
    val лимитTimeWait = ((данные.диапазонПортов ?: 20_000L) / 2).coerceAtLeast(1_000L)
    if (данные.сокетовTimeWait > лимитTimeWait) {
        добавить(
            10,
            л("TIME_WAIT: {1} соединений", данные.сокетовTimeWait),
            л(
                "Свободных локальных портов {1}, половина занята соединениями в состоянии TIME_WAIT — новые исходящие подключения могут не открываться.",
                данные.диапазонПортов,
            ),
            "sysctl -w net.ipv4.tcp_fin_timeout=30 net.ipv4.tcp_tw_reuse=1",
        )
    } else if (данные.сокетовTimeWait > 500 && данные.параметрЧисло("net.ipv4.tcp_tw_reuse") == 0L) {
        добавить(
            5,
            л("TIME_WAIT: {1} соединений при выключенном переиспользовании", данные.сокетовTimeWait),
            л("Соединения висят в TIME_WAIT, а net.ipv4.tcp_tw_reuse=0 — порты не переиспользуются. Для сервера с большим числом коротких подключений переиспользование безопасно и полезно."),
            "sysctl -w net.ipv4.tcp_tw_reuse=1",
            важная = false,
        )
    }

    // 8. Алгоритм управления перегрузкой: BBR заметно быстрее cubic на длинных каналах.
    val управлениеПерегрузкой = данные.параметр("net.ipv4.tcp_congestion_control")
    if (управлениеПерегрузкой != null && управлениеПерегрузкой != "bbr") {
        val доступные = данные.параметр("net.ipv4.tcp_available_congestion_control").orEmpty()
        val командаQdisc = if (данные.параметр("net.core.default_qdisc") == "fq") "" else " net.core.default_qdisc=fq"
        добавить(
            5,
            л("Управление перегрузкой TCP: {1}", управлениеПерегрузкой),
            if (доступные.split(РАЗДЕЛИТЕЛЬ_ПОЛЕЙ).contains("bbr")) {
                л(
                    "Модуль BBR уже доступен. BBR держит скорость на каналах с потерями, тогда как {1} резко снижает её при любой потере пакета.",
                    управлениеПерегрузкой,
                )
            } else {
                л("BBR не загружен (доступно: {1}). Загрузите модуль ядра — на Ubuntu он в пакете linux-modules-extra, при ошибке modprobe поставьте его: apt-get install -y linux-modules-extra-${'$'}(uname -r)", доступные)
            },
            л("modprobe tcp_bbr && sysctl -w net.ipv4.tcp_congestion_control=bbr{1}", командаQdisc),
            важная = false,
        )
    }

    // 9. Проблемы на самих интерфейсах: потери в очереди карты и ошибки линии.
    // Счётчик отброшенных накопительный и растёт в том числе от служебных кадров,
    // для которых у ядра нет обработчика, поэтому о потерях судят по приросту за
    // последний опрос, а не по доле с момента загрузки сервера.
    val очередьКартыТек = данные.параметрЧисло("net.core.netdev_max_backlog") ?: 0L
    for (интерфейс in данные.внешниеИнтерфейсы) {
        val заОпрос = интерфейс.отбросыЗаОпрос
        if (интерфейс.потериСейчас && заОпрос != null) {
            if (данные.потерьОчередиЯдра == 0L && очередьКартыТек >= 4096L) {
                // /proc/net/softnet_stat не показывает ни одной потери на программной
                // очереди приёма, а очередь и так уже увеличена — поднимать
                // netdev_max_backlog ещё выше не поможет. Так ядро считает кадры, для
                // которых нет обработчика: служебные кадры роутера (LLDP, IEEE1905.1,
                // 802.3 XID) и пакеты, отклонённые файрволом. Для сервисов сервера это
                // не потеря данных.
                добавить(
                    5,
                    л("Отброшено пакетов на «{1}»: {2} за опрос", интерфейс.имя, заОпрос.отброшено),
                    л(
                        "Это {1} из {2} пакетов, принятых за последний опрос, но программная очередь приёма (/proc/net/softnet_stat) потерь не показывает, а net.core.netdev_max_backlog уже {3} — дело не в переполнении очереди. Чаще всего так выглядят кадры, для которых у ядра нет обработчика: служебные кадры роутера (LLDP, IEEE1905.1, 802.3 XID) и пакеты, отклонённые файрволом. Проверить, что именно отбрасывается (пока идёт захват, счётчик не растёт — так устроено ядро):",
                        форматПроцента(заОпрос.доля),
                        форматСчётчик(заОпрос.принято),
                        очередьКартыТек,
                    ),
                    л("tcpdump -i {1} -e -nn -c 20 'not (ip or arp or ip6)'", интерфейс.имя),
                    важная = false,
                )
            } else {
                добавить(
                    10,
                    л("Отброшено пакетов на «{1}»: {2} за опрос", интерфейс.имя, заОпрос.отброшено),
                    л(
                        "Это {1} из {2} пакетов, принятых за последний опрос — ядро не успевает разбирать очередь сетевой карты. Увеличьте net.core.netdev_max_backlog и число очередей карты.",
                        форматПроцента(заОпрос.доля),
                        форматСчётчик(заОпрос.принято),
                    ),
                    л("sysctl -w net.core.netdev_max_backlog={1}", maxOf(4096L, очередьКартыТек * 2)),
                )
            }
        } else {
            val доляНакопленная = интерфейс.доляОтброшенных
            if (интерфейс.отброшеноПриёме > 0 && доляНакопленная != null && доляНакопленная > ПОРОГ_ОТБРОШЕННЫХ_НОРМА) {
                // Потерь сейчас нет, а счётчик набран раньше: обрывы линии,
                // перезагрузки и служебный шум роутера. Балл за прошлое не снимаем.
                val сейчас = if (заОпрос != null) {
                    л("Потерь за последний опрос нет — счётчик набран раньше и на работу сервисов сейчас не влияет. Обнулится при перезагрузке сервера.")
                } else {
                    л("Потерь за один снимок не измерить — доля появится со следующего опроса.")
                }
                добавить(
                    0,
                    л("Отброшено пакетов на «{1}»: {2} за всё время работы", интерфейс.имя, интерфейс.отброшеноПриёме),
                    л("Накопительно это {1} принятых пакетов. {2}", форматПроцента(доляНакопленная), сейчас),
                    важная = false,
                )
            }
        }
        val ошибкиЗаОпрос = интерфейс.ошибкиКаналаЗаОпрос
        if (ошибкиЗаОпрос > 0L) {
            добавить(
                10,
                л("Ошибки линии на «{1}»: {2} за опрос", интерфейс.имя, ошибкиЗаОпрос),
                л(
                    "Ошибки приёма и отправки растут прямо сейчас — за последний опрос их {1}. Обычно это битые кадры: проверьте кабель, порт коммутатора и настройки скорости/дуплекса.",
                    ошибкиЗаОпрос,
                ),
            )
        } else if (интерфейс.ошибкиПриёма + интерфейс.ошибкиОтправки > 0L) {
            // Ошибки были когда-то (кабель дёргали, линк поднимался заново) —
            // за прошлое балл не снимаем, но и молчать не стоит.
            добавить(
                0,
                л("Ошибки линии на «{1}»: {2} за всё время работы", интерфейс.имя, интерфейс.ошибкиПриёма + интерфейс.ошибкиОтправки),
                л(
                    "Ошибок приёма {1}, отправки {2}, но за последний опрос не прибавилось ни одной — счётчик набран раньше. Следим за приростом, а не за накопленным значением.",
                    интерфейс.ошибкиПриёма,
                    интерфейс.ошибкиОтправки,
                ),
                важная = false,
            )
        }
        if (интерфейс.рабочий && интерфейс.линияПоднята == false) {
            добавить(
                10,
                л("Линк на «{1}» опущен", интерфейс.имя),
                л("Интерфейс уже передавал данные, а сейчас носителя нет: оборван кабель, выключен порт коммутатора или сработала защита сервиса восстановления линка. Проверьте кабель и порт."),
            )
        }
    }

    // 10. Параметры, которые стоит подтянуть на любом сервере.
    val очередьКарты = данные.параметрЧисло("net.core.netdev_max_backlog")
    if (очередьКарты != null && очередьКарты < 1000) {
        добавить(
            5,
            л("Малая очередь приёма сетевой карты: {1}", очередьКарты),
            л("При всплеске трафика ядро начнёт отбрасывать пакеты ещё до обработки. Значение 4096 подходит для гигабитного канала."),
            "sysctl -w net.core.netdev_max_backlog=4096",
            важная = false,
        )
    }
    val буферПриёма = данные.параметрЧисло("net.core.rmem_max")
    val буферОтправки = данные.параметрЧисло("net.core.wmem_max")
    if (буферПриёма != null && буферПриёма < 16_777_216L) {
        добавить(
            3,
            л("Максимальный буфер приёма всего {1}", форматБайт(буферПриёма)),
            л("Соединения с большой задержкой (мобильные клиенты, другие города) не смогут разогнаться — буфера не хватает. Для сервера с сайтами хватает 16 МиБ."),
            "sysctl -w net.core.rmem_max=16777216 net.core.wmem_max=16777216",
            важная = false,
        )
    } else if (буферОтправки != null && буферОтправки < 16_777_216L) {
        добавить(
            3,
            л("Максимальный буфер отправки всего {1}", форматБайт(буферОтправки)),
            л("Отдача крупных ответов ограничена размером буфера — поднимите предел для дальних клиентов."),
            "sysctl -w net.core.wmem_max=16777216",
            важная = false,
        )
    }
    if (данные.параметрЧисло("net.ipv4.tcp_slow_start_after_idle") == 1L) {
        добавить(
            3,
            л("Включён медленный старт после простоя"),
            л("После каждой паузы соединение снова начинает с малой скорости. Для сайтов с короткими запросами выгоднее выключить: соединения уже «разогреты»."),
            "sysctl -w net.ipv4.tcp_slow_start_after_idle=0",
            важная = false,
        )
    }
    val синОчередь = данные.параметрЧисло("net.ipv4.tcp_max_syn_backlog") ?: 0L
    val общаяОчередь = данные.параметрЧисло("net.core.somaxconn") ?: 0L
    if (общаяОчередь > 0 && синОчередь > 0 && синОчередь < общаяОчередь) {
        добавить(
            3,
            л("Очередь SYN ({1}) меньше очереди соединений ({2})", синОчередь, общаяОчередь),
            л("При всплеске подключений узкое место — очередь «полуоткрытых» соединений. Значения стоит уравнять."),
            "sysctl -w net.ipv4.tcp_max_syn_backlog=4096",
            важная = false,
        )
    }
    val проверкаМолчащих = данные.параметрЧисло("net.ipv4.tcp_keepalive_time")
    if (проверкаМолчащих != null && проверкаМолчащих > 600L) {
        добавить(
            0,
            л("TCP-проверка молчащих соединений — {1} с", проверкаМолчащих),
            л("Два часа сервер считает оборванное соединение живым. Для веб-сервера разумно 300 секунд — быстрее освобождаются сокеты и память."),
            "sysctl -w net.ipv4.tcp_keepalive_time=300",
            важная = false,
        )
    }
    val завершение = данные.параметрЧисло("net.ipv4.tcp_fin_timeout")
    if (завершение != null && завершение > 30L) {
        добавить(
            0,
            л("Закрытие соединения — {1} с", завершение),
            л("Столько ждёт последний FIN. 30 секунд уменьшает число «зависших» сокетов без риска потерять данные."),
            "sysctl -w net.ipv4.tcp_fin_timeout=30",
            важная = false,
        )
    }
    if (данные.параметрЧисло("net.ipv4.tcp_fastopen") == 0L) {
        добавить(
            0,
            л("Быстрое открытие TCP (TFO) выключено"),
            л("С ним клиенты отдают первый запрос сразу вместе с SYN — сайт отвечает на один обмен пакетами быстрее. Включайте, если сайт доступен по HTTPS."),
            "sysctl -w net.ipv4.tcp_fastopen=3",
            важная = false,
        )
    }
    if (данные.udpНетПорта > 0) {
        добавить(
            0,
            л("UDP на закрытые порты: {1}", данные.udpНетПорта),
            л("Датаграммы пришли на порт, который никто не слушает — обычно так выглядят сканирования. Если это должен быть рабочий сервис, проверьте, запущен ли он."),
            важная = false,
        )
    }

    val итог = балл.coerceIn(0, 100)
    val уровень = when {
        итог >= 85 -> УРОВЕНЬ_СЕТИ_ОТЛИЧНО
        итог >= 70 -> УРОВЕНЬ_СЕТИ_НОРМАЛЬНО
        итог >= 50 -> УРОВЕНЬ_СЕТИ_ВНИМАНИЕ
        else -> УРОВЕНЬ_СЕТИ_ПЛОХО
    }
    return ОценкаСети(итог, уровень, важные + советы)
}

/**
 * Текстовый отчёт по диагностике — то, что копируется кнопкой «Скопировать»
 * и что удобно переслать администратору сервера или сохранить в переписку.
 */
/**
 * Короткая строка о линке для карточки интерфейса и текстового отчёта:
 * состояние линии, скорость и режим дуплекса. Пусто, когда данных нет —
 * у виртуальных интерфейсов (мосты, docker0, lo) физического линка не бывает.
 */
fun описаниеЛинка(интерфейс: ИнтерфейсСети): String {
    val куски = mutableListOf<String>()
    when (интерфейс.линияПоднята) {
        true -> куски.add(л("линия UP"))
        false -> куски.add(л("линия DOWN"))
        null -> Unit
    }
    интерфейс.скоростьМбит?.let { куски.add(л("{1} Мбит/с", it)) }
    when (интерфейс.дуплекс) {
        "full" -> куски.add(л("полный дуплекс"))
        "half" -> куски.add(л("полудуплекс"))
    }
    return куски.joinToString(", ")
}

fun отчётСети(данные: ДиагностикаСети, оценка: ОценкаСети): String {
    val строки = mutableListOf<String>()
    fun строка(текст: String = "") = строки.add(текст)

    строка(л("Диагностика сети сервера · {1}", полнаяДата(данные.время)))
    строка(л("Оценка: {1} из 100 — {2}", оценка.балл, л(оценка.уровень)))
    строка()

    строка(л("TCP (счётчики с момента запуска сервера)"))
    строка(л("  Сегментов принято: {1}", форматСчётчик(данные.сегментовПринято)))
    строка(л("  Сегментов отправлено: {1}", форматСчётчик(данные.сегментовОтправлено)))
    строка(л("  Повторных передач: {1}", форматСчётчик(данные.ретрансмиссий)))
    данные.доляРетрансмиссий?.let { строка(л("  Доля повторных передач: {1} %", два(it))) }
    данные.темп?.доляРетрансмиссий?.let {
        строка(
            л(
                "  За последний опрос: повторных передач {1} из {2} сегментов — {3} %",
                форматСчётчик(данные.темп.ретрансмиссийЗаОпрос),
                форматСчётчик(данные.темп.сегментовЗаОпрос),
                два(it),
            )
        )
    }
    строка(л("  Соединений установлено сейчас: {1}", форматСчётчик(данные.установленоСейчас)))
    строка(л(
        "  Открытий активных/пассивных: {1} / {2}",
        форматСчётчик(данные.активныхОткрытий),
        форматСчётчик(данные.пассивныхОткрытий),
    ))
    строка(л("  Неудачных открытий: {1}", форматСчётчик(данные.неудачныхОткрытий)))
    строка(л("  Сбросов соединений: {1}", форматСчётчик(данные.сбросовСоединений)))
    строка(л("  Ошибок приёма сегментов: {1}", форматСчётчик(данные.ошибокПриёмаСегментов)))
    строка(л("  Ошибок контрольных сумм: {1}", форматСчётчик(данные.ошибокКонтрольныхСумм)))
    данные.темп?.let {
        строка(л(
            "  Новых соединений: {1}/с, повторных передач: {2}/мин",
            два(it.соединенийВСекунду),
            два(it.ретрансмиссийВМинуту),
        ))
    }
    строка()

    строка("UDP")
    строка(л("  Датаграмм принято: {1}", форматСчётчик(данные.udpДатаграмм)))
    строка(л("  Датаграмм отправлено: {1}", форматСчётчик(данные.udpОтправлено)))
    строка(л("  На закрытые порты: {1}", форматСчётчик(данные.udpНетПорта)))
    строка(л("  Ошибок приёма: {1}", форматСчётчик(данные.udpОшибок)))
    строка(л("  Переполнений буфера приёма/отправки: {1} / {2}", данные.udpОшибокБуфераПриёма, данные.udpОшибокБуфераОтправки))
    данные.темп?.let { строка(л("  Пакетов: {1}/с", два(it.udpПакетовВСекунду))) }
    строка()

    строка(л("Очереди, сбои и сокеты"))
    строка(л("  Переполнений очереди прослушивания: {1}", данные.переполненияОчереди))
    строка(л("  Отброшено SYN: {1}, в бэклоге: {2}", данные.отброшеноSYN, данные.отброшеноБэклогом))
    строка(л("  SYN-cookies включены: {1}", данные.synКуки))
    строка(л(
        "  Закрытий из-за нехватки памяти: {1}, срабатываний ограничителя: {2}",
        данные.ошибкиПамятиTcp,
        данные.давлениеПамяти,
    ))
    строка(л(
        "  Таймаутов TCP: {1}, потеряно повторных передач: {2}",
        форматСчётчик(данные.таймаутовTcp),
        данные.потерянныхРетрансмиссий,
    ))
    строка(л("  Сокетов всего: {1}, TCP: {2}, UDP: {3}", данные.сокетовВсего, данные.сокетовTcp, данные.сокетовUdp))
    строка(л("  TIME_WAIT: {1}, осиротевших: {2}", данные.сокетовTimeWait, данные.сокетовTcpОсиротевших))
    строка(л("  Слушающих портов: {1}", данные.слушающихПортов ?: "—"))
    данные.загруженностьConntrack?.let {
        строка(л("  Таблица соединений: {1} из {2} ({3})", данные.conntrack, данные.conntrackМаксимум, форматПроцента(it)))
    }
    строка()

    if (данные.интерфейсы.isNotEmpty()) {
        строка(л("Интерфейсы"))
        for (интерфейс in данные.интерфейсы) {
            val доля = интерфейс.доляОтброшенных?.let { л(" ({1} отброшено)", форматПроцента(it)) }.orEmpty()
            val заОпрос = интерфейс.отбросыЗаОпрос?.let {
                л(
                    ", за опрос отброшено {1} из {2} пакетов — {3}",
                    форматСчётчик(it.отброшено),
                    форматСчётчик(it.принято),
                    форматПроцента(it.доля),
                )
            }.orEmpty()
            строка(
                л(
                    "  {1}: принято {2}, отправлено {3}, пакетов {4}, отброшено {5}{6}{7}",
                    интерфейс.имя,
                    форматБайт(интерфейс.принятоБайт),
                    форматБайт(интерфейс.отправленоБайт),
                    форматСчётчик(интерфейс.принятоПакетов),
                    форматСчётчик(интерфейс.отброшеноПриёме),
                    доля,
                    заОпрос,
                ),
            )
            val состояние = listOf(
                описаниеЛинка(интерфейс),
                if (интерфейс.ошибкиКаналаЗаОпрос > 0L) {
                    л("ошибок за опрос {1}", форматСчётчик(интерфейс.ошибкиКаналаЗаОпрос))
                } else {
                    ""
                },
            ).filter { it.isNotEmpty() }
            if (состояние.isNotEmpty()) строка(л("     Состояние: {1}", состояние.joinToString(", ")))
        }
        строка()
    }

    val параметры = ПОКАЗЫВАЕМЫЕ_ПАРАМЕТРЫ.mapNotNull { (ключ, подпись) ->
        данные.параметр(ключ)?.let { л("{1} ({2}): {3}", подпись, ключ, it) }
    }
    if (параметры.isNotEmpty()) {
        строка(л("Параметры ядра"))
        параметры.forEach { строка("  $it") }
        строка()
    }

    if (оценка.рекомендации.isEmpty()) {
        строка(л("Рекомендаций нет — параметры сети в порядке."))
    } else {
        строка(л("Рекомендации (по важности)"))
        for ((номер, совет) in оценка.рекомендации.withIndex()) {
            val пометка = if (совет.важная) л("[важно] ") else ""
            строка(л("  {1}. {2}{3}", номер + 1, пометка, совет.заголовок))
            строка(л("     {1}", совет.пояснение))
            if (совет.команда.isNotBlank()) строка(л("     Команда: {1}", совет.команда))
        }
    }
    return строки.joinToString("\n")
}

/** Проценты для текста рекомендаций — без зависимости от локали. */
private fun форматПроцента(значение: Double): String =
    if (значение < 10) два(значение) + " %" else л("{1} %", значение.toInt())

/** Два знака после запятой — для долей и процентов в текстах. */
private fun два(значение: Double): String = String.format(Locale.ROOT, "%.2f", значение)

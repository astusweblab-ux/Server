/** Вкладка «Сеть»: диагностика TCP и UDP, оценка состояния и советы по оптимизации. */
@Composable
fun ЭкранСети(снимок: Снимок, движок: Движок) {
    val данные = снимок.сеть
    val оценка = снимок.оценкаСети ?: оценитьСеть(данные)
    val буфер = LocalClipboardManager.current
    val контекст = LocalContext.current

    Прокрутка {
        Карточка(
            заголовок = л("Состояние сети"),
            подзаголовок = л("счётчики TCP и UDP, очереди и параметры ядра сервера"),
            справа = {
                Ярлычок(
                    текст = if (данные == null) л("нет данных") else л(оценка.уровень),
                    цвет = цветУровня(оценка.уровень),
                )
            },
        ) {
            if (данные == null) {
                Пусто(л("Данные появятся после первого опроса сети (по умолчанию раз в 30 секунд)"))
                Spacer(Modifier.height(8.dp))
                Row(verticalAlignment = Alignment.CenterVertically) {
                    if (снимок.опросИдёт) {
                        Крутилка()
                        Spacer(Modifier.width(10.dp))
                    }
                    TextButton(onClick = { движок.обновитьСетьСейчас() }, enabled = !снимок.опросИдёт) {
                        Текст(л("Обновить сейчас"))
                    }
                }
                return@Карточка
            }

            Row(verticalAlignment = Alignment.CenterVertically) {
                Кольцо(
                    значение = оценка.балл.toDouble(),
                    подпись = л("сеть"),
                    текст = оценка.балл.toString(),
                    цвет = цветУровня(оценка.уровень),
                )
                Spacer(Modifier.width(14.dp))
                Column(modifier = Modifier.weight(1f)) {
                    Текст(
                        текст = л("Оценка: {1} из 100", оценка.балл),
                        color = цветУровня(оценка.уровень),
                        style = MaterialTheme.typography.titleMedium,
                    )
                    Spacer(Modifier.height(4.dp))
                    Текст(
                        текст = пояснениеУровня(оценка.уровень),
                        color = Палитра.ТУСКЛЫЙ,
                        style = MaterialTheme.typography.bodySmall,
                    )
                    Spacer(Modifier.height(4.dp))
                    Текст(
                        текст = л("Обновлено: {1}", времяДата(данные.время)),
                        color = Палитра.ТУСКЛЫЙ,
                        style = MaterialTheme.typography.labelSmall,
                    )
                }
            }

            Spacer(Modifier.height(12.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                Плитка(
                    подпись = л("Соединений сейчас"),
                    значение = форматСчётчик(данные.установленоСейчас),
                    modifier = Modifier.weight(1f),
                )
                Плитка(
                    подпись = л("Новых соединений"),
                    значение = данные.темп?.let { л("{1}/с", форматЧисло(it.соединенийВСекунду)) } ?: "—",
                    modifier = Modifier.weight(1f),
                )
            }
            Spacer(Modifier.height(8.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                Плитка(
                    подпись = л("Повторных передач"),
                    значение = доляРетрансмиссий(данные)?.let { форматПроцент(it) } ?: "—",
                    цвет = цветРетрансмиссий(доляРетрансмиссий(данные)),
                    modifier = Modifier.weight(1f),
                )
                Плитка(
                    подпись = л("Пакетов UDP"),
                    значение = данные.темп?.let { л("{1}/с", форматЧисло(it.udpПакетовВСекунду)) } ?: "—",
                    modifier = Modifier.weight(1f),
                )
            }

            Spacer(Modifier.height(10.dp))
            Row(verticalAlignment = Alignment.CenterVertically) {
                if (снимок.опросИдёт) {
                    Крутилка()
                    Spacer(Modifier.width(10.dp))
                }
                TextButton(onClick = { движок.обновитьСетьСейчас() }, enabled = !снимок.опросИдёт) {
                    Текст(л("Обновить сейчас"))
                }
                TextButton(onClick = {
                    буфер.setText(AnnotatedString(отчётСети(данные, оценка)))
                    Toast.makeText(контекст, л("Отчёт скопирован в буфер обмена"), Toast.LENGTH_SHORT).show()
                }) {
                    Текст(л("Скопировать отчёт"))
                }
            }
        }

        if (данные != null) {
            КарточкаПротокола(данные)
            КарточкаСокетов(данные)
            КарточкаИнтерфейсов(данные)
            КарточкаПараметров(данные)
            КарточкаРекомендаций(оценка, данные, буфер, контекст)
        }
    }
}

@Composable
private fun КарточкаПротокола(данные: ДиагностикаСети) {
    Карточка(
        заголовок = л("Протоколы TCP и UDP"),
        подзаголовок = л("счётчики накопительные — с момента запуска сервера"),
        справа = { Ярлычок(л("сокетов: {1}", форматСчётчик(данные.сокетовTcp + данные.сокетовUdp)), Палитра.СИНИЙ) },
    ) {
        val доля = доляРетрансмиссий(данные)
        СтрокаЗначения(л("Сегментов принято"), форматСчётчик(данные.сегментовПринято))
        СтрокаЗначения(л("Сегментов отправлено"), форматСчётчик(данные.сегментовОтправлено))
        СтрокаЗначения(
            подпись = л("Повторных передач"),
            значение = л("{1} · {2}", форматСчётчик(данные.ретрансмиссий), форматПроцент(доля)),
            цвет = цветРетрансмиссий(доля),
        )
        СтрокаЗначения(л("Открытий активных / пассивных"), л("{1} / {2}", данные.активныхОткрытий, данные.пассивныхОткрытий))
        СтрокаЗначения(л("Неудачных открытий"), форматСчётчик(данные.неудачныхОткрытий))
        СтрокаЗначения(л("Сбросов соединений"), форматСчётчик(данные.сбросовСоединений))
        СтрокаЗначения(л("Ошибок приёма сегментов"), форматСчётчик(данные.ошибокПриёмаСегментов))
        СтрокаЗначения(л("Ошибок контрольных сумм"), форматСчётчик(данные.ошибокКонтрольныхСумм))
        данные.темп?.let { темп ->
            Spacer(Modifier.height(6.dp))
            СтрокаЗначения(л("Повторных передач в минуту"), форматЧисло(темп.ретрансмиссийВМинуту))
            СтрокаЗначения(л("Сбросов в минуту"), форматЧисло(темп.сбросовВМинуту))
            СтрокаЗначения(л("Замер за"), л("{1} с", форматЧисло(темп.секунд)))
            СтрокаЗначения(
                подпись = л("Повторных передач за замер"),
                значение = л(
                    "{1} из {2} сегментов",
                    форматСчётчик(темп.ретрансмиссийЗаОпрос),
                    форматСчётчик(темп.сегментовЗаОпрос),
                ) +
                    (доляВсплеска(данные)?.let { л(" · {1}", форматПроцент(it)) } ?: ""),
                цвет = цветРетрансмиссий(доляВсплеска(данные)),
            )
        }

        Spacer(Modifier.height(12.dp))
        Текст("UDP", color = Палитра.ТУСКЛЫЙ, style = MaterialTheme.typography.labelSmall)
        Spacer(Modifier.height(6.dp))
        СтрокаЗначения(л("Датаграмм принято"), форматСчётчик(данные.udpДатаграмм))
        СтрокаЗначения(л("Датаграмм отправлено"), форматСчётчик(данные.udpОтправлено))
        СтрокаЗначения(
            подпись = л("На закрытые порты"),
            значение = форматСчётчик(данные.udpНетПорта),
            цвет = if (данные.udpНетПорта > 0) Палитра.ЖЁЛТЫЙ else Палитра.ТЕКСТ,
        )
        СтрокаЗначения(
            подпись = л("Ошибок приёма"),
            значение = форматСчётчик(данные.udpОшибок),
            цвет = if (данные.udpОшибок > 0) Палитра.КРАСНЫЙ else Палитра.ТЕКСТ,
        )
        СтрокаЗначения(
            подпись = л("Переполнений буфера"),
            значение = л("{1} / {2}", данные.udpОшибокБуфераПриёма, данные.udpОшибокБуфераОтправки),
            цвет = if (данные.ошибокUdpВсего > 0) Палитра.ОРАНЖЕВЫЙ else Палитра.ТЕКСТ,
        )
    }
}

@Composable
private fun КарточкаСокетов(данные: ДиагностикаСети) {
    val лимитTimeWait = ((данные.диапазонПортов ?: 20_000L) / 2).coerceAtLeast(1_000L)
    Карточка(
        заголовок = л("Очереди, сбои и таблицы"),
        подзаголовок = л("переполнения, память TCP и таблица соединений"),
    ) {
        СтрокаЗначения(
            подпись = л("Переполнений очереди прослушивания"),
            значение = форматСчётчик(данные.переполненияОчереди),
            цвет = if (данные.переполненияОчереди > 0) Палитра.КРАСНЫЙ else Палитра.ТЕКСТ,
        )
        СтрокаЗначения(
            подпись = л("Отброшено SYN"),
            значение = л("{1} · бэклог {2}", форматСчётчик(данные.отброшеноSYN), форматСчётчик(данные.отброшеноБэклогом)),
            цвет = if (данные.отброшеноSYN + данные.отброшеноБэклогом > 0) Палитра.ОРАНЖЕВЫЙ else Палитра.ТЕКСТ,
        )
        СтрокаЗначения(
            подпись = л("SYN-cookies включены"),
            значение = форматСчётчик(данные.synКуки),
            цвет = if (данные.synКуки > 0) Палитра.ОРАНЖЕВЫЙ else Палитра.ТЕКСТ,
        )
        СтрокаЗначения(л("Закрытий из-за памяти"), форматСчётчик(данные.ошибкиПамятиTcp))
        СтрокаЗначения(л("Срабатываний ограничителя памяти"), форматСчётчик(данные.давлениеПамяти))
        СтрокаЗначения(л("Таймаутов TCP"), форматСчётчик(данные.таймаутовTcp))
        СтрокаЗначения(л("Потеряно повторных передач"), форматСчётчик(данные.потерянныхРетрансмиссий))
        СтрокаЗначения(л("Память под TCP"), л("{1} страниц", форматСчётчик(данные.памятьTcpСтраниц)))

        Spacer(Modifier.height(10.dp))
        СтрокаЗначения(л("Сокетов всего"), форматСчётчик(данные.сокетовВсего))
        СтрокаЗначения("TCP / UDP", л("{1} / {2}", форматСчётчик(данные.сокетовTcp), форматСчётчик(данные.сокетовUdp)))
        СтрокаЗначения(
            подпись = "TIME_WAIT",
            значение = л("{1} · осиротевших {2}", форматСчётчик(данные.сокетовTimeWait), данные.сокетовTcpОсиротевших),
            цвет = if (данные.сокетовTimeWait > лимитTimeWait) Палитра.КРАСНЫЙ else Палитра.ТЕКСТ,
        )
        СтрокаЗначения(л("Слушающих портов"), данные.слушающихПортов?.toString() ?: "—")
        данные.сводка?.let { сводка ->
            СтрокаЗначения(
                подпись = л("Соединения по данным ss"),
                значение = л("всего {1}, TCP {2} (установлено {3})", сводка.всего, сводка.tcp, сводка.установлено),
            )
        }

        Spacer(Modifier.height(10.dp))
        val полоски = mutableListOf<Полоска>()
        данные.загруженностьConntrack?.let { занятость ->
            полоски.add(
                Полоска(
                    подпись = л("Таблица соединений (conntrack)"),
                    значение = л("{1} из {2}", данные.conntrack, данные.conntrackМаксимум),
                    доля = (занятость / 100.0).toFloat(),
                    цвет = цветЗаполнения(занятость),
                ),
            )
        }
        полоски.add(
            Полоска(
                подпись = л("Соединения TIME_WAIT"),
                значение = л("{1} из {2}", данные.сокетовTimeWait, лимитTimeWait),
                доля = (данные.сокетовTimeWait.toDouble() / лимитTimeWait).toFloat(),
                цвет = цветЗаполнения(данные.сокетовTimeWait * 100.0 / лимитTimeWait),
            ),
        )
        Полоски(полоски)
    }
}

@Composable
private fun КарточкаИнтерфейсов(данные: ДиагностикаСети) {
    val интерфейсы = данные.интерфейсы
    Карточка(
        заголовок = л("Сетевые интерфейсы"),
        подзаголовок = л("трафик за время работы, состояние линии и потери на приёме"),
        справа = {
            // Красный — только за то, что происходит сейчас: накопительные
            // счётчики за прошлое тревогу не поднимают.
            val проблемы = данные.внешниеИнтерфейсы.count { it.ошибкиСейчас || it.потериСейчас }
            val оборваны = данные.внешниеИнтерфейсы.count { it.рабочий && it.линияПоднята == false }
            Ярлычок(
                текст = when {
                    проблемы > 0 -> л("проблемы: {1}", проблемы)
                    оборваны > 0 -> л("линк опущен: {1}", оборваны)
                    else -> л("чисто")
                },
                цвет = when {
                    проблемы > 0 -> Палитра.КРАСНЫЙ
                    оборваны > 0 -> Палитра.ОРАНЖЕВЫЙ
                    else -> Палитра.ЗЕЛЁНЫЙ
                },
            )
        },
    ) {
        if (интерфейсы.isEmpty()) {
            Пусто(л("Данные интерфейсов не получены"))
            return@Карточка
        }
        val максимумПакетов = интерфейсы.maxOf { it.принятоПакетов }.coerceAtLeast(1L)
        Полоски(
            интерфейсы.map { интерфейс ->
                Полоска(
                    подпись = интерфейс.имя,
                    значение = л("↓ {1} ↑ {2}", форматБайт(интерфейс.принятоБайт), форматБайт(интерфейс.отправленоБайт)),
                    доля = (интерфейс.принятоПакетов.toDouble() / максимумПакетов).toFloat(),
                    цвет = цветИнтерфейса(интерфейс),
                )
            },
        )
        Spacer(Modifier.height(10.dp))
        интерфейсы.forEach { интерфейс ->
            СтрокаЗначения(
                подпись = л("«{1}»: пакеты / отброшено (за всё время работы)", интерфейс.имя),
                значение = л("{1} / {2}", форматСчётчик(интерфейс.принятоПакетов), форматСчётчик(интерфейс.отброшеноПриёме)) +
                    (интерфейс.доляОтброшенных?.let { л(" ({1})", форматПроцент(it)) } ?: ""),
                цвет = цветИнтерфейса(интерфейс),
            )
            интерфейс.отбросыЗаОпрос?.let { заОпрос ->
                СтрокаЗначения(
                    подпись = л("«{1}»: отброшено за последний опрос", интерфейс.имя),
                    значение = л(
                        "{1} из {2} ({3})",
                        форматСчётчик(заОпрос.отброшено),
                        форматСчётчик(заОпрос.принято),
                        форматПроцент(заОпрос.доля),
                    ),
                    цвет = if (интерфейс.потериСейчас) Палитра.ОРАНЖЕВЫЙ else Палитра.ТЕКСТ,
                )
            }
            val линк = описаниеЛинка(интерфейс)
            if (линк.isNotEmpty()) {
                СтрокаЗначения(
                    подпись = л("«{1}»: линия, скорость и режим", интерфейс.имя),
                    значение = линк,
                    цвет = if (интерфейс.рабочий && интерфейс.линияПоднята == false) Палитра.ОРАНЖЕВЫЙ else Палитра.ТЕКСТ,
                )
            }
            СтрокаЗначения(
                подпись = л("«{1}»: ошибки приёма / отправки (за всё время работы)", интерфейс.имя),
                значение = л("{1} / {2}", интерфейс.ошибкиПриёма, интерфейс.ошибкиОтправки),
            )
            if (интерфейс.ошибкиКаналаЗаОпрос > 0L) {
                СтрокаЗначения(
                    подпись = л("«{1}»: ошибки за последний опрос", интерфейс.имя),
                    значение = форматСчётчик(интерфейс.ошибкиКаналаЗаОпрос),
                    цвет = Палитра.КРАСНЫЙ,
                )
            }
        }
        val оборванные = данные.внешниеИнтерфейсы.filter { it.рабочий && it.линияПоднята == false }
        if (оборванные.isNotEmpty()) {
            Spacer(Modifier.height(6.dp))
            Текст(
                текст = л("Линк опущен на «{1}» — проверьте кабель, порт коммутатора и службу восстановления линка.", оборванные.joinToString(", ") { it.имя }),
                color = Палитра.ОРАНЖЕВЫЙ,
                style = MaterialTheme.typography.labelSmall,
            )
        }
        val проблемыСейчас = данные.внешниеИнтерфейсы.any { it.ошибкиСейчас || it.потериСейчас }
        val проблемыРаньше = данные.внешниеИнтерфейсы.any {
            it.ошибкиПриёма + it.ошибкиОтправки > 0L || it.отброшеноПриёме > 0L
        }
        if (!проблемыСейчас) {
            Spacer(Modifier.height(6.dp))
            Текст(
                текст = if (проблемыРаньше) {
                    л("Ошибок линии нет, потерь за последний опрос тоже — отброшенные пакеты набрались раньше.")
                } else {
                    л("Ошибок и отбросов на внешних интерфейсах нет.")
                },
                color = Палитра.ЗЕЛЁНЫЙ,
                style = MaterialTheme.typography.labelSmall,
            )
        }
    }
}

@Composable
private fun КарточкаПараметров(данные: ДиагностикаСети) {
    val строки = ПОКАЗЫВАЕМЫЕ_ПАРАМЕТРЫ.mapNotNull { (ключ, подпись) ->
        данные.параметр(ключ)?.let { подпись to it }
    }
    Карточка(
        заголовок = л("Параметры ядра"),
        подзаголовок = л("текущие значения на сервере (меняются через sysctl)"),
    ) {
        if (строки.isEmpty()) {
            Пусто(л("Сервер не вернул параметры сети"))
            return@Карточка
        }
        строки.forEach { (подпись, значение) ->
            СтрокаЗначения(подпись, значение, моно = true)
        }
    }
}

@Composable
private fun КарточкаРекомендаций(
    оценка: ОценкаСети,
    данные: ДиагностикаСети,
    буфер: androidx.compose.ui.platform.ClipboardManager,
    контекст: android.content.Context,
) {
    Карточка(
        заголовок = л("Рекомендации по оптимизации"),
        подзаголовок = л("в порядке важности — сверху то, что даёт больше всего"),
        справа = {
            val важных = оценка.рекомендации.count { it.важная }
            Ярлычок(
                текст = if (важных > 0) л("важных: {1}", важных) else л("всего: {1}", оценка.рекомендации.size),
                цвет = if (важных > 0) Палитра.ОРАНЖЕВЫЙ else Палитра.ЗЕЛЁНЫЙ,
            )
        },
    ) {
        if (оценка.рекомендации.isEmpty()) {
            Текст(
                текст = л("Параметры сети в порядке — вмешательство не требуется. Продолжайте следить за долей повторных передач и потерями на интерфейсах."),
                color = Палитра.ЗЕЛЁНЫЙ,
                style = MaterialTheme.typography.bodySmall,
            )
        } else {
            оценка.рекомендации.forEachIndexed { индекс, совет ->
                if (индекс > 0) {
                    Spacer(Modifier.height(6.dp))
                    androidx.compose.material3.HorizontalDivider(color = Палитра.ГРАНИЦА)
                    Spacer(Modifier.height(6.dp))
                }
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Ярлычок(
                        текст = if (совет.важная) л("важно") else л("совет"),
                        цвет = if (совет.важная) Палитра.КРАСНЫЙ else Палитра.СИНИЙ,
                    )
                    Spacer(Modifier.width(8.dp))
                    Текст(
                        текст = совет.заголовок,
                        color = Палитра.ТЕКСТ,
                        style = MaterialTheme.typography.bodyMedium,
                        modifier = Modifier.weight(1f),
                    )
                }
                Spacer(Modifier.height(4.dp))
                Текст(
                    текст = совет.пояснение,
                    color = Палитра.ТУСКЛЫЙ,
                    style = MaterialTheme.typography.bodySmall,
                )
                if (совет.команда.isNotBlank()) {
                    Spacer(Modifier.height(4.dp))
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Текст(
                            текст = совет.команда,
                            color = Палитра.АКЦЕНТ,
                            style = MaterialTheme.typography.labelSmall.copy(
                                fontFamily = androidx.compose.ui.text.font.FontFamily.Monospace,
                            ),
                            modifier = Modifier.weight(1f),
                        )
                        TextButton(onClick = {
                            буфер.setText(AnnotatedString(совет.команда))
                            Toast.makeText(контекст, л("Команда скопирована"), Toast.LENGTH_SHORT).show()
                        }) {
                            Текст(л("Копировать"))
                        }
                    }
                }
            }
            Spacer(Modifier.height(10.dp))
            Текст(
                текст = л("Команды выполняются на сервере по SSH от имени sudo и действуют до перезагрузки. Чтобы сохранить их навсегда, запишите строки в /etc/sysctl.d/99-сеть.conf и выполните sysctl --system (или перезагрузите сервер)."),
                color = Палитра.ЖЁЛТЫЙ,
                style = MaterialTheme.typography.labelSmall,
            )
        }
        if (данные.темп == null) {
            Spacer(Modifier.height(8.dp))
            Текст(
                текст = л("Скорости (в секунду и в минуту) появятся после второго опроса сети — сейчас показаны только накопительные счётчики."),
                color = Палитра.ТУСКЛЫЙ,
                style = MaterialTheme.typography.labelSmall,
            )
        }
    }
}

/**
 * Доля повторных передач для витрины: накопительная (за всё время работы
 * сервера) — она устойчива. Мгновенная доля показывается отдельно, когда
 * повторных передач за опрос достаточно много, чтобы ей верить.
 */
private fun доляРетрансмиссий(данные: ДиагностикаСети): Double? = данные.доляРетрансмиссий

/** Мгновенная доля повторных передач — только при заметном всплеске. */
private fun доляВсплеска(данные: ДиагностикаСети): Double? =
    данные.темп?.takeIf { it.всплескРетрансмиссий }?.доляРетрансмиссий

private fun цветУровня(уровень: String): Color = when (уровень) {
    УРОВЕНЬ_СЕТИ_ОТЛИЧНО -> Палитра.ЗЕЛЁНЫЙ
    УРОВЕНЬ_СЕТИ_НОРМАЛЬНО -> Палитра.СИНИЙ
    УРОВЕНЬ_СЕТИ_ПЛОХО -> Палитра.КРАСНЫЙ
    else -> Палитра.ЖЁЛТЫЙ
}

private fun пояснениеУровня(уровень: String): String = when (уровень) {
    УРОВЕНЬ_СЕТИ_ОТЛИЧНО -> л("Счётчики в норме: потерь и переполнений нет.")
    УРОВЕНЬ_СЕТИ_НОРМАЛЬНО -> л("Сеть работает ровно, но есть что подтянуть в настройках.")
    УРОВЕНЬ_СЕТИ_ПЛОХО -> л("Есть серьёзные сбои: примените важные рекомендации ниже.")
    else -> л("Часть показателей вышла за норму — посмотрите рекомендации ниже.")
}

private fun цветРетрансмиссий(доля: Double?): Color = when {
    доля == null -> Палитра.ТУСКЛЫЙ
    доля > 2.0 -> Палитра.КРАСНЫЙ
    доля > 0.5 -> Палитра.ЖЁЛТЫЙ
    else -> Палитра.ЗЕЛЁНЫЙ
}

private fun цветЗаполнения(процент: Double): Color = when {
    процент >= 90.0 -> Палитра.КРАСНЫЙ
    процент >= 70.0 -> Палитра.ЖЁЛТЫЙ
    процент >= 40.0 -> Палитра.СИНИЙ
    else -> Палитра.ЗЕЛЁНЫЙ
}

private fun цветИнтерфейса(интерфейс: ИнтерфейсСети): Color = when {
    интерфейс.ошибкиСейчас || интерфейс.потериСейчас -> Палитра.КРАСНЫЙ
    интерфейс.рабочий && интерфейс.линияПоднята == false -> Палитра.ОРАНЖЕВЫЙ
    else -> Палитра.ЗЕЛЁНЫЙ
}

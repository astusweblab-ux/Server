/**
 * Вкладка «Обслуживание»: аудит сервера — обновления пакетов, сбойные службы,
 * журналы, точное время, место на дисках и здоровье накопителей. Тот раздел,
 * который обычно смотрят «раз в месяц», собранный в одну оценку 0–100.
 */
@Composable
fun ЭкранОбслуживания(снимок: Снимок, движок: Движок) {
    val данные = снимок.обслуживание
    val оценка = снимок.оценкаОбслуживания ?: оценитьОбслуживание(данные)
    val буфер = LocalClipboardManager.current
    val контекст = LocalContext.current

    Прокрутка {
        Карточка(
            заголовок = л("Обслуживание сервера"),
            подзаголовок = л("обновления, службы, журналы, время и диски"),
            справа = {
                Ярлычок(
                    текст = if (данные == null) л("нет данных") else л(оценка.уровень),
                    цвет = цветУровняОбслуживания(оценка.уровень),
                )
            },
        ) {
            if (данные == null) {
                Пусто(л("Данные появятся после первого аудита (по умолчанию раз в 10 минут)"))
                Spacer(Modifier.height(8.dp))
                Row(verticalAlignment = Alignment.CenterVertically) {
                    if (снимок.опросИдёт) {
                        Крутилка()
                        Spacer(Modifier.width(10.dp))
                    }
                    TextButton(onClick = { движок.обновитьОбслуживаниеСейчас() }, enabled = !снимок.опросИдёт) {
                        Текст(л("Обновить сейчас"))
                    }
                }
                return@Карточка
            }

            Row(verticalAlignment = Alignment.CenterVertically) {
                Кольцо(
                    значение = оценка.балл.toDouble(),
                    подпись = л("сервис"),
                    текст = оценка.балл.toString(),
                    цвет = цветУровняОбслуживания(оценка.уровень),
                )
                Spacer(Modifier.width(14.dp))
                Column(modifier = Modifier.weight(1f)) {
                    Текст(
                        текст = л("Оценка: {1} из 100", оценка.балл),
                        color = цветУровняОбслуживания(оценка.уровень),
                        style = MaterialTheme.typography.titleMedium,
                    )
                    Spacer(Modifier.height(4.dp))
                    Текст(
                        текст = пояснениеОбслуживания(оценка),
                        color = Палитра.ТУСКЛЫЙ,
                        style = MaterialTheme.typography.bodySmall,
                    )
                    Spacer(Modifier.height(4.dp))
                    Текст(
                        текст = л("Проверено: {1}", времяДата(данные.время)),
                        color = Палитра.ТУСКЛЫЙ,
                        style = MaterialTheme.typography.labelSmall,
                    )
                }
            }

            Spacer(Modifier.height(12.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                Плитка(
                    подпись = л("Обновлений доступно"),
                    значение = (данные.обновленийВсего ?: 0).toString(),
                    цвет = цветОбновлений(данные.обновленийВсего),
                    modifier = Modifier.weight(1f),
                )
                Плитка(
                    подпись = л("Из них безопасности"),
                    значение = (данные.обновленийБезопасности ?: 0).toString(),
                    цвет = if ((данные.обновленийБезопасности ?: 0) > 0) Палитра.КРАСНЫЙ else Палитра.ЗЕЛЁНЫЙ,
                    modifier = Modifier.weight(1f),
                )
            }
            Spacer(Modifier.height(8.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                Плитка(
                    подпись = л("Сбойных служб"),
                    значение = данные.сбойныеЮниты.size.toString(),
                    цвет = if (данные.сбойныеЮниты.isEmpty()) Палитра.ЗЕЛЁНЫЙ else Палитра.КРАСНЫЙ,
                    modifier = Modifier.weight(1f),
                )
                Плитка(
                    подпись = л("Загрузка сервера"),
                    значение = данные.загрузкаСекунд?.let { л("{1} с", одинЗнак(it)) } ?: "—",
                    modifier = Modifier.weight(1f),
                )
            }

            Spacer(Modifier.height(10.dp))
            Row(verticalAlignment = Alignment.CenterVertically) {
                if (снимок.опросИдёт) {
                    Крутилка()
                    Spacer(Modifier.width(10.dp))
                }
                TextButton(onClick = { движок.обновитьОбслуживаниеСейчас() }, enabled = !снимок.опросИдёт) {
                    Текст(л("Обновить сейчас"))
                }
                TextButton(onClick = {
                    буфер.setText(AnnotatedString(отчётОбслуживания(данные, оценка)))
                    Toast.makeText(контекст, л("Отчёт скопирован в буфер обмена"), Toast.LENGTH_SHORT).show()
                }) {
                    Текст(л("Скопировать отчёт"))
                }
            }
            TextButton(onClick = {
                поделитьсяОтчётом(контекст, отчётОбслуживания(данные, оценка))
            }) {
                Текст(л("Поделиться отчётом"))
            }
        }

        if (данные != null) {
            КарточкаОбновлений(данные)
            КарточкаСлужбыИВремя(данные)
            КарточкаЖурналов(данные)
            КарточкаНакопителей(данные)
            КарточкаРекомендацийОбслуживания(оценка, буфер, контекст)
        }
    }
}

@Composable
private fun КарточкаОбновлений(данные: Обслуживание) {
    Карточка(
        заголовок = л("Обновления пакетов"),
        подзаголовок = л("обновления ядра и системы"),
        справа = {
            Ярлычок(
                текст = if (данные.перезагрузкаТребуется || данные.перезагрузкаЯдра) л("нужна перезагрузка") else л("перезагрузка не нужна"),
                цвет = if (данные.перезагрузкаТребуется || данные.перезагрузкаЯдра) Палитра.КРАСНЫЙ else Палитра.ЗЕЛЁНЫЙ,
            )
        },
    ) {
        СтрокаЗначения(л("Ядро работает"), данные.ядро.ifBlank { л("нет данных") }, моно = true)
        if (данные.ядроУстановлено.isNotEmpty()) {
            СтрокаЗначения(
                подпись = л("Ядро установлено"),
                значение = данные.ядроУстановлено,
                цвет = if (данные.перезагрузкаЯдра) Палитра.ЖЁЛТЫЙ else Палитра.ТЕКСТ,
                моно = true,
            )
        }
        СтрокаЗначения(л("Аптайм"), форматАптайм(данные.аптайм))
        СтрокаЗначения(
            подпись = л("Доступно обновлений"),
            значение = (данные.обновленийВсего ?: 0).toString(),
            цвет = цветОбновлений(данные.обновленийВсего),
        )
        if (данные.обновленийСейчас != null && данные.обновленийСейчас != данные.обновленийВсего) {
            СтрокаЗначения(
                подпись = л("apt установит сейчас"),
                значение = данные.обновленийСейчас.toString(),
                цвет = цветОбновлений(данные.обновленийСейчас),
            )
        }
        СтрокаЗначения(
            подпись = л("Обновления безопасности"),
            значение = (данные.обновленийБезопасности ?: 0).toString(),
            цвет = if ((данные.обновленийБезопасности ?: 0) > 0) Палитра.КРАСНЫЙ else Палитра.ЗЕЛЁНЫЙ,
        )
        СтрокаЗначения(л("Установлено пакетов"), форматСчётчик((данные.пакетовУстановлено ?: 0).toLong()))
        СтрокаЗначения(л("Кандидаты на авт. удаление"), форматСчётчик((данные.удалитьПакетов ?: 0).toLong()))
        СтрокаЗначения(
            подпись = л("Автообновления безопасности"),
            значение = включено(данные.автообновленияВключены),
            цвет = if (данные.автообновленияВключены == false) Палитра.ЖЁЛТЫЙ else Палитра.ТЕКСТ,
        )
        СтрокаЗначения(
            подпись = л("Ротация журналов"),
            значение = включено(данные.ротацияЛоговВключена),
            цвет = if (данные.ротацияЛоговВключена == false) Палитра.ЖЁЛТЫЙ else Палитра.ТЕКСТ,
        )
        СтрокаЗначения(л("Юнитов в автозапуске"), (данные.автозапускЮнитов ?: 0).toString())
    }
}

@Composable
private fun КарточкаСлужбыИВремя(данные: Обслуживание) {
    Карточка(
        заголовок = л("Службы и время"),
        подзаголовок = л("сбойные юниты, синхронизация часов и старт системы"),
        справа = {
            Ярлычок(
                текст = if (данные.сбойныеЮниты.isEmpty()) л("службы в порядке") else л("есть сбои"),
                цвет = if (данные.сбойныеЮниты.isEmpty()) Палитра.ЗЕЛЁНЫЙ else Палитра.КРАСНЫЙ,
            )
        },
    ) {
        if (данные.сбойныеЮниты.isEmpty()) {
            СтрокаЗначения(л("Сбойные юниты"), л("нет"), цвет = Палитра.ЗЕЛЁНЫЙ)
        } else {
            for (юнит in данные.сбойныеЮниты) {
                СтрокаЗначения(л("Сбойный юнит"), юнит, цвет = Палитра.КРАСНЫЙ, моно = true)
            }
        }
        СтрокаЗначения(
            подпись = л("Синхронизация времени"),
            значение = when (данные.ntpСинхронизирован) {
                true -> л("синхронизировано")
                false -> л("не синхронизировано")
                else -> л("нет данных")
            },
            цвет = if (данные.ntpСинхронизирован == false) Палитра.КРАСНЫЙ else Палитра.ТЕКСТ,
        )
        if (данные.службаВремени.isNotEmpty()) СтрокаЗначения(л("Служба времени"), данные.службаВремени)
        if (данные.часовойПояс.isNotEmpty()) СтрокаЗначения(л("Часовой пояс"), данные.часовойПояс)
        СтрокаЗначения(
            подпись = л("Загрузка сервера"),
            значение = данные.загрузкаСекунд?.let { л("{1} с", одинЗнак(it)) } ?: л("нет данных"),
        )
        данные.свопПроцент?.let { процент ->
            СтрокаЗначения(
                подпись = л("Подкачка занята"),
                значение = л("{1} %", одинЗнак(процент)),
                цвет = if (процент >= 50.0) Палитра.ЖЁЛТЫЙ else Палитра.ЗЕЛЁНЫЙ,
            )
        }
    }
}

@Composable
private fun КарточкаЖурналов(данные: Обслуживание) {
    Карточка(
        заголовок = л("Журналы и место"),
        подзаголовок = л("что занимает диск и как быстро растут журналы"),
    ) {
        данные.дискЗанято?.let { занято ->
            СтрокаЗначения(
                подпись = л("Диск занят"),
                значение = л("{1} % · свободно {2}", одинЗнак(занято), форматБайт(данные.дискСвободно)),
                цвет = цветДиска(занято),
            )
            Spacer(Modifier.height(4.dp))
            Полоски(
                элементы = listOf(
                    Полоска(
                        подпись = л("Занято на разделе"),
                        значение = л("{1} %", одинЗнак(занято)),
                        доля = (занято / 100.0).toFloat(),
                        цвет = цветДиска(занято),
                    ),
                ),
            )
        }
        СтрокаЗначения(
            подпись = л("Журнал systemd"),
            значение = форматБайт(данные.размерЖурнала),
            цвет = когдаБольшойЛог(данные.размерЖурнала, ПОРОГ_ЖУРНАЛА_БАЙТ),
        )
        СтрокаЗначения(
            подпись = л("Каталог /var/log без журнала"),
            значение = форматБайт(обычныеЛоги(данные)),
            цвет = цветОбычныхЛогов(важностьОбычныхЛогов(данные)),
        )
        if (данные.крупныеЛоги.isNotEmpty()) {
            Spacer(Modifier.height(8.dp))
            Текст(л("Крупнейшие файлы журналов"), color = Палитра.ТУСКЛЫЙ, style = MaterialTheme.typography.labelSmall)
            Spacer(Modifier.height(6.dp))
            Полоски(элементы = полоскиЛогов(данные.крупныеЛоги, данные.размерЛогов))
        }
    }
}

@Composable
private fun КарточкаНакопителей(данные: Обслуживание) {
    val проблемыСоSmart = данные.дискиЗдоровье.any { it.статус.isNotBlank() && !it.вПорядке }
    Карточка(
        заголовок = л("Накопители и SMART"),
        подзаголовок = л("какие диски есть, куда смонтированы и как себя чувствуют"),
        справа = {
            Ярлычок(
                текст = when {
                    проблемыСоSmart -> л("есть проблемы")
                    !данные.smartДоступен -> л("нет smartmontools")
                    данные.дискиЗдоровье.isEmpty() -> л("нет данных")
                    else -> л("SMART в норме")
                },
                цвет = when {
                    проблемыСоSmart -> Палитра.КРАСНЫЙ
                    !данные.smartДоступен -> Палитра.ЖЁЛТЫЙ
                    данные.дискиЗдоровье.isEmpty() -> Палитра.ТУСКЛЫЙ
                    else -> Палитра.ЗЕЛЁНЫЙ
                },
            )
        },
    ) {
        if (данные.накопители.isEmpty()) {
            Пусто(л("Список накопителей сервер не вернул"))
        } else {
            for (диск in данные.накопители) {
                СтрокаЗначения(
                    подпись = "${диск.устройство} · ${диск.модель.ifBlank { л("модель неизвестна") }}",
                    значение = "${форматБайт(диск.размер)} · ${if (диск.смонтирован) л("смонтирован") else л("не используется")}",
                    цвет = if (диск.смонтирован) Палитра.ТЕКСТ else Палитра.ЖЁЛТЫЙ,
                )
            }
        }
        if (данные.дискиЗдоровье.isNotEmpty()) {
            Spacer(Modifier.height(8.dp))
            Текст(л("Здоровье дисков"), color = Палитра.ТУСКЛЫЙ, style = MaterialTheme.typography.labelSmall)
            Spacer(Modifier.height(6.dp))
            for (диск in данные.дискиЗдоровье) {
                СтрокаЗначения(
                    подпись = диск.устройство,
                    значение = описаниеЗдоровья(диск),
                    цвет = if (диск.вПорядке) Палитра.ЗЕЛЁНЫЙ else Палитра.КРАСНЫЙ,
                )
            }
        } else if (!данные.smartДоступен) {
            Spacer(Modifier.height(6.dp))
            Текст(
                текст = л("Чтобы видеть износ и переназначенные сектора, установите smartmontools: sudo apt install smartmontools"),
                color = Палитра.ТУСКЛЫЙ,
                style = MaterialTheme.typography.labelSmall,
            )
        }
        if (данные.дублиВFstab.isNotEmpty()) {
            Spacer(Modifier.height(8.dp))
            СтрокаЗначения(
                подпись = л("Повторы в /etc/fstab"),
                значение = данные.дублиВFstab.joinToString(", "),
                цвет = Палитра.ЖЁЛТЫЙ,
            )
        }
    }
}

@Composable
private fun КарточкаРекомендацийОбслуживания(
    оценка: ОценкаОбслуживания,
    буфер: androidx.compose.ui.platform.ClipboardManager,
    контекст: Context,
) {
    Карточка(
        заголовок = л("Что сделать"),
        подзаголовок = л("рекомендации по обслуживанию — от важных к необязательным"),
        справа = { Ярлычок(л("замечаний: {1}", оценка.рекомендации.size), Палитра.СИНИЙ) },
    ) {
        if (оценка.рекомендации.isEmpty()) {
            Текст(
                текст = л("Замечаний нет: обновления установлены, службы здоровы, журналы под контролем."),
                color = Палитра.ЗЕЛЁНЫЙ,
                style = MaterialTheme.typography.bodySmall,
            )
            return@Карточка
        }

        for (рекомендация in оценка.рекомендации) {
            СтрокаРекомендацииОбслуживания(рекомендация, буфер, контекст)
        }
        Spacer(Modifier.height(6.dp))
        Текст(
            текст = л("Команды выполняются на сервере по SSH. Обновления и перезагрузка — ваше решение: приложение только показывает, что накопилось."),
            color = Палитра.ТУСКЛЫЙ,
            style = MaterialTheme.typography.labelSmall,
        )
    }
}

@Composable
private fun СтрокаРекомендацииОбслуживания(
    рекомендация: РекомендацияОбслуживания,
    буфер: androidx.compose.ui.platform.ClipboardManager,
    контекст: Context,
) {
    val цвет = if (рекомендация.важная) Палитра.ОРАНЖЕВЫЙ else Палитра.СИНИЙ
    Column(modifier = Modifier.fillMaxWidth().padding(vertical = 6.dp)) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            Ярлычок(if (рекомендация.важная) л("важно") else л("совет"), цвет)
            Spacer(Modifier.width(8.dp))
            Текст(
                текст = рекомендация.заголовок,
                color = Палитра.ТЕКСТ,
                style = MaterialTheme.typography.titleSmall,
            )
        }
        Spacer(Modifier.height(4.dp))
        Текст(
            текст = рекомендация.пояснение,
            color = Палитра.ТУСКЛЫЙ,
            style = MaterialTheme.typography.bodySmall,
        )
        if (рекомендация.команда.isNotBlank()) {
            Spacer(Modifier.height(4.dp))
            Row(verticalAlignment = Alignment.CenterVertically) {
                Текст(
                    текст = рекомендация.команда,
                    color = Палитра.АКЦЕНТ,
                    style = MaterialTheme.typography.labelSmall.copy(fontFamily = FontFamily.Monospace),
                    modifier = Modifier.weight(1f),
                )
                TextButton(onClick = {
                    буфер.setText(AnnotatedString(рекомендация.команда))
                    Toast.makeText(контекст, л("Команда скопирована"), Toast.LENGTH_SHORT).show()
                }) {
                    Текст(л("Копировать"))
                }
            }
        }
    }
}

private fun полоскиЛогов(логи: List<КрупныйЛог>, всего: Long?): List<Полоска> {
    val предел = (всего ?: логи.maxOfOrNull { it.байт } ?: 1L).coerceAtLeast(1L)
    return логи.take(6).map { лог ->
        Полоска(
            подпись = лог.путь.removePrefix("/var/log/"),
            значение = форматБайт(лог.байт),
            доля = (лог.байт.toDouble() / предел).toFloat(),
            цвет = когдаБольшойЛог(лог.байт, ПОРОГ_ЛОГОВ_ТРЕВОГА_БАЙТ),
        )
    }
}

private fun когдаБольшойЛог(размер: Long?, тревогаС: Long): Color = when {
    размер == null -> Палитра.ТУСКЛЫЙ
    размер >= тревогаС * 2 -> Палитра.КРАСНЫЙ
    размер >= тревогаС -> Палитра.ЖЁЛТЫЙ
    else -> Палитра.ЗЕЛЁНЫЙ
}

/** Цвет строки /var/log по важности обычных (не systemd) журналов из ядра оценки. */
private fun цветОбычныхЛогов(важность: Int): Color = when {
    важность >= 8 -> Палитра.КРАСНЫЙ
    важность >= 4 -> Палитра.ЖЁЛТЫЙ
    else -> Палитра.ЗЕЛЁНЫЙ
}

private fun цветДиска(процент: Double): Color = when {
    процент >= 90.0 -> Палитра.КРАСНЫЙ
    процент >= 80.0 -> Палитра.ОРАНЖЕВЫЙ
    процент >= 70.0 -> Палитра.ЖЁЛТЫЙ
    else -> Палитра.ЗЕЛЁНЫЙ
}

private fun цветОбновлений(количество: Int?): Color = when {
    количество == null -> Палитра.ТУСКЛЫЙ
    количество == 0 -> Палитра.ЗЕЛЁНЫЙ
    количество >= 10 -> Палитра.ЖЁЛТЫЙ
    else -> Палитра.СИНИЙ
}

private fun описаниеЗдоровья(диск: ЗдоровьеДиска): String {
    val части = mutableListOf<String>()
    части.add(диск.статус.ifBlank { л("нет ответа") })
    диск.переназначеноСекторов?.takeIf { it > 0L }?.let { части.add(л("переназначено секторов: {1}", it)) }
    диск.температура?.let { части.add(л("{1} °C", одинЗнак(it))) }
    диск.часовРаботы?.let { части.add(л("наработка {1} ч", форматСчётчик(it))) }
    return части.joinToString(" · ")
}

private fun цветУровняОбслуживания(уровень: String): Color = when (уровень) {
    УРОВЕНЬ_ОБСЛУЖИВАНИЯ_ОТЛИЧНО -> Палитра.ЗЕЛЁНЫЙ
    УРОВЕНЬ_ОБСЛУЖИВАНИЯ_НОРМАЛЬНО -> Палитра.СИНИЙ
    УРОВЕНЬ_ОБСЛУЖИВАНИЯ_ПЛОХО -> Палитра.КРАСНЫЙ
    else -> Палитра.ЖЁЛТЫЙ
}

private fun пояснениеОбслуживания(оценка: ОценкаОбслуживания): String = when (оценка.уровень) {
    УРОВЕНЬ_ОБСЛУЖИВАНИЯ_ОТЛИЧНО -> л("Обновления установлены, службы здоровы, журналы под контролем.")
    УРОВЕНЬ_ОБСЛУЖИВАНИЯ_НОРМАЛЬНО -> л("Сервер в порядке, но есть что подтянуть — смотрите советы ниже.")
    УРОВЕНЬ_ОБСЛУЖИВАНИЯ_ПЛОХО -> л("Накопились важные дела: обновления, сбои или место на диске.")
    else -> л("Обработайте важные советы ниже — и оценка вернётся в норму.")
}

private fun включено(значение: Boolean?): String = when (значение) {
    true -> л("включено")
    false -> л("выключено")
    else -> л("нет данных")
}

private fun одинЗнак(значение: Double): String =
    if (значение == значение.toLong().toDouble()) значение.toLong().toString()
    else String.format(java.util.Locale.ROOT, "%.1f", значение)

/** Отправляет текстовый отчёт аудита во внешнее приложение (почта, мессенджер). */
private fun поделитьсяОтчётом(контекст: Context, текст: String) {
    try {
        val намерение = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, л("Обслуживание сервера"))
            putExtra(Intent.EXTRA_TEXT, текст)
        }
        контекст.startActivity(Intent.createChooser(намерение, л("Поделиться отчётом")))
    } catch (ошибка: Exception) {
        Toast.makeText(контекст, л("Не удалось поделиться отчётом: {1}", ошибка.message), Toast.LENGTH_LONG).show()
    }
}

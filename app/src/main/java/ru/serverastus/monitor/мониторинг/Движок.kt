/** Параметры подключения активного сервера, вырезанные из настроек приложения. */
fun параметрыСервера(настройки: Настройки): ПараметрыСервера {
    val сервер = настройки.сервер
    return ПараметрыСервера(
        хост = сервер.optString("хост").trim(),
        порт = настройки.целое(сервер, "порт", 22),
        пользователь = сервер.optString("пользователь").trim(),
        пароль = настройки.парольСервера(),
        файлКлюча = сервер.optString("файл_ключа"),
        таймаутСекунд = настройки.целое(сервер, "таймаут_секунд", 20),
        дискПуть = сервер.optString("диск_путь").ifBlank { "/" },
    )
}

/**
 * Фоновый опрос Linux-сервера, сайтов, портов и служб.
 *
 * Повторяет настольный движок (`server_monitor/desktop/worker.py`): те же
 * интервалы, те же тексты событий, та же история в SQLite. Отличия только
 * во внешней оболочке — вместо потока с очередью корутины и `StateFlow`,
 * который читает интерфейс Compose.
 *
 * Серверов может быть несколько. Движок всегда работает с активным профилем
 * настроек: SSH-сеанс, история, техжурнал и интервалы берутся у него. Историю
 * движок создаёт сам через `фабрикаИстории` — у каждого сервера свой файл базы,
 * поэтому данные разных серверов не смешиваются.
 */
class Движок(
    val настройки: Настройки,
    val оповещения: Оповещения,
    private val фабрикаИстории: (String) -> История,
) {

    private val область = CoroutineScope(SupervisorJob() + Dispatchers.IO)
    private var задание: Job? = null

    private val _снимок = MutableStateFlow(Снимок())
    val снимок: StateFlow<Снимок> = _снимок.asStateFlow()

    private val _сообщения = MutableSharedFlow<String>(extraBufferCapacity = 16)
    val сообщения: SharedFlow<String> = _сообщения.asSharedFlow()

    // Интервалы опроса в секундах — пересчитываются при смене настроек.
    private var интервалСервера = 5.0
    private var интервалПодробностей = 20.0
    private var интервалСайтов = 10.0
    private var интервалПортов = 15.0
    private var интервалСлужб = 20.0
    private var интервалБезопасности = 30.0
    private var интервалСети = 30.0
    private var интервалОбслуживания = 600.0

    private val стоп = AtomicBoolean(true)
    private val флагПаузы = AtomicBoolean(false)
    private val флагНемедленно = AtomicBoolean(false)

    private val очередьСлужб = ConcurrentLinkedQueue<Pair<String, String>>()
    private val очередьIp = ConcurrentLinkedQueue<Pair<String, String>>()

    private var сервер: LinuxServer? = null
    private var ключСервера: List<String>? = null
    private var кэшПодробностей = Подробности()

    private var следующийСервер = 0L
    private var следующиеПодробности = 0L
    private var следующиеСайты = 0L
    private var следующиеПорты = 0L
    private var следующиеСлужбы = 0L
    private var следующаяБезопасность = 0L
    private var следующаяСеть = 0L
    private var следующаяОбслуживание = 0L
    private var следующаяИстория = 0L
    private var следующаяОчистка = System.currentTimeMillis() + 3_600_000

    private var идётОпрос = 0

    private val доступностьЦелей = mutableMapOf<String, Boolean>()
    private val состоянияСлужб = mutableMapOf<String, Boolean>()
    private val флагиПорогов = mutableMapOf<String, Boolean>()
    private var времяПоследнегоСобытияБ: Long? = null

    // Оценка сети держится с «гистерезисом»: одно оповещение о просадке и одно
    // о восстановлении, а не сообщение на каждый опрос.
    private var сетьПросела = false

    // То же для обслуживания: аудит идёт редко, поэтому и оповещаем один раз.
    private var обслуживаниеПросело = false

    /**
     * История активного сервера: у каждого профиля свой файл базы, поэтому при
     * переключении сервера объект истории подменяется (см. `сменитьФайлы`).
     */
    private var историяТекущая = фабрикаИстории(настройки.файлИстории())
    val история: История get() = историяТекущая

    private var имяФайлаИстории = настройки.файлИстории()

    /** Имя файла истории активного сервера — показывается на вкладке «Журнал». */
    val имяИстории: String get() = имяФайлаИстории

    /**
     * Чей снимок сейчас собирается. Меняется только вместе с файлами данных
     * (см. `сменитьФайлы`), поэтому запоздавший опрос прежнего сервера
     * помечает свой снимок прежним идентификатором — и интерфейс его прячет.
     */
    private var идДанных = настройки.активныйId

    /** Техжурнал активного сервера: у каждого профиля свой файл `журнал[_ид].log`. */
    private var файлЖурнала = File(настройки.каталог, настройки.файлЖурнала())

    private val действиеСлужбы = mapOf(
        "start" to ("запустить_службу" to л("Служба запущена вручную.")),
        "stop" to ("остановить_службу" to л("Служба остановлена вручную.")),
        "restart" to ("перезапустить_службу" to л("Служба перезапущена вручную.")),
    )

    init {
        применитьНастройки()
    }

    // --- управление ------------------------------------------------------

    val наПаузе: Boolean get() = флагПаузы.get()

    fun запустить() {
        if (задание?.isActive == true) return
        стоп.set(false)
        флагПаузы.set(false)
        флагНемедленно.set(true)
        обновитьСнимок { it.copy(запущено = true) }
        задание = область.launch { цикл() }
    }

    fun остановить() {
        стоп.set(true)
        задание?.cancel()
        задание = null
        сервер?.закрыть()
        сервер = null
        кэшПодробностей = Подробности()
        обновитьСнимок { it.copy(запущено = false, опросИдёт = false, действиеИдёт = null) }
    }

    fun пауза() {
        флагПаузы.set(true)
        опубликоватьСостояние()
    }

    fun продолжить() {
        флагПаузы.set(false)
        флагНемедленно.set(true)
        опубликоватьСостояние()
    }

    fun проверитьСейчас() {
        флагНемедленно.set(true)
        if (задание?.isActive != true) запустить()
    }

    fun запуститьСлужбу(имя: String) = поставитьДействиеСлужбы(имя, "start")

    fun остановитьСлужбу(имя: String) = поставитьДействиеСлужбы(имя, "stop")

    fun перезапуститьСлужбу(имя: String) = поставитьДействиеСлужбы(имя, "restart")

    private fun поставитьДействиеСлужбы(имя: String, действие: String) {
        очередьСлужб.add(имя to действие)
        флагНемедленно.set(true)
        if (задание?.isActive != true) запустить()
    }

    fun заблокироватьIp(ip: String) = поставитьДействиеIp(ip, "ban")

    fun разблокироватьIp(ip: String) = поставитьДействиеIp(ip, "unban")

    private fun поставитьДействиеIp(ip: String, действие: String) {
        очередьIp.add(ip to действие)
        флагНемедленно.set(true)
        if (задание?.isActive != true) запустить()
    }

    /** Пересчитывает интервалы по текущим настройкам и опрашивает всё заново. */
    fun применитьНастройки() {
        сменитьФайлы()
        val сам = настройки.сервер
        интервалСервера = настройки.число(сам, "интервал_секунд", 5.0).coerceAtLeast(1.0)
        интервалПодробностей = настройки.число(сам, "интервал_подробностей_секунд", 20.0).coerceAtLeast(5.0)
        интервалСайтов = настройки.числоСервера("сайты_интервал_секунд", 10.0).coerceAtLeast(1.0)
        интервалПортов = настройки.числоСервера("порты_интервал_секунд", 15.0).coerceAtLeast(1.0)
        интервалСлужб = maxOf(10.0, интервалПодробностей)
        интервалБезопасности = настройки.число(сам, "интервал_безопасности_секунд", 30.0).coerceAtLeast(5.0)
        интервалСети = настройки.число(сам, "интервал_сети_секунд", 30.0).coerceAtLeast(10.0)
        интервалОбслуживания =
            настройки.число(сам, "интервал_обслуживания_секунд", 600.0).coerceAtLeast(60.0)
        флагНемедленно.set(true)
    }

    /**
     * Переключает движок на другой профиль сервера: прежний опрос дожидается
     * завершения, сеанс закрывается, история и техжурнал берутся от нового
     * профиля, состояние экранов сбрасывается. Опрос продолжается, если шёл.
     */
    fun переключитьСервер(ид: String) {
        if (!настройки.выбратьСервер(ид)) return
        перезапуститьОпрос(журналировать = true)
    }

    /** Перечитывает профиль активного сервера (после правки или удаления соседей). */
    fun обновитьСервер() = перезапуститьОпрос()

    private fun перезапуститьОпрос(журналировать: Boolean = false) {
        // Пустой снимок нового сервера показываем сразу: иначе на экранах
        // несколько секунд висели бы числа прежнего.
        _снимок.value = Снимок(
            запущено = _снимок.value.запущено,
            серверId = настройки.активныйId,
            имяПрофиля = настройки.имяПрофиля(),
        )
        область.launch { сброситьСостояние(журналировать) }
    }

    /**
     * Останавливает текущий опрос, закрывает SSH-сеанс и пересобирает состояние.
     * Дожидается конца текущего цикла: он может держать открытый сеанс и ещё не
     * дописанную строку истории, а писать её уже в базу другого сервера нельзя.
     */
    private suspend fun сброситьСостояние(журналировать: Boolean = false) {
        val былЗапущен = задание?.isActive == true || _снимок.value.запущено
        флагПаузы.set(false)
        стоп.set(true)
        val прежнее = задание
        задание = null
        прежнее?.cancelAndJoin()
        сервер?.закрыть()
        сервер = null
        ключСервера = null
        кэшПодробностей = Подробности()
        очередьСлужб.clear()
        очередьIp.clear()
        доступностьЦелей.clear()
        состоянияСлужб.clear()
        флагиПорогов.clear()
        времяПоследнегоСобытияБ = null
        сетьПросела = false
        обслуживаниеПросело = false
        идётОпрос = 0
        следующийСервер = 0L
        следующиеПодробности = 0L
        следующиеСайты = 0L
        следующиеПорты = 0L
        следующиеСлужбы = 0L
        следующаяБезопасность = 0L
        следующаяСеть = 0L
        следующаяОбслуживание = 0L
        следующаяИстория = 0L
        стоп.set(false)
        применитьНастройки()
        _снимок.value = Снимок(
            запущено = былЗапущен,
            серверId = настройки.активныйId,
            имяПрофиля = настройки.имяПрофиля(),
        )
        if (былЗапущен) запустить() else опубликоватьСостояние()
        if (журналировать) записатьВЖурнал(л("Активный сервер: {1}", настройки.подпись()))
    }

    /** Подменяет историю и техжурнал, если активный сервер сменился. */
    private fun сменитьФайлы() {
        val новоеИмя = настройки.файлИстории()
        if (новоеИмя != имяФайлаИстории) {
            историяТекущая.закрыть()
            историяТекущая = фабрикаИстории(новоеИмя)
            имяФайлаИстории = новоеИмя
        }
        файлЖурнала = File(настройки.каталог, настройки.файлЖурнала())
        идДанных = настройки.активныйId
    }

    /**
     * Обновляет снимок, проставляя в нём сервер, чьи данные собраны: интерфейс
     * по этим полям понимает, что показывает, и не смешивает серверы.
     */
    private fun обновитьСнимок(правка: (Снимок) -> Снимок) {
        _снимок.update { снимок ->
            правка(снимок).copy(серверId = идДанных, имяПрофиля = настройки.имяПрофиля(идДанных))
        }
    }

    /** Проверяет подключение по текущим настройкам, не трогая рабочий сеанс. */
    suspend fun проверитьПодключение(): Pair<Boolean, String> =
        проверитьПодключение(параметрыСервера(настройки))

    /** Проверяет подключение по переданным значениям — так работает мастер настройки. */
    suspend fun проверитьПодключение(проверяемые: ПараметрыСервера): Pair<Boolean, String> =
        withContext(Dispatchers.IO) {
            val тестовый = LinuxServer(проверяемые)
            try {
                тестовый.проверитьПодключение()
            } finally {
                тестовый.закрыть()
            }
        }

    fun обновитьСобытия() {
        val события = try {
            история.события(200)
        } catch (_: Exception) {
            return
        }
        обновитьСнимок { it.copy(события = события) }
    }

    /**
     * Удаляет все записи журнала событий из базы и обнуляет окно.
     * Возвращает число удалённых записей.
     */
    fun обнулитьЖурнал(): Int {
        val удалено = try {
            история.обнулитьСобытия()
        } catch (ошибка: Exception) {
            записатьВЖурнал(л("Не удалось обнулить журнал событий: {1}", "${ошибка.message}"))
            return 0
        }
        обновитьСнимок { it.copy(события = emptyList()) }
        записатьВЖурнал(л("Журнал событий обнулён: удалено записей — {1}", удалено))
        return удалено
    }

    /** Обнуляет техжурнал: чистит окно в памяти и файл на диске. */
    fun очиститьТехжурнал() {
        обновитьСнимок { it.copy(техжурнал = emptyList()) }
        try {
            файлЖурнала.writeText("")
        } catch (_: Exception) {
            // журнал на диске — вспомогательный, его сбой не должен мешать опросу
        }
    }

    fun записатьВЖурнал(сообщение: String) {
        val строка = "[${полнаяДата(System.currentTimeMillis() / 1000)}] $сообщение"
        обновитьСнимок { it.copy(техжурнал = (it.техжурнал + строка).takeLast(МАКСИМУМ_СТРОК_ТЕХЖУРНАЛА)) }
        try {
            if (файлЖурнала.length() > ПРЕДЕЛ_ФАЙЛА_ЖУРНАЛА) {
                val хвост = файлЖурнала.readLines().takeLast(1000)
                файлЖурнала.writeText(хвост.joinToString("\n") + "\n")
            }
            файлЖурнала.appendText("$строка\n")
        } catch (_: Exception) {
            // журнал на диске — вспомогательный, его сбой не должен мешать опросу
        }
    }

    // --- основной цикл ---------------------------------------------------

    private suspend fun цикл() {
        записатьВЖурнал(л("Опрос запущен"))
        while (true) {
            try {
                if (флагПаузы.get()) {
                    опубликоватьСостояние()
                    delay(500)
                    continue
                }
                val срочно = флагНемедленно.get()
                if (очередьСлужб.isNotEmpty()) выполнитьДействияСлужб()
                if (очередьIp.isNotEmpty()) выполнитьДействияIp()
                if (срочно || сейчас() >= следующийСервер) собратьМетрики()
                if (срочно || сейчас() >= следующиеСайты) проверитьГруппу("http")
                if (срочно || сейчас() >= следующиеПорты) проверитьГруппу("tcp")
                if (срочно || сейчас() >= следующиеСлужбы) опроситьСлужбы()
                if (срочно || сейчас() >= следующаяБезопасность) собратьБезопасность()
                if (срочно || сейчас() >= следующаяСеть) собратьСеть()
                if (срочно || сейчас() >= следующаяОбслуживание) собратьОбслуживание()
                if (срочно || сейчас() >= следующаяИстория) отправитьИсторию()
                if (сейчас() >= следующаяОчистка) почиститьИсторию()
                флагНемедленно.set(false)
                опубликоватьСостояние()
            } catch (отмена: CancellationException) {
                throw отмена
            } catch (ошибка: Exception) {
                записатьВЖурнал(л("Сбой в цикле опроса: {1}", "${ошибка.message}"))
                оповещения.записатьБезОповещения(
                    УРОВЕНЬ_СБОЙ,
                    л("Приложение"),
                    л("Сбой в опросе: {1}", "${ошибка.message}"),
                )
            }
            delay(500)
        }
    }

    private fun сейчас(): Long = System.currentTimeMillis()

    private fun секунды(значение: Double): Long = (значение * 1000).toLong()

    // --- метрики Linux-сервера -------------------------------------------

    private fun собратьМетрики() {
        val настройкиСервера = настройки.сервер
        следующийСервер = сейчас() + секунды(интервалСервера)
        if (!настройки.да(настройкиСервера, "включен", true)) {
            обновитьСнимок {
                it.copy(связь = false, текстСвязи = л("Опрос Linux-сервера выключен в настройках"), задержкаМс = null)
            }
            return
        }
        if (!настройки.настроен()) {
            // Пока адрес и логин не заданы, сервер не опрашиваем: иначе журнал
            // каждые пять секунд заполнялся бы одной и той же ошибкой связи.
            обновитьСнимок {
                it.copy(связь = null, текстСвязи = ТЕКСТ_НЕ_НАСТРОЕНО, задержкаМс = null)
            }
            return
        }

        val соединение = серверИлиСоздать()
        val нужныПодробности = сейчас() >= следующиеПодробности

        опросНачало()
        val начало = сейчас()
        val метрики: Метрики
        try {
            try {
                var снятые = соединение.снятьБыстро()
                if (нужныПодробности) {
                    кэшПодробностей = соединение.снятьПодробно()
                    следующиеПодробности = сейчас() + секунды(интервалПодробностей)
                }
                снятые = снятые.слить(кэшПодробностей)
                метрики = снятые
            } catch (ошибка: ОшибкаСвязи) {
                следующийСервер = сейчас() + ПОВТОР_ПРИ_СБОЕ_МС
                val текст = ошибка.message ?: л("Не удалось подключиться")
                настройки.отметитьПодключение(настройки.активныйId, false, текст)
                обновитьСнимок { it.copy(связь = false, текстСвязи = текст, задержкаМс = null) }
                оповещения.событие(УРОВЕНЬ_СБОЙ, л("Сервер"), л("Нет связи с сервером по SSH: {1}", текст))
                return
            } catch (ошибка: Exception) {
                следующийСервер = сейчас() + ПОВТОР_ПРИ_СБОЕ_МС
                записатьВЖурнал(л("Ошибка сбора метрик: {1}", "${ошибка.message}"))
                обновитьСнимок {
                    it.copy(связь = false, текстСвязи = л("Ошибка опроса: {1}", "${ошибка.message}"), задержкаМс = null)
                }
                return
            }
        } finally {
            опросКонец()
        }

        val задержка = сейчас() - начало
        настройки.отметитьПодключение(настройки.активныйId, true)
        обновитьСнимок {
            it.copy(
                связь = true,
                текстСвязи = л("Связь с сервером есть"),
                задержкаМс = задержка,
                метрики = метрики,
                последнийОпрос = System.currentTimeMillis() / 1000,
                имяСервера = метрики.хост.ifBlank { параметрыСервера(настройки).хост },
            )
        }
        try {
            история.добавитьМетрики(метрики)
        } catch (ошибка: Exception) {
            записатьВЖурнал(л("Не удалось сохранить метрики: {1}", "${ошибка.message}"))
        }
        проверитьПороги(метрики)
    }

    private fun проверитьПороги(метрики: Метрики) {
        val пороги = настройки.сервер.optJSONObject("пороги_предупреждений") ?: JSONObject()
        val правила = listOf(
            Triple("цп_процент", метрики.цп, л("Загрузка процессора")),
            Triple("озу_процент", метрики.озуПроцент, л("Занятая память")),
            Triple("диск_процент", метрики.дискПроцент, л("Занятое место на диске")),
        )
        for ((ключ, значение, описание) in правила) {
            if (значение == null || !пороги.has(ключ)) continue
            val порог = пороги.optDouble(ключ, 0.0)
            if (порог <= 0.0) continue
            val выше = значение >= порог
            val прежнее = флагиПорогов[ключ]
            флагиПорогов[ключ] = выше
            if (прежнее == выше) continue
            when {
                выше -> оповещения.событие(
                    УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ,
                    л("Сервер"),
                    л("{1} достигла {2}% (порог {3}%)", описание, ноль(значение), ноль(порог)),
                )
                прежнее == true -> оповещения.событие(
                    УРОВЕНЬ_УСПЕХ,
                    л("Сервер"),
                    л("{1} вернулась в норму: {2}%", описание, ноль(значение)),
                )
            }
        }
    }

    private fun ноль(значение: Double): String = String.format(Locale.ROOT, "%.0f", значение)

    // --- сайты и порты ---------------------------------------------------

    private fun цели(вид: String): List<JSONObject> = if (вид == "http") {
        настройки.сайты().filter { настройки.да(it, "включен", true) }
    } else {
        настройки.порты().filter { настройки.да(it, "включен", true) }
    }

    private suspend fun проверитьГруппу(вид: String) {
        val список = цели(вид)
        if (вид == "http") {
            следующиеСайты = сейчас() + секунды(интервалСайтов)
        } else {
            следующиеПорты = сейчас() + секунды(интервалПортов)
        }
        if (список.isEmpty()) {
            обновитьСтатистику()
            return
        }

        опросНачало()
        try {
            coroutineScope {
                val задачи = список.map { цель ->
                    async(Dispatchers.IO) {
                        try {
                            if (вид == "http") проверитьСайт(сайтИзJson(цель, настройки.коды(цель)))
                            else проверитьПорт(портИзJson(цель))
                        } catch (ошибка: Exception) {
                            РезультатПроверки(
                                время = System.currentTimeMillis() / 1000,
                                имя = цель.optString("имя").ifBlank { л("без имени") },
                                вид = вид,
                                адрес = "",
                                доступно = false,
                                ошибка = л("Внутренняя ошибка проверки: {1}", "${ошибка.message}"),
                            )
                        }
                    }
                }
                for (задача in задачи) обработатьПроверку(задача.await())
            }
        } finally {
            опросКонец()
        }
        обновитьСтатистику()
    }

    private fun обработатьПроверку(результат: РезультатПроверки) {
        val имя = результат.имя
        val доступно = результат.доступно
        val прежнее = доступностьЦелей[имя]
        доступностьЦелей[имя] = доступно
        try {
            история.добавитьПроверку(результат)
        } catch (ошибка: Exception) {
            записатьВЖурнал(л("Не удалось сохранить проверку «{1}»: {2}", имя, "${ошибка.message}"))
        }
        обновитьСнимок { снимок ->
            val полная = снимок.историяПроверок[имя].orEmpty()
            снимок.copy(
                проверки = снимок.проверки + (имя to результат),
                историяПроверок = снимок.историяПроверок + (имя to (полная + результат).takeLast(24)),
            )
        }
        if (прежнее != null && прежнее != доступно) {
            val причина = результат.ошибка
                ?: if (результат.код != null) л("код ответа {1}", результат.код) else л("нет ответа")
            if (доступно) {
                оповещения.событие(УРОВЕНЬ_УСПЕХ, имя, л("Работа восстановлена"))
            } else {
                оповещения.событие(УРОВЕНЬ_СБОЙ, имя, л("Цель недоступна — {1}", причина))
            }
        }
    }

    private fun обновитьСтатистику() {
        val итог = mutableMapOf<String, СтатистикаПроверки>()
        val суткиНазад = System.currentTimeMillis() / 1000 - 86400
        for (имя in доступностьЦелей.keys.toList()) {
            try {
                val (доступность, всего) = история.доступность(имя, суткиНазад)
                val (среднее, максимум) = история.статистикаЗадержек(имя, суткиНазад)
                итог[имя] = СтатистикаПроверки(доступность, всего, среднее, максимум)
            } catch (_: Exception) {
                // если база недоступна — статистика просто не обновится
            }
        }
        обновитьСнимок { it.copy(статистика = итог) }
    }

    // --- службы ----------------------------------------------------------

    private suspend fun опроситьСлужбы() {
        следующиеСлужбы = сейчас() + секунды(интервалСлужб)
        val настройкиСервера = настройки.сервер
        val units = настройки.службы()
        if (units.isEmpty() || !настройки.настроен() || !настройки.да(настройкиСервера, "включен", true)) {
            обновитьСнимок { it.copy(службы = emptyList()) }
            return
        }
        val соединение = серверИлиСоздать()
        val службы = try {
            соединение.службы(units)
        } catch (ошибка: ОшибкаСвязи) {
            записатьВЖурнал(л("Не удалось получить состояние служб: {1}", "${ошибка.message}"))
            return
        }
        сравнитьСлужбы(службы)
        обновитьСнимок { it.copy(службы = службы) }
    }

    private fun сравнитьСлужбы(службы: List<Служба>) {
        for (служба in службы) {
            val имя = служба.имя
            val работает = служба.работает
            val прежнее = состоянияСлужб[имя]
            состоянияСлужб[имя] = работает
            if (прежнее == null || прежнее == работает) continue
            val описание = служба.описание.ifBlank { имя }
            if (работает) {
                оповещения.событие(УРОВЕНЬ_УСПЕХ, имя, л("Служба запущена ({1})", описание))
            } else {
                val состояние = служба.состояниеТекст.ifBlank { л("неизвестно") }
                оповещения.событие(
                    УРОВЕНЬ_СБОЙ,
                    имя,
                    л("Служба не работает: {1} ({2})", состояние, описание),
                )
            }
        }
    }

    private suspend fun выполнитьДействияСлужб() {
        val задания = mutableListOf<Pair<String, String>>()
        while (true) {
            val задание = очередьСлужб.poll() ?: break
            задания.add(задание)
        }
        if (задания.isEmpty()) return
        if (!настройки.настроен()) {
            _сообщения.tryEmit(л("Сначала настройте сервер в мастере настройки"))
            return
        }
        val соединение = серверИлиСоздать()

        for ((имя, действие) in задания) {
            обновитьСнимок { it.copy(действиеИдёт = имя) }
            val (получилось, сообщение) = when (действие) {
                "start" -> соединение.запуститьСлужбу(имя)
                "stop" -> соединение.остановитьСлужбу(имя)
                else -> соединение.перезапуститьСлужбу(имя)
            }
            _сообщения.tryEmit(сообщение)
            val текст = действиеСлужбы[действие]?.second ?: л("Действие выполнено.")
            оповещения.событие(
                if (получилось) УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ else УРОВЕНЬ_СБОЙ,
                имя,
                if (получилось) "$текст $сообщение" else л("Не удалось выполнить действие: {1}", сообщение),
            )
        }
        обновитьСнимок { it.copy(действиеИдёт = null) }

        delay(1000)
        val службы = try {
            соединение.службы(настройки.службы())
        } catch (_: ОшибкаСвязи) {
            return
        }
        службы.forEach { состоянияСлужб[it.имя] = it.работает }
        обновитьСнимок { it.copy(службы = службы) }
    }

    // --- безопасность: fail2ban + блокировка IP ---------------------------

    private suspend fun собратьБезопасность() {
        следующаяБезопасность = сейчас() + секунды(интервалБезопасности)
        if (!настройки.настроен() || !настройки.да(настройки.сервер, "включен", true)) return
        val соединение = серверИлиСоздать()

        опросНачало()
        val данные: Безопасность
        try {
            данные = try {
                соединение.собратьБезопасность()
            } catch (ошибка: ОшибкаСвязи) {
                следующаяБезопасность = сейчас() + ПОВТОР_ПРИ_СБОЕ_МС
                записатьВЖурнал(л("Не удалось получить данные безопасности: {1}", "${ошибка.message}"))
                return
            } catch (ошибка: Exception) {
                следующаяБезопасность = сейчас() + ПОВТОР_ПРИ_СБОЕ_МС
                записатьВЖурнал(л("Ошибка сбора данных безопасности: {1}", "${ошибка.message}"))
                return
            }
        } finally {
            опросКонец()
        }

        обработатьСобытияБезопасности(данные)
        обновитьСнимок { it.copy(безопасность = данные) }
    }

    /**
     * Оповещает только о НОВЫХ банах с момента прошлого опроса — при первом
     * запуске просто запоминает точку отсчёта, не спамя всей историей
     * fail2ban.log (там могут быть десятки старых банов).
     */
    private fun обработатьСобытияБезопасности(данные: Безопасность) {
        val события = данные.события
        val прежнееВремя = времяПоследнегоСобытияБ
        if (прежнееВремя == null) {
            времяПоследнегоСобытияБ = события.maxOfOrNull { it.время } ?: 0L
            return
        }
        val новые = события.filter { it.время > прежнееВремя }
        if (новые.isEmpty()) return
        времяПоследнегоСобытияБ = новые.maxOf { it.время }
        for (событие in новые.sortedBy { it.время }) {
            if (событие.действие == "ban") {
                оповещения.событие(
                    УРОВЕНЬ_СБОЙ,
                    событие.ip,
                    л(
                        "fail2ban заблокировал подозрительный IP {1} (jail «{2}») — похоже на подбор пароля/атаку",
                        событие.ip,
                        событие.jail,
                    ),
                )
            } else {
                оповещения.записатьБезОповещения(
                    "сведения",
                    событие.ip,
                    л("fail2ban снял временную блокировку с {1} (jail «{2}»)", событие.ip, событие.jail),
                )
            }
        }
    }

    // --- диагностика сети: TCP и UDP --------------------------------------

    /**
     * Снимает счётчики TCP/UDP, состояния сокетов и параметры ядра, оценивает
     * их и сообщает о просадке. Опрос идёт реже остальных (по умолчанию раз в
     * 30 с): счётчики накопительные, чаще снимать их смысла нет.
     */
    private suspend fun собратьСеть() {
        следующаяСеть = сейчас() + секунды(интервалСети)
        if (!настройки.настроен() || !настройки.да(настройки.сервер, "включен", true)) return
        val соединение = серверИлиСоздать()

        опросНачало()
        val данные: ДиагностикаСети
        try {
            данные = try {
                соединение.собратьСеть()
            } catch (ошибка: ОшибкаСвязи) {
                следующаяСеть = сейчас() + ПОВТОР_ПРИ_СБОЕ_МС
                записатьВЖурнал(л("Не удалось получить диагностику сети: {1}", "${ошибка.message}"))
                return
            } catch (ошибка: Exception) {
                следующаяСеть = сейчас() + ПОВТОР_ПРИ_СБОЕ_МС
                записатьВЖурнал(л("Ошибка диагностики сети: {1}", "${ошибка.message}"))
                return
            }
        } finally {
            опросКонец()
        }

        val оценка = оценитьСеть(данные)
        оповеститьОСети(оценка)
        обновитьСнимок { it.copy(сеть = данные, оценкаСети = оценка) }
    }

    /** Оповещает о просадке оценки сети и о её восстановлении. */
    private fun оповеститьОСети(оценка: ОценкаСети) {
        if (оценка.балл < 50 && !сетьПросела) {
            сетьПросела = true
            val главная = оценка.рекомендации.firstOrNull { it.важная } ?: оценка.рекомендации.firstOrNull()
            val хвост = главная?.let { л(". Главное: {1}", it.заголовок) } ?: ""
            оповещения.событие(
                УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ,
                л("Сеть"),
                л(
                    "Состояние сети ухудшилось: оценка {1} из 100 ({2})",
                    оценка.балл,
                    л(оценка.уровень),
                ) + хвост,
            )
        } else if (оценка.балл >= 75 && сетьПросела) {
            сетьПросела = false
            оповещения.событие(
                УРОВЕНЬ_УСПЕХ,
                л("Сеть"),
                л("Состояние сети восстановилось: оценка {1} из 100 ({2})", оценка.балл, л(оценка.уровень)),
            )
        }
    }

    /** Немедленный опрос диагностики сети — кнопка «Обновить сейчас» на вкладке. */
    fun обновитьСетьСейчас() {
        следующаяСеть = 0L
        проверитьСейчас()
    }

    // --- обслуживание сервера ---------------------------------------------

    /**
     * Проводит аудит обслуживания: обновления, сбойные службы, журналы, время,
     * диски и SMART. Опрос идёт редко (по умолчанию раз в 10 минут) — эти
     * данные меняются медленно, а часть команд заметно нагружает сервер.
     */
    private suspend fun собратьОбслуживание() {
        следующаяОбслуживание = сейчас() + секунды(интервалОбслуживания)
        if (!настройки.настроен() || !настройки.да(настройки.сервер, "включен", true)) return
        val соединение = серверИлиСоздать()

        опросНачало()
        val данные: Обслуживание
        try {
            данные = try {
                соединение.собратьОбслуживание()
            } catch (ошибка: ОшибкаСвязи) {
                следующаяОбслуживание = сейчас() + ПОВТОР_ПРИ_СБОЕ_МС
                записатьВЖурнал(л("Не удалось получить данные обслуживания: {1}", "${ошибка.message}"))
                return
            } catch (ошибка: Exception) {
                следующаяОбслуживание = сейчас() + ПОВТОР_ПРИ_СБОЕ_МС
                записатьВЖурнал(л("Ошибка аудита обслуживания: {1}", "${ошибка.message}"))
                return
            }
        } finally {
            опросКонец()
        }

        val оценка = оценитьОбслуживание(данные)
        оповеститьОбОбслуживании(оценка)
        обновитьСнимок { it.copy(обслуживание = данные, оценкаОбслуживания = оценка) }
    }

    /** Оповещает о том, что сервер требует внимания, и о возврате в норму. */
    private fun оповеститьОбОбслуживании(оценка: ОценкаОбслуживания) {
        if (оценка.балл < 70 && !обслуживаниеПросело) {
            обслуживаниеПросело = true
            val главная = оценка.рекомендации.firstOrNull { it.важная } ?: оценка.рекомендации.firstOrNull()
            val хвост = главная?.let { л(". Главное: {1}", it.заголовок) } ?: ""
            оповещения.событие(
                УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ,
                л("Обслуживание"),
                л(
                    "Сервер требует внимания: оценка обслуживания {1} из 100 ({2})",
                    оценка.балл,
                    л(оценка.уровень),
                ) + хвост,
            )
        } else if (оценка.балл >= 85 && обслуживаниеПросело) {
            обслуживаниеПросело = false
            оповещения.событие(
                УРОВЕНЬ_УСПЕХ,
                л("Обслуживание"),
                л(
                    "Обслуживание сервера снова в норме: оценка {1} из 100 ({2})",
                    оценка.балл,
                    л(оценка.уровень),
                ),
            )
        }
    }

    /** Немедленный аудит обслуживания — кнопка «Обновить сейчас» на вкладке. */
    fun обновитьОбслуживаниеСейчас() {
        следующаяОбслуживание = 0L
        проверитьСейчас()
    }

    private suspend fun выполнитьДействияIp() {
        val задания = mutableListOf<Pair<String, String>>()
        while (true) {
            val задание = очередьIp.poll() ?: break
            задания.add(задание)
        }
        if (задания.isEmpty()) return
        val соединение = серверИлиСоздать()

        for ((ip, действие) in задания) {
            обновитьСнимок { it.copy(действиеИдёт = ip) }
            val (получилось, сообщение) = if (действие == "ban") {
                соединение.заблокироватьIp(ip)
            } else {
                соединение.разблокироватьIp(ip)
            }
            _сообщения.tryEmit(сообщение)
            оповещения.событие(if (получилось) УРОВЕНЬ_ПРЕДУПРЕЖДЕНИЕ else УРОВЕНЬ_СБОЙ, ip, сообщение)
        }
        обновитьСнимок { it.copy(действиеИдёт = null) }
        следующаяБезопасность = 0L
    }

    // --- история ---------------------------------------------------------

    private fun отправитьИсторию() {
        следующаяИстория = сейчас() + maxOf(20_000L, секунды(интервалСервера))
        val начало = System.currentTimeMillis() / 1000 - ОКНО_ИСТОРИИ_СЕКУНД
        try {
            val точки = история.историяГрафика(начало, предел = 4000, максимумТочек = МАКСИМУМ_ТОЧЕК_ГРАФИКА)
            val проверки = доступностьЦелей.keys.toList().associateWith { история.историяПроверок(it, начало) }
            val события = история.события(200)
            val размер = история.размерБайт()
            обновитьСнимок {
                it.copy(историяГрафика = точки, историяПроверок = проверки, события = события, размерБд = размер)
            }
        } catch (ошибка: Exception) {
            записатьВЖурнал(л("Не удалось прочитать историю: {1}", "${ошибка.message}"))
        }
    }

    private fun почиститьИсторию() {
        следующаяОчистка = сейчас() + 6 * 3_600_000
        try {
            val дней = настройки.числоСервера("хранить_дней", 14.0)
            история.очистить(дней)
        } catch (ошибка: Exception) {
            записатьВЖурнал(л("Не удалось почистить историю: {1}", "${ошибка.message}"))
        }
    }

    // --- служебное -------------------------------------------------------

    private fun серверИлиСоздать(): LinuxServer {
        val настройкиСервера = параметрыСервера(настройки)
        val ключ = listOf(настройкиСервера.хост, настройкиСервера.порт.toString(), настройкиСервера.пользователь, настройкиСервера.пароль, настройкиСервера.файлКлюча)
        сервер?.let { if (ключСервера == ключ) return it }
        сервер?.закрыть()
        val новый = LinuxServer(настройкиСервера) { сообщение -> записатьВЖурнал(сообщение) }
        сервер = новый
        ключСервера = ключ
        кэшПодробностей = Подробности()
        return новый
    }

    private fun опросНачало() {
        идётОпрос += 1
        опубликоватьСостояние()
    }

    private fun опросКонец() {
        идётОпрос = maxOf(0, идётОпрос - 1)
        опубликоватьСостояние()
    }

    private fun опубликоватьСостояние() {
        val ближайший = minOf(следующийСервер, следующиеСайты, следующиеПорты)
        val остаток = ((ближайший - сейчас()).coerceAtLeast(0)) / 1000
        обновитьСнимок {
            it.copy(
                пауза = флагПаузы.get(),
                опросИдёт = идётОпрос > 0,
                доСледующегоОпроса = остаток,
                запущено = !стоп.get(),
            )
        }
    }

    fun закрыть() {
        остановить()
        область.cancel()
    }
}


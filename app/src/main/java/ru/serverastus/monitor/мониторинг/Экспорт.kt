package ru.serverastus.monitor.мониторинг

import ru.serverastus.monitor.данные.Локаль
import ru.serverastus.monitor.данные.времяТекст
import ru.serverastus.monitor.данные.л
import java.io.File
import java.io.FileOutputStream
import java.io.OutputStreamWriter
import java.math.BigDecimal

/** Что получилось при выгрузке истории в CSV. */
data class РезультатЭкспорта(
    val папка: File,
    val строкМетрик: Int,
    val строкПроверок: Int,
    val файлы: List<File>,
)

/**
 * Выгружает историю в CSV — те же файлы и формат, что в настольном
 * приложении (`desktop/app.py`, `_записать_csv_метрик`/`_записать_csv_проверок`):
 * разделитель «;», кодировка UTF-8 с BOM (чтобы Excel видел русский текст).
 * Заголовки и тексты ошибок пишутся на языке интерфейса.
 */
fun экспортCsv(история: История, каталог: File): РезультатЭкспорта {
    val папка = File(каталог, "экспорт").apply { mkdirs() }
    val файлМетрик = File(папка, "метрики.csv")
    val файлПроверок = File(папка, "проверки.csv")

    val строкМетрик = записатьМетрики(история, файлМетрик)
    val строкПроверок = записатьПроверки(история, файлПроверок)

    return РезультатЭкспорта(папка, строкМетрик, строкПроверок, listOf(файлМетрик, файлПроверок))
}

private fun записатьМетрики(история: История, файл: File): Int {
    val метрики = история.метрикиЗаписи()
    открытьПисатель(файл).use { писатель ->
        писатель.строка(
            listOf(
                л("Время"), л("ЦП, %"), л("ОЗУ занято, байт"), л("ОЗУ всего, байт"),
                л("Диск занято, байт"), л("Диск всего, байт"), л("Нагрузка 1 мин"),
                л("Процессов"), л("Аптайм, с"),
            ),
        )
        for (запись in метрики) {
            писатель.строка(
                listOf(
                    времяТекст(запись.время),
                    число(запись.цп),
                    число(запись.озуЗанято),
                    число(запись.озуВсего),
                    число(запись.дискЗанято),
                    число(запись.дискВсего),
                    число(запись.нагрузка1),
                    число(запись.процессов),
                    число(запись.аптайм),
                ),
            )
        }
    }
    return метрики.size
}

private fun записатьПроверки(история: История, файл: File): Int {
    var всего = 0
    открытьПисатель(файл).use { писатель ->
        писатель.строка(
            listOf(
                л("Время"), л("Имя"), л("Вид"), л("Адрес"), л("Доступно"), л("Код"),
                л("Время, мс"), л("SSL, дней"), л("Ошибка"),
            ),
        )
        for (имя in история.имена()) {
            for (запись in история.историяПроверок(имя, 0L, предел = 200000)) {
                писатель.строка(
                    listOf(
                        времяТекст(запись.время),
                        запись.имя,
                        запись.вид,
                        запись.адрес,
                        if (запись.доступно) л("да") else л("нет"),
                        число(запись.код),
                        число(запись.времяМс),
                        число(запись.sslДней),
                        запись.ошибка?.let { Локаль.перевестиГотовый(it) } ?: "",
                    ),
                )
                всего += 1
            }
        }
    }
    return всего
}

private fun открытьПисатель(файл: File): OutputStreamWriter {
    val поток = OutputStreamWriter(FileOutputStream(файл), Charsets.UTF_8)
    // BOM в начале файла — признак UTF-8 для Excel (utf-8-sig в Python).
    поток.write("\uFEFF")
    return поток
}

private fun OutputStreamWriter.строка(поля: List<String>) {
    write(поля.joinToString(";") { поле -> кодироватьПоле(поле) })
    write("\r\n")
}

/** Экранирование как у csv.writer с delimiter=";". */
private fun кодироватьПоле(значение: String): String {
    val нужно = значение.any { it == ';' || it == '"' || it == '\n' || it == '\r' }
    if (!нужно) return значение
    return "\"" + значение.replace("\"", "\"\"") + "\""
}

/** Числа пишутся как в Python: 42 — целое, 42.0 — дробное, пустое значение — пусто. */
private fun число(значение: Number?): String {
    if (значение == null) return ""
    if (значение is Int || значение is Long || значение is Short || значение is Byte) {
        return значение.toString()
    }
    val дробное = значение.toDouble()
    if (дробное.isNaN() || дробное.isInfinite()) return ""
    val точно = BigDecimal(дробное).stripTrailingZeros()
    return if (точно.scale() <= 0) точно.setScale(1).toPlainString() else точно.toPlainString()
}
